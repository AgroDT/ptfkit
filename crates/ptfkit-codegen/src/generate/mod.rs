mod python;
mod rust;
mod rust_core;

use std::{
    collections::BTreeSet,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use anyhow::{Context, Result, bail};

use crate::model::{CompiledFunction, CoreFunction, Entry, Output, PythonGeneration};

pub(crate) const GENERATED_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n";
pub(crate) const RUST_HEADER: &str = "// @generated by ptfkit-codegen; DO NOT EDIT.\n";

struct StagedWrite {
    target: PathBuf,
    temporary: PathBuf,
}

pub(crate) fn run(root: &Path, entries: Vec<Entry>) -> Result<()> {
    let compiled = compile_targets(entries)?;
    let core_writes = rust_core::render(&compiled)?
        .into_iter()
        .map(|(relative, contents)| (root.join("crates/ptfkit-core/src").join(relative), contents))
        .collect::<Vec<_>>();
    for (path, _) in &core_writes {
        refuse_unmarked_rust_target(path)?;
    }
    let rust_writes = rust::render(&compiled)?
        .into_iter()
        .map(|(relative, contents)| {
            (
                root.join("crates/ptfkit-py/src/ufunc").join(relative),
                contents,
            )
        })
        .collect::<Vec<_>>();
    let rust_paths = rust_writes
        .iter()
        .map(|(path, _)| path.clone())
        .collect::<Vec<_>>();
    let rust_write_count = core_writes.len() + rust_writes.len();
    let mut writes = core_writes;
    writes.extend(rust_writes);
    let mut python_paths = Vec::new();
    for (module, mode, contents) in python::render(&compiled)? {
        if mode == PythonGeneration::Manual {
            println!("skipped manual Python module {module}");
            continue;
        }
        let path = root
            .join("crates/ptfkit-py/python")
            .join(module.replace('.', "/") + ".py");
        refuse_unmarked_python_target(&path)?;
        python_paths.push(path.clone());
        writes.push((path, contents));
    }
    let core_stub = root.join("crates/ptfkit-py/python/ptfkit/_core.pyi");
    python_paths.push(core_stub.clone());
    writes.push((core_stub, python::render_core_stub(&compiled)));

    let expected_rust_paths = rust_paths.iter().cloned().collect();
    let expected_python_paths = python_paths.iter().cloned().collect();
    remove_obsolete_generated(
        &root.join("crates/ptfkit-py/src/ufunc/generated"),
        &expected_rust_paths,
        RUST_HEADER,
    )?;
    let expected_core_paths = writes[..rust_write_count]
        .iter()
        .filter_map(|(path, _)| {
            path.starts_with(root.join("crates/ptfkit-core/src"))
                .then_some(path.clone())
        })
        .collect();
    remove_obsolete_generated(
        &root.join("crates/ptfkit-core/src"),
        &expected_core_paths,
        RUST_HEADER,
    )?;
    remove_obsolete_generated(
        &root.join("crates/ptfkit-py/python/ptfkit"),
        &expected_python_paths,
        GENERATED_HEADER,
    )?;
    let staged = stage_writes(writes)?;
    let rust_temporary_paths = staged[..rust_write_count]
        .iter()
        .map(|write| write.temporary.clone())
        .collect::<Vec<_>>();
    let python_temporary_paths = staged[rust_write_count..]
        .iter()
        .map(|write| write.temporary.clone())
        .collect::<Vec<_>>();
    if let Err(error) =
        rustfmt(&rust_temporary_paths).and_then(|()| ruff(root, &python_temporary_paths))
    {
        cleanup_staged(&staged);
        return Err(error);
    }
    for (index, write) in staged.iter().enumerate() {
        if let Err(error) = commit_staged_file(write) {
            cleanup_staged(&staged[index..]);
            return Err(error);
        }
    }
    remove_obsolete_generated_file(
        &root.join("crates/ptfkit-py/src/ufunc/generated.rs"),
        RUST_HEADER,
    )?;
    Ok(())
}

fn refuse_unmarked_python_target(path: &Path) -> Result<()> {
    if path.exists()
        && fs::read_to_string(path)?.lines().next() != Some(GENERATED_HEADER.trim_end())
    {
        bail!(
            "refusing to overwrite {}:\nthe file is not marked as generated",
            path.display()
        );
    }
    Ok(())
}

fn refuse_unmarked_rust_target(path: &Path) -> Result<()> {
    if path.exists() && !is_generated_rust_target(&fs::read_to_string(path)?) {
        bail!(
            "refusing to overwrite {}:\nthe file is not marked as generated",
            path.display()
        );
    }
    Ok(())
}

fn is_generated_rust_target(contents: &str) -> bool {
    contents.lines().next() == Some(RUST_HEADER.trim_end())
        || contents.lines().next() == Some("//! @generated by ptfkit-codegen; DO NOT EDIT.")
        || (contents.starts_with("#![doc")
            && contents.contains("@generated by ptfkit-codegen; DO NOT EDIT."))
}

fn stage_writes(writes: Vec<(PathBuf, String)>) -> Result<Vec<StagedWrite>> {
    let mut staged = Vec::with_capacity(writes.len());
    for (target, content) in writes {
        if let Err(error) = fs::create_dir_all(target.parent().expect("output path has a parent")) {
            cleanup_staged(&staged);
            return Err(error.into());
        }
        let temporary = temporary_path(&target);
        if let Err(error) = fs::write(&temporary, content) {
            cleanup_staged(&staged);
            return Err(error.into());
        }
        staged.push(StagedWrite { target, temporary });
    }
    Ok(staged)
}

fn temporary_path(target: &Path) -> PathBuf {
    let extension = target
        .extension()
        .and_then(|extension| extension.to_str())
        .unwrap_or_default();
    target.with_extension(format!("ptfkit-codegen.{extension}"))
}

fn commit_staged_file(write: &StagedWrite) -> Result<bool> {
    let formatted = fs::read_to_string(&write.temporary)?;
    let existing = fs::read(&write.target).ok();
    let output = normalize_line_endings(&formatted);

    if existing.as_deref() == Some(output.as_bytes()) {
        fs::remove_file(&write.temporary)?;
        return Ok(false);
    }

    fs::write(&write.temporary, output)?;
    fs::rename(&write.temporary, &write.target)?;
    Ok(true)
}

fn normalize_line_endings(content: &str) -> String {
    content.replace("\r\n", "\n").replace('\r', "\n")
}

fn cleanup_staged(staged: &[StagedWrite]) {
    for write in staged {
        let _ = fs::remove_file(&write.temporary);
    }
}

fn remove_obsolete_generated(
    directory: &Path,
    expected: &BTreeSet<PathBuf>,
    header: &str,
) -> Result<()> {
    if !directory.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(directory)? {
        let path = entry?.path();
        if path.is_dir() {
            remove_obsolete_generated(&path, expected, header)?;
        } else if !expected.contains(&path) {
            remove_obsolete_generated_file(&path, header)?;
        }
    }
    Ok(())
}

fn remove_obsolete_generated_file(path: &Path, header: &str) -> Result<()> {
    if path.is_file() && fs::read(path)?.starts_with(header.as_bytes()) {
        fs::remove_file(path)?;
    }
    Ok(())
}

fn ruff(root: &Path, paths: &[PathBuf]) -> Result<()> {
    if paths.is_empty() {
        return Ok(());
    }
    let output = Command::new("uv")
        .args(["run", "--no-sync", "ruff", "format"])
        .args(paths)
        .current_dir(root.join("crates/ptfkit-py"))
        .output()
        .context("running Ruff on generated Python")?;
    if !output.status.success() {
        bail!(
            "Ruff failed while formatting generated Python:\n{}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(())
}

fn rustfmt(paths: &[PathBuf]) -> Result<()> {
    let output = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .args(paths)
        .output()
        .context("running rustfmt on generated Rust")?;
    if !output.status.success() {
        bail!(
            "rustfmt failed while formatting generated Rust:\n{}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    for path in paths {
        let source = fs::read_to_string(path)?;
        fs::write(path, separate_item_attributes(&source))?;
    }
    Ok(())
}

fn separate_item_attributes(source: &str) -> String {
    source.replace("}\n#[", "}\n\n#[")
}

fn compile_targets(entries: Vec<Entry>) -> Result<Vec<CompiledFunction>> {
    let mut compiled = Vec::new();
    for entry in entries {
        for (function_index, function) in entry.spec.functions.iter().enumerate() {
            if matches!(
                function.status.as_str(),
                "implemented" | "ready-for-implementation"
            ) {
                let ir = entry.implementations[function_index]
                    .clone()
                    .expect("semantic validation requires an implementation for generated code");
                compiled.push(CompiledFunction {
                    entry: entry.clone(),
                    function_index,
                    ir,
                    core: CoreFunction {
                        name: function.name.clone(),
                        inputs: function
                            .inputs
                            .iter()
                            .map(|input| input.name.clone())
                            .collect(),
                        output: match function.result_class() {
                            Some(_) => Output::Struct(
                                function
                                    .outputs
                                    .fields()
                                    .iter()
                                    .map(|output| output.name.clone())
                                    .collect(),
                            ),
                            None => Output::Scalar,
                        },
                    },
                });
            }
        }
    }
    Ok(compiled)
}

#[cfg(test)]
mod tests {
    use std::{
        collections::BTreeSet,
        fs,
        path::{Path, PathBuf},
    };

    use super::{
        GENERATED_HEADER, StagedWrite, commit_staged_file, compile_targets, python,
        refuse_unmarked_python_target, remove_obsolete_generated, rust, rust_core,
        separate_item_attributes,
    };
    #[test]
    fn cleanup_only_removes_obsolete_marked_files() {
        let directory = std::env::temp_dir().join(format!(
            "ptfkit-codegen-cleanup-{}-{}",
            std::process::id(),
            line!()
        ));
        fs::create_dir_all(&directory).unwrap();
        let obsolete = directory.join("obsolete.py");
        let current = directory.join("current.py");
        let manual = directory.join("manual.py");
        fs::write(&obsolete, format!("{GENERATED_HEADER}obsolete\n")).unwrap();
        fs::write(&current, format!("{GENERATED_HEADER}current\n")).unwrap();
        fs::write(&manual, "manual\n").unwrap();

        remove_obsolete_generated(
            &directory,
            &BTreeSet::from([current.clone()]),
            GENERATED_HEADER,
        )
        .unwrap();

        assert!(!obsolete.exists());
        assert!(current.exists());
        assert!(manual.exists());
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn every_code_generating_function_reaches_each_retained_target() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let entries = crate::specs::load(&root).unwrap();
        let expected = entries
            .iter()
            .flat_map(|entry| {
                entry
                    .spec
                    .functions
                    .iter()
                    .map(move |function| (entry, function))
            })
            .filter(|(_, function)| {
                matches!(
                    function.status.as_str(),
                    "implemented" | "ready-for-implementation"
                )
            })
            .collect::<Vec<_>>();
        let compiled = compile_targets(entries.clone()).unwrap();

        assert_eq!(compiled.len(), expected.len());
        let core = rust_core::render(&compiled).unwrap();
        let ufuncs = rust::render(&compiled).unwrap();
        let wrappers = python::render(&compiled).unwrap();
        for (entry, function) in expected {
            assert!(
                core.iter()
                    .any(|(path, _)| path == &PathBuf::from(format!("{}.rs", entry.slug)))
            );
            let ufunc = ufuncs
                .iter()
                .find(|(path, _)| path == &PathBuf::from(format!("generated/{}.rs", entry.slug)))
                .unwrap();
            assert!(!ufunc.1.contains("ptfkit_core"));
            let wrapper = wrappers
                .iter()
                .find(|(module, _, _)| module == &format!("ptfkit.{}", entry.slug))
                .unwrap();
            assert_eq!(wrapper.1, entry.spec.generation.public_python);
            assert!(wrapper.2.contains(&function.public_api.name));
        }
    }

    #[test]
    fn unmarked_python_target_is_not_overwritten() {
        let directory = std::env::temp_dir().join(format!(
            "ptfkit-codegen-ownership-{}-{}",
            std::process::id(),
            line!()
        ));
        fs::create_dir_all(&directory).unwrap();
        let target = directory.join("manual.py");
        fs::write(&target, "def calc_ptf_manual():\n    pass\n").unwrap();

        let error = refuse_unmarked_python_target(&target).unwrap_err();

        assert!(error.to_string().contains("not marked as generated"));
        assert_eq!(
            fs::read_to_string(&target).unwrap(),
            "def calc_ptf_manual():\n    pass\n"
        );
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn unchanged_lf_content_is_not_replaced() {
        let directory = std::env::temp_dir().join(format!(
            "ptfkit-codegen-eol-{}-{}",
            std::process::id(),
            line!()
        ));
        fs::create_dir_all(&directory).unwrap();
        let target = directory.join("generated.py");
        let temporary = directory.join("generated.ptfkit-codegen.py");
        let original = b"first\nsecond\n";
        fs::write(&target, original).unwrap();
        fs::write(&temporary, b"first\r\nsecond\r\n").unwrap();

        let changed = commit_staged_file(&StagedWrite {
            target: target.clone(),
            temporary: temporary.clone(),
        })
        .unwrap();

        assert!(!changed);
        assert_eq!(fs::read(&target).unwrap(), original);
        assert!(!temporary.exists());
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn existing_crlf_content_is_normalized_to_lf() {
        let directory = std::env::temp_dir().join(format!(
            "ptfkit-codegen-eol-{}-{}",
            std::process::id(),
            line!()
        ));
        fs::create_dir_all(&directory).unwrap();
        let target = directory.join("generated.rs");
        let temporary = directory.join("generated.ptfkit-codegen.rs");
        fs::write(&target, b"first\r\nsecond\r\n").unwrap();
        fs::write(&temporary, b"first\r\nsecond\r\n").unwrap();

        let changed = commit_staged_file(&StagedWrite {
            target: target.clone(),
            temporary: temporary.clone(),
        })
        .unwrap();

        assert!(changed);
        assert_eq!(fs::read(&target).unwrap(), b"first\nsecond\n");
        assert!(!temporary.exists());
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn separates_generated_items_from_following_attributes() {
        assert_eq!(
            separate_item_attributes("pub struct Result {}\n#[must_use]\npub fn calculate() {}\n"),
            "pub struct Result {}\n\n#[must_use]\npub fn calculate() {}\n"
        );
    }
}
