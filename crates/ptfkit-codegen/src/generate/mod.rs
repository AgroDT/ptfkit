mod python;
mod rust;

use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use anyhow::{Context, Result, bail};

use crate::{
    core,
    model::{CoreFunction, Entry, Output, PythonGeneration, Resolved},
    validate,
};

pub(crate) const GENERATED_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n";
pub(crate) const RUST_HEADER: &str = "//! @generated by ptfkit-codegen; DO NOT EDIT.\n";

pub(crate) fn run(root: &Path, entries: Vec<Entry>) -> Result<()> {
    let resolved = resolve(
        entries,
        core::discover(&root.join("crates/ptfkit-core/src/lib.rs"))?,
    )?;
    let rust_writes = rust::render(&resolved)?
        .into_iter()
        .map(|(relative, contents)| {
            (
                root.join("crates/ptfkit-py/src/ufunc").join(relative),
                contents,
            )
        })
        .collect::<Vec<_>>();
    let rust_paths = rust_writes
        .iter()
        .map(|(path, _)| path.clone())
        .collect::<Vec<_>>();
    let mut writes = rust_writes;
    let mut python_paths = Vec::new();
    for (module, mode, contents) in python::render(&resolved)? {
        if mode == PythonGeneration::Manual {
            println!("skipped manual Python module {module}");
            continue;
        }
        let path = root
            .join("crates/ptfkit-py/python")
            .join(module.replace('.', "/") + ".py");
        if path.exists()
            && fs::read_to_string(&path)?.lines().next() != Some(GENERATED_HEADER.trim_end())
        {
            bail!(
                "refusing to overwrite {}:\nthe file is not marked as generated",
                path.display()
            );
        }
        python_paths.push(path.clone());
        writes.push((path, contents));
    }
    let core_stub = root.join("crates/ptfkit-py/python/ptfkit/_core.pyi");
    python_paths.push(core_stub.clone());
    writes.push((core_stub, python::render_core_stub(&resolved)));

    let expected_rust_paths = rust_paths.iter().cloned().collect();
    let expected_python_paths = python_paths.iter().cloned().collect();
    remove_obsolete_generated(
        &root.join("crates/ptfkit-py/src/ufunc/generated"),
        &expected_rust_paths,
        RUST_HEADER,
    )?;
    remove_obsolete_generated(
        &root.join("crates/ptfkit-py/python/ptfkit"),
        &expected_python_paths,
        GENERATED_HEADER,
    )?;
    for (path, content) in writes {
        if fs::read_to_string(&path).ok().as_deref() != Some(&content) {
            fs::create_dir_all(path.parent().expect("output path has a parent"))?;
            let temporary = path.with_extension("tmp");
            fs::write(&temporary, content)?;
            fs::rename(temporary, path)?;
        }
    }
    rustfmt(&rust_paths)?;
    ruff(root, &python_paths)?;
    remove_obsolete_generated_file(
        &root.join("crates/ptfkit-py/src/ufunc/generated.rs"),
        RUST_HEADER,
    )?;
    Ok(())
}

fn remove_obsolete_generated(
    directory: &Path,
    expected: &BTreeSet<PathBuf>,
    header: &str,
) -> Result<()> {
    if !directory.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(directory)? {
        let path = entry?.path();
        if path.is_dir() {
            remove_obsolete_generated(&path, expected, header)?;
        } else if !expected.contains(&path) {
            remove_obsolete_generated_file(&path, header)?;
        }
    }
    Ok(())
}

fn remove_obsolete_generated_file(path: &Path, header: &str) -> Result<()> {
    if path.is_file() && fs::read(path)?.starts_with(header.as_bytes()) {
        fs::remove_file(path)?;
    }
    Ok(())
}

fn ruff(root: &Path, paths: &[PathBuf]) -> Result<()> {
    if paths.is_empty() {
        return Ok(());
    }
    let output = Command::new("uv")
        .args(["run", "--no-sync", "ruff", "format"])
        .args(paths)
        .current_dir(root.join("crates/ptfkit-py"))
        .output()
        .context("running Ruff on generated Python")?;
    if !output.status.success() {
        bail!(
            "Ruff failed while formatting generated Python:\n{}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(())
}

fn rustfmt(paths: &[PathBuf]) -> Result<()> {
    let output = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .args(paths)
        .output()
        .context("running rustfmt on generated Rust")?;
    if !output.status.success() {
        bail!(
            "rustfmt failed while formatting generated Rust:\n{}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(())
}

fn resolve(entries: Vec<Entry>, core: Vec<CoreFunction>) -> Result<Vec<Resolved>> {
    let mut specs = BTreeMap::new();
    for entry in &entries {
        for (index, function) in entry.spec.functions.iter().enumerate() {
            if function.status == "implemented" || function.status == "ready-for-implementation" {
                specs.insert(function.name.clone(), (entry.clone(), index));
            }
        }
    }
    let mut resolved = Vec::new();
    let mut errors = Vec::new();
    for function in core {
        let Some((entry, index)) = specs.remove(&function.name) else {
            errors.push(format!(
                "core function `{}` has no specification entry",
                function.name
            ));
            continue;
        };
        let spec = &entry.spec.functions[index];
        let inputs: Vec<_> = spec.inputs.iter().map(|input| &input.name).collect();
        if inputs != function.inputs.iter().collect::<Vec<_>>() {
            errors.push(validate::diag(
                &entry,
                "inputs",
                Some(&function.name),
                &format!(
                    "Rust arguments {:?} do not match specification {:?}",
                    function.inputs, inputs
                ),
            ));
        }
        match (
            &function.output,
            spec.outputs.len(),
            spec.public_api.result_class.is_some(),
        ) {
            (Output::Scalar, 1, false) => {}
            (Output::Struct(fields), count, true)
                if fields
                    == &spec
                        .outputs
                        .iter()
                        .map(|output| output.name.clone())
                        .collect::<Vec<_>>()
                    && count == fields.len() => {}
            (Output::Scalar, _, _) => errors.push(validate::diag(
                &entry,
                "outputs",
                Some(&function.name),
                "a scalar Rust result requires one output and null result_class",
            )),
            (Output::Struct(fields), _, _) => errors.push(validate::diag(
                &entry,
                "outputs",
                Some(&function.name),
                &format!("Rust result fields {fields:?} do not match specification output names"),
            )),
        }
        resolved.push(Resolved {
            entry,
            function_index: index,
            core: function,
        });
    }
    for (name, (entry, index)) in &specs {
        if entry.spec.functions[*index].status == "implemented" {
            errors.push(format!(
                "specification function `{name}` has no implemented calc_ptf_* core function"
            ));
        }
    }
    if !errors.is_empty() {
        bail!("core/specification matching failed:\n{}", errors.join("\n"))
    }
    Ok(resolved)
}

#[cfg(test)]
mod tests {
    use std::{collections::BTreeSet, fs, path::PathBuf};

    use super::{GENERATED_HEADER, remove_obsolete_generated, resolve};
    use crate::model::{
        CoreFunction, Documentation, Entry, Function, FunctionScope, Models, Output, PublicApi,
        PythonGeneration, Scope, Source, Spec,
    };

    fn entry(name: &str, status: &str) -> Entry {
        Entry {
            path: PathBuf::from("test.md"),
            spec: Spec {
                source: Source {
                    key: "test".into(),
                    summary: "Test source.".into(),
                    citation_apa: "Test (2026).".into(),
                    doi: None,
                },
                scope: Scope::default(),
                python_generation: PythonGeneration::Generated,
                functions: vec![Function {
                    name: name.into(),
                    status: status.into(),
                    public_api: PublicApi {
                        name: name.into(),
                        result_class: None,
                        summary: "Test function.".into(),
                    },
                    scope: FunctionScope {
                        territory: None,
                        prediction_target: "Test value.".into(),
                        models: Models::default(),
                    },
                    inputs: Vec::new(),
                    outputs: vec![crate::model::Parameter {
                        name: "value".into(),
                        unit: "1".into(),
                        domain: None,
                        description: "Test value.".into(),
                    }],
                    documentation: Documentation::default(),
                }],
            },
            section_functions: vec![name.into()],
        }
    }

    fn core(name: &str) -> CoreFunction {
        CoreFunction {
            name: name.into(),
            module: vec!["test".into()],
            inputs: Vec::new(),
            output: Output::Scalar,
        }
    }

    #[test]
    fn ready_function_without_core_is_valid() {
        assert!(
            resolve(
                vec![entry("calc_ptf_test", "ready-for-implementation")],
                vec![]
            )
            .is_ok()
        );
    }

    #[test]
    fn ready_function_with_core_is_resolved() {
        let resolved = resolve(
            vec![entry("calc_ptf_test", "ready-for-implementation")],
            vec![core("calc_ptf_test")],
        )
        .unwrap();
        assert_eq!(resolved.len(), 1);
    }

    #[test]
    fn implemented_function_without_core_is_rejected() {
        let error = resolve(vec![entry("calc_ptf_test", "implemented")], vec![])
            .err()
            .unwrap();
        assert!(
            error
                .to_string()
                .contains("has no implemented calc_ptf_* core function")
        );
    }

    #[test]
    fn cleanup_only_removes_obsolete_marked_files() {
        let directory = std::env::temp_dir().join(format!(
            "ptfkit-codegen-cleanup-{}-{}",
            std::process::id(),
            line!()
        ));
        fs::create_dir_all(&directory).unwrap();
        let obsolete = directory.join("obsolete.py");
        let current = directory.join("current.py");
        let manual = directory.join("manual.py");
        fs::write(&obsolete, format!("{GENERATED_HEADER}obsolete\n")).unwrap();
        fs::write(&current, format!("{GENERATED_HEADER}current\n")).unwrap();
        fs::write(&manual, "manual\n").unwrap();

        remove_obsolete_generated(
            &directory,
            &BTreeSet::from([current.clone()]),
            GENERATED_HEADER,
        )
        .unwrap();

        assert!(!obsolete.exists());
        assert!(current.exists());
        assert!(manual.exists());
        fs::remove_dir_all(directory).unwrap();
    }
}
