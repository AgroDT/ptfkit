mod python;
mod rust;

use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use anyhow::{Context, Result, bail};

use crate::{
    core,
    model::{CoreFunction, Entry, Output, PythonGeneration, Resolved},
    validate,
};

pub(crate) const GENERATED_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n";
pub(crate) const RUST_HEADER: &str = "//! @generated by ptfkit-codegen; DO NOT EDIT.\n";

pub(crate) fn run(root: &Path, entries: Vec<Entry>) -> Result<()> {
    let resolved = resolve(
        entries,
        core::discover(&root.join("crates/ptfkit-core/src/lib.rs"))?,
    )?;
    let rust_writes = rust::render(&resolved)?
        .into_iter()
        .map(|(relative, contents)| {
            (
                root.join("crates/ptfkit-py/src/ufunc").join(relative),
                contents,
            )
        })
        .collect::<Vec<_>>();
    let rust_paths = rust_writes
        .iter()
        .map(|(path, _)| path.clone())
        .collect::<Vec<_>>();
    let mut writes = rust_writes;
    let mut python_paths = Vec::new();
    for (module, mode, contents) in python::render(&resolved)? {
        if mode == PythonGeneration::Manual {
            println!("skipped manual Python module {module}");
            continue;
        }
        let path = root
            .join("crates/ptfkit-py/python")
            .join(module.replace('.', "/") + ".py");
        if path.exists()
            && fs::read_to_string(&path)?.lines().next() != Some(GENERATED_HEADER.trim_end())
        {
            bail!(
                "refusing to overwrite {}:\nthe file is not marked as generated",
                path.display()
            );
        }
        python_paths.push(path.clone());
        writes.push((path, contents));
    }
    for (path, content) in writes {
        if fs::read_to_string(&path).ok().as_deref() != Some(&content) {
            fs::create_dir_all(path.parent().expect("output path has a parent"))?;
            let temporary = path.with_extension("tmp");
            fs::write(&temporary, content)?;
            fs::rename(temporary, path)?;
        }
    }
    rustfmt(&rust_paths)?;
    ruff(root, &python_paths)?;
    let legacy = root.join("crates/ptfkit-py/src/ufunc/generated.rs");
    if legacy.is_file() {
        fs::remove_file(legacy)?;
    }
    Ok(())
}

fn ruff(root: &Path, paths: &[PathBuf]) -> Result<()> {
    if paths.is_empty() {
        return Ok(());
    }
    let output = Command::new("uv")
        .args(["run", "--no-sync", "ruff", "format"])
        .args(paths)
        .current_dir(root.join("crates/ptfkit-py"))
        .output()
        .context("running Ruff on generated Python")?;
    if !output.status.success() {
        bail!(
            "Ruff failed while formatting generated Python:\n{}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(())
}

fn rustfmt(paths: &[PathBuf]) -> Result<()> {
    let output = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .args(paths)
        .output()
        .context("running rustfmt on generated Rust")?;
    if !output.status.success() {
        bail!(
            "rustfmt failed while formatting generated Rust:\n{}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(())
}

fn resolve(entries: Vec<Entry>, core: Vec<CoreFunction>) -> Result<Vec<Resolved>> {
    let mut specs = BTreeMap::new();
    for entry in &entries {
        for (index, function) in entry.spec.functions.iter().enumerate() {
            if function.status == "implemented" || function.status == "ready-for-implementation" {
                specs.insert(function.name.clone(), (entry.clone(), index));
            }
        }
    }
    let mut resolved = Vec::new();
    let mut errors = Vec::new();
    for function in core {
        let Some((entry, index)) = specs.remove(&function.name) else {
            errors.push(format!(
                "core function `{}` has no specification entry",
                function.name
            ));
            continue;
        };
        let spec = &entry.spec.functions[index];
        let inputs: Vec<_> = spec.inputs.iter().map(|input| &input.name).collect();
        if inputs != function.inputs.iter().collect::<Vec<_>>() {
            errors.push(validate::diag(
                &entry,
                "inputs",
                Some(&function.name),
                &format!(
                    "Rust arguments {:?} do not match specification {:?}",
                    function.inputs, inputs
                ),
            ));
        }
        match (
            &function.output,
            spec.outputs.len(),
            spec.public_api.result_class.is_some(),
        ) {
            (Output::Scalar, 1, false) => {}
            (Output::Struct(fields), count, true)
                if fields
                    == &spec
                        .outputs
                        .iter()
                        .map(|output| output.name.clone())
                        .collect::<Vec<_>>()
                    && count == fields.len() => {}
            (Output::Scalar, _, _) => errors.push(validate::diag(
                &entry,
                "outputs",
                Some(&function.name),
                "a scalar Rust result requires one output and null result_class",
            )),
            (Output::Struct(fields), _, _) => errors.push(validate::diag(
                &entry,
                "outputs",
                Some(&function.name),
                &format!("Rust result fields {fields:?} do not match specification output names"),
            )),
        }
        resolved.push(Resolved {
            entry,
            function_index: index,
            core: function,
        });
    }
    for name in specs.keys() {
        errors.push(format!(
            "specification function `{name}` has no implemented calc_ptf_* core function"
        ));
    }
    if !errors.is_empty() {
        bail!("core/specification matching failed:\n{}", errors.join("\n"))
    }
    Ok(resolved)
}
