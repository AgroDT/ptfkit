mod extension;
mod stub;
mod syntax;
mod test;
mod wrapper;

use crate::model::CompiledFunction;

use crate::output::GeneratedFile;

pub(super) const C_HEADER: &str = "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n";
pub(super) const WRAPPER_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n";

pub(super) struct Output {
    pub(super) extension: Vec<GeneratedFile>,
    pub(super) wrappers: Vec<GeneratedFile>,
    pub(super) tests: Vec<GeneratedFile>,
}

pub(super) fn render(
    functions: &[CompiledFunction],
    usda_texture: &crate::usda_texture::Specification,
) -> anyhow::Result<Output> {
    Ok(Output {
        extension: extension::render(functions)?,
        wrappers: {
            let mut wrappers = wrapper::render(functions)?;
            wrappers.push(GeneratedFile::new(
                "ptfkit/_ptfkit.pyi".into(),
                stub::render(functions),
            ));
            wrappers.push(crate::usda_texture::render_module(usda_texture));
            wrappers
        },
        tests: {
            let mut tests = test::render(functions);
            tests.push(crate::usda_texture::render_tests(usda_texture));
            tests
        },
    })
}

pub(crate) fn natural_sort_key(value: &str) -> String {
    let mut key = String::new();
    let mut digits = String::new();
    for character in value.chars() {
        if character.is_ascii_digit() {
            digits.push(character);
        } else {
            if !digits.is_empty() {
                key.push_str(&format!("{digits:0>20}"));
                digits.clear();
            }
            key.push(character);
        }
    }
    if !digits.is_empty() {
        key.push_str(&format!("{digits:0>20}"));
    }
    key
}
