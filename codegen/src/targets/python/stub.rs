use crate::model::CompiledFunction;

use super::{WRAPPER_HEADER, syntax::Module};

pub(super) fn render(functions: &[CompiledFunction]) -> String {
    let mut names = functions
        .iter()
        .map(|function| function.core.name.as_str())
        .collect::<Vec<_>>();
    names.sort_unstable();

    let mut module = Module::new(WRAPPER_HEADER);
    module.blank_line();
    module.import("numpy", "ufunc");
    module.blank_line();
    for name in names {
        module.line(format_args!("{name}: ufunc"));
    }
    module.into_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn declares_every_native_ufunc_in_sorted_order() {
        let mut functions = crate::test_support::functions();
        functions.reverse();
        assert_eq!(
            render(&functions),
            "# @generated by ptfkit-codegen; DO NOT EDIT.\n\nfrom numpy import ufunc\n\ncalc_ptf_example10_record: ufunc\ncalc_ptf_example10_scalar: ufunc\ncalc_ptf_example2_record: ufunc\ncalc_ptf_example2_scalar: ufunc\n"
        );
    }
}
