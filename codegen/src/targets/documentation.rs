use std::path::PathBuf;

use crate::model::{Entry, Function, Parameter};

pub(super) const HEADER: &str = "<!-- @generated by ptfkit-codegen; DO NOT EDIT. -->\n\n";
pub(super) const FRONTMATTER_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n\n";

pub(super) fn parameter_details(parameter: &Parameter) -> String {
    format!("{} ({})", parameter.description, parameter.unit)
}

pub(super) fn parameter_documentation(parameter: &Parameter) -> String {
    format!("{}: {}", parameter.name, parameter_details(parameter))
}

pub(super) fn render(entries: &[Entry]) -> Vec<super::GeneratedFile> {
    let mut files = vec![super::GeneratedFile::new(
        PathBuf::from("index.md"),
        format!("{}\n", render_index(entries).trim_end()),
    )];
    for entry in entries {
        files.push(super::GeneratedFile::new(
            PathBuf::from(format!("{}.md", entry.slug)),
            format!("{}\n", render_source(entry).trim_end()),
        ));
    }
    files
}

fn render_index(entries: &[Entry]) -> String {
    let mut text = format!("---\n{FRONTMATTER_HEADER}title: PTF Sources\n---\n\n");
    text.push_str("# PTF Sources\n\n");
    text.push_str(
        "Each page describes the source, scope, inputs, outputs, status, and limitations of the \
         functions defined by one specification.\n\n",
    );
    text.push_str("| Source | Territory | Functions |\n| --- | --- | ---: |\n");
    for entry in entries {
        let spec = &entry.spec;
        let territory = spec.scope.territory.as_deref().unwrap_or("—");
        text.push_str(&format!(
            "| [{}](./{}.md) | {} | {} |\n",
            escape_table(&spec.source.summary),
            entry.slug,
            escape_table(territory),
            spec.functions.len(),
        ));
    }
    text
}

fn render_source(entry: &Entry) -> String {
    let spec = &entry.spec;
    let mut text = format!(
        "---\n{FRONTMATTER_HEADER}title: PTF source {slug}\nnav-title: {slug}\n---\n\n",
        slug = entry.slug
    );
    text.push_str(&format!("# {}\n\n", spec.source.summary));
    text.push_str("## Source\n\n");
    text.push_str(&spec.source.citation_apa);
    text.push_str("\n\n");
    if let Some(doi) = &spec.source.doi {
        text.push_str(&format!("[DOI: {}]({})\n\n", doi.identifier, doi.url));
    }
    if spec.scope.territory.is_some() || spec.scope.dataset.is_some() {
        text.push_str("## Scope\n\n");
        if let Some(territory) = &spec.scope.territory {
            text.push_str(&format!("**Territory:** {territory}\n\n"));
        }
        if let Some(dataset) = &spec.scope.dataset {
            text.push_str(&format!("**Dataset:** {dataset}\n\n"));
        }
    }
    text.push_str("## Functions\n\n");
    for function in &spec.functions {
        render_function(&mut text, function);
    }
    text
}

fn render_function(text: &mut String, function: &Function) {
    text.push_str(&format!("### `{}`\n\n", function.public_api.name));
    text.push_str(&function.public_api.summary);
    text.push_str("\n\n");
    text.push_str(&format!("**Status:** `{}`\n\n", function.status));
    text.push_str(&format!(
        "**Prediction target:** {}\n\n",
        function.scope.prediction_target
    ));

    let models = [
        function
            .scope
            .models
            .h_theta
            .as_ref()
            .map(|model| format!("$h(\\theta)$ — {model}")),
        function
            .scope
            .models
            .k_h
            .as_ref()
            .map(|model| format!("$k(h)$ — {model}")),
    ]
    .into_iter()
    .flatten()
    .collect::<Vec<_>>();
    if !models.is_empty() {
        text.push_str(&format!("**Models:** {}\n\n", models.join("; ")));
    }

    render_parameters(text, "Inputs", &function.inputs);
    render_parameters(text, "Outputs", function.outputs.fields());
    for note in &function.documentation.notes {
        render_admonition(text, "note", note);
    }
    for warning in &function.documentation.warnings {
        render_admonition(text, "warning", warning);
    }
}

fn render_parameters(text: &mut String, title: &str, parameters: &[Parameter]) {
    text.push_str(&format!("#### {title}\n\n"));
    text.push_str("| Name | Unit | Domain | Description |\n| --- | --- | --- | --- |\n");
    for parameter in parameters {
        text.push_str(&format!(
            "| `{}` | {} | {} | {} |\n",
            parameter.name,
            escape_table(&parameter.unit),
            parameter
                .domain
                .as_deref()
                .map(escape_table)
                .unwrap_or_else(|| "—".into()),
            escape_table(&parameter.description),
        ));
    }
    text.push('\n');
}

fn render_admonition(text: &mut String, kind: &str, body: &str) {
    text.push_str(&format!("!!! {kind}\n\n"));
    for line in body.lines() {
        text.push_str(&format!("    {line}\n"));
    }
    text.push('\n');
}

fn escape_table(value: &str) -> String {
    value.replace('\n', " ").replace('|', "\\|")
}
