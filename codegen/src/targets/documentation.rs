use std::path::PathBuf;

use crate::{
    documentation::{self as docs, FunctionDocument},
    model::{Entry, Parameter},
    render::{Render, Writer},
};

pub(super) const HEADER: &str = "<!-- @generated by ptfkit-codegen; DO NOT EDIT. -->\n\n";
pub(super) const FRONTMATTER_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n\n";

pub(super) fn parameter_details(parameter: &Parameter) -> String {
    format!("{} ({})", parameter.description, parameter.unit)
}

pub(super) fn parameter_documentation(parameter: &Parameter) -> String {
    format!("{}: {}", parameter.name, parameter_details(parameter))
}

pub(super) fn markdown_file(
    path: impl Into<PathBuf>,
    render: impl FnOnce(&mut Writer),
) -> super::GeneratedFile {
    let mut writer = Writer::new();
    render(&mut writer);
    super::GeneratedFile::new(path.into(), markdown_contents(writer))
}

pub(super) fn markdown_contents(writer: Writer) -> String {
    let contents = writer.into_string();
    format!("{}\n", contents.trim_end())
}

pub(super) fn frontmatter(writer: &mut Writer, render: impl FnOnce(&mut Writer)) {
    writer.line("---");
    render(writer);
    writer.line("---");
    writer.blank_line();
}

pub(super) fn generated_frontmatter(writer: &mut Writer, render: impl FnOnce(&mut Writer)) {
    frontmatter(writer, |writer| {
        writer.write(FRONTMATTER_HEADER);
        render(writer);
    });
}

pub(super) fn code_block(writer: &mut Writer, language: &str, render: impl FnOnce(&mut Writer)) {
    writer.line(format_args!("```{language}"));
    render(writer);
    writer.line("```");
    writer.blank_line();
}

pub(super) fn admonition(
    writer: &mut Writer,
    kind: &str,
    body: &str,
    render_line: impl Fn(&str) -> String,
) {
    writer.line(format_args!("!!! {kind}"));
    writer.blank_line();
    writer.indented(|writer| {
        for line in body.lines() {
            writer.line(render_line(line));
        }
    });
    writer.blank_line();
}

pub(super) fn render(entries: &[Entry]) -> Vec<super::GeneratedFile> {
    let mut files = vec![markdown_file("index.md", |writer| {
        IndexPage { entries }.render(writer);
    })];
    for entry in entries {
        files.push(markdown_file(format!("{}.md", entry.slug), |writer| {
            SourcePage { entry }.render(writer);
        }));
    }
    files
}

struct IndexPage<'a> {
    entries: &'a [Entry],
}

impl Render for IndexPage<'_> {
    fn render(&self, writer: &mut Writer) {
        generated_frontmatter(writer, |writer| writer.line("title: PTF Sources"));
        writer.line("# PTF Sources");
        writer.blank_line();
        writer.line(
            "Each page describes the source, scope, inputs, outputs, status, and limitations of the functions defined by one specification.",
        );
        writer.blank_line();
        writer.line("| Source | Territory | Functions |");
        writer.line("| --- | --- | ---: |");
        for entry in self.entries {
            let source = docs::for_source(&entry.spec.source, &entry.spec.scope);
            let territory = source.territory.unwrap_or("\u{2014}");
            writer.line(format_args!(
                "| [{}](./{}.md) | {} | {} |",
                escape_table(source.summary),
                entry.slug,
                escape_table(territory),
                entry.spec.functions.len(),
            ));
        }
    }
}

struct SourcePage<'a> {
    entry: &'a Entry,
}

impl Render for SourcePage<'_> {
    fn render(&self, writer: &mut Writer) {
        let spec = &self.entry.spec;
        let source = docs::for_source(&spec.source, &spec.scope);
        generated_frontmatter(writer, |writer| {
            writer.line(format_args!("title: PTF source {}", self.entry.slug));
            writer.line(format_args!("nav-title: {}", self.entry.slug));
        });
        writer.line(format_args!("# {}", source.summary));
        writer.blank_line();
        writer.line("## Source");
        writer.blank_line();
        writer.line(source.reference.citation);
        writer.blank_line();
        if let Some(doi) = source.reference.doi {
            writer.line(format_args!("[DOI: {}]({})", doi.identifier, doi.url));
            writer.blank_line();
        }
        if source.territory.is_some() || source.dataset.is_some() {
            writer.line("## Scope");
            writer.blank_line();
            if let Some(territory) = source.territory {
                writer.line(format_args!("**Territory:** {territory}"));
                writer.blank_line();
            }
            if let Some(dataset) = source.dataset {
                writer.line(format_args!("**Dataset:** {dataset}"));
                writer.blank_line();
            }
        }
        writer.line("## Functions");
        writer.blank_line();
        for function in &spec.functions {
            FunctionSection {
                document: docs::for_function(function),
                name: &function.public_api.name,
                status: &function.status,
            }
            .render(writer);
        }
    }
}

struct FunctionSection<'a> {
    document: FunctionDocument<'a>,
    name: &'a str,
    status: &'a str,
}

impl Render for FunctionSection<'_> {
    fn render(&self, writer: &mut Writer) {
        writer.line(format_args!("### `{}`", self.name));
        writer.blank_line();
        writer.line(self.document.summary);
        writer.blank_line();
        writer.line(format_args!("**Status:** `{}`", self.status));
        writer.blank_line();
        writer.line(format_args!(
            "**Prediction target:** {}",
            self.document.remarks.prediction_target
        ));
        writer.blank_line();

        if self.document.models.h_theta.is_some() || self.document.models.k_h.is_some() {
            writer.write("**Models:** ");
            if let Some(model) = self.document.models.h_theta {
                writer.write(format_args!("$h(\\theta)$ \u{2014} {model}"));
                if self.document.models.k_h.is_some() {
                    writer.write("; ");
                }
            }
            if let Some(model) = self.document.models.k_h {
                writer.write(format_args!("$k(h)$ \u{2014} {model}"));
            }
            writer.blank_line();
        }

        ParameterTable {
            title: "Inputs",
            parameters: self.document.parameters,
        }
        .render(writer);
        ParameterTable {
            title: "Outputs",
            parameters: match self.document.returns {
                docs::Returns::Scalar(field) => std::slice::from_ref(field),
                docs::Returns::Record { fields, .. } => fields,
            },
        }
        .render(writer);
        for note in self.document.notes {
            Admonition {
                kind: "note",
                body: note,
            }
            .render(writer);
        }
        for warning in self.document.warnings {
            Admonition {
                kind: "warning",
                body: warning,
            }
            .render(writer);
        }
    }
}

struct ParameterTable<'a> {
    title: &'a str,
    parameters: &'a [Parameter],
}

impl Render for ParameterTable<'_> {
    fn render(&self, writer: &mut Writer) {
        writer.line(format_args!("#### {}", self.title));
        writer.blank_line();
        writer.line("| Name | Unit | Domain | Description |");
        writer.line("| --- | --- | --- | --- |");
        for parameter in self.parameters {
            writer.line(format_args!(
                "| `{}` | {} | {} | {} |",
                parameter.name,
                escape_table(&parameter.unit),
                parameter
                    .domain
                    .as_deref()
                    .map(escape_table)
                    .unwrap_or_else(|| "\u{2014}".into()),
                escape_table(&parameter.description),
            ));
        }
        writer.blank_line();
    }
}

struct Admonition<'a> {
    kind: &'a str,
    body: &'a str,
}

impl Render for Admonition<'_> {
    fn render(&self, writer: &mut Writer) {
        admonition(writer, self.kind, self.body, str::to_owned);
    }
}

fn escape_table(value: &str) -> String {
    value.replace('\n', " ").replace('|', "\\|")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_admonitions_with_writer_indentation() {
        let mut writer = Writer::new();
        Admonition {
            kind: "note",
            body: "first\nsecond",
        }
        .render(&mut writer);

        assert_eq!(
            writer.into_string(),
            "!!! note\n\n    first\n    second\n\n"
        );
    }

    #[test]
    fn renders_generated_frontmatter_with_the_existing_spacing() {
        let file = markdown_file("test.md", |writer| {
            generated_frontmatter(writer, |writer| writer.line("title: Test"));
            writer.line("# Test");
        });

        assert_eq!(
            file.contents,
            "---\n# @generated by ptfkit-codegen; DO NOT EDIT.\n\ntitle: Test\n---\n\n# Test\n"
        );
    }
}
