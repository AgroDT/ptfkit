pub(super) const HEADER: &str = "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n";

pub(super) struct OutputFiles {
    pub(super) c_headers: Vec<GeneratedFile>,
    pub(super) cpp_modules: Vec<GeneratedFile>,
    pub(super) c_tests: Vec<GeneratedFile>,
    pub(super) cpp_tests: Vec<GeneratedFile>,
}

#[cfg(test)]
pub(super) fn render(functions: &[CompiledFunction]) -> Result<OutputFiles> {
    render_with_definitions(functions, &[])
}

pub(super) fn render_with_definitions(
    functions: &[CompiledFunction],
    documents: &[crate::specs::DefinitionDocument],
) -> Result<OutputFiles> {
    let mut c_headers = Vec::new();
    let mut cpp_modules = Vec::new();
    let mut c_tests = Vec::new();
    let mut cpp_tests = Vec::new();
    let mut umbrella = Writer::new();
    umbrella.write(format_args!(
        "{HEADER}\n\n#ifndef PTFKIT_PTFKIT_H\n#define PTFKIT_PTFKIT_H\n\n"
    ));

    let mut root_module = Writer::new();
    root_module.write(format_args!("{HEADER}\n\nexport module ptfkit;\n\n"));

    let mut module_paths = vec!["cpp/ptfkit.cppm".to_owned()];
    let shared = super::shared_enum_groups(functions);
    for (document, definitions) in &shared {
        let description = documents
            .iter()
            .find(|entry| entry.module == *document)
            .map(|entry| entry.description.as_str());
        c_headers.push(file(
            format!("ptfkit/{document}.h"),
            shared_c_header(document, definitions, description),
        ));
        umbrella.line(format_args!("#include <ptfkit/{document}.h>"));
        cpp_modules.push(file(
            format!("{document}.cppm"),
            shared_cpp_module(document, definitions, description),
        ));
        module_paths.push(format!("cpp/{document}.cppm"));
        root_module.line(format_args!("export import ptfkit.{document};"));
    }
    for (slug, functions) in group_by_source(functions) {
        umbrella.line(format_args!("#include <ptfkit/{slug}.h>"));
        c_headers.push(file(
            format!("ptfkit/{slug}.h"),
            c_header(slug, &functions)?,
        ));
        module_paths.push(format!("cpp/{slug}.cppm"));
        root_module.line(format_args!("export import ptfkit.{slug};"));
        cpp_modules.push(file(format!("{slug}.cppm"), cpp_module(slug, &functions)?));
        c_tests.push(file(format!("{slug}.c"), c_test(slug, &functions)?));
        cpp_tests.push(file(format!("{slug}.cpp"), cpp_test(slug, &functions)?));
    }
    umbrella.write("\n\n#endif\n");
    c_headers.push(file("ptfkit/ptfkit.h", umbrella.into_string()));

    cpp_modules.push(file("ptfkit.cppm", root_module.into_string()));

    Ok(OutputFiles {
        c_headers,
        cpp_modules,
        c_tests,
        cpp_tests,
    })
}

fn file(path: impl Into<PathBuf>, contents: String) -> GeneratedFile {
    GeneratedFile::new(path.into(), contents)
}

pub(crate) fn c_result_name(schema: &str) -> String {
    schema
        .remove_boundaries(&[Boundary::LowerDigit])
        .to_case(Case::Snake)
}

fn c_header(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    let guard = format!("PTFKIT_{}_H", slug.to_ascii_uppercase());
    let mut writer = Writer::new();
    writer.write(format_args!(
        "{HEADER}\n\n#ifndef {guard}\n#define {guard}\n\n"
    ));
    for document in shared_documents(functions) {
        writer.write(format_args!("#include <ptfkit/{document}.h>\n"));
    }
    if requires_pow4(functions) {
        writer.write("#include <ptfkit/detail/power.h>\n");
    }
    if requires_math(functions) || requires_lookup(functions) || requires_tree(functions) {
        writer.write("#include <math.h>\n");
    }
    if requires_pow4(functions)
        || requires_math(functions)
        || requires_lookup(functions)
        || requires_tree(functions)
    {
        writer.blank_line();
    }
    let first = functions
        .first()
        .expect("generated source contains at least one function");
    source_comment(&first.entry.spec.source, &first.entry.spec.scope).render(&mut writer);
    for definition in enum_definitions(functions) {
        writer.blank_line();
        render_enum(&mut writer, slug, definition, NativeDialect::C);
    }
    let mut schemas = BTreeSet::new();
    for function in functions {
        let spec = &function.entry.spec.functions[function.function_index];
        if let Output::Struct(fields) = &function.core.output {
            let schema = spec
                .result_class()
                .ok_or(crate::targets::GenerationError::MissingResultClass)?;
            if schemas.insert(schema.to_owned()) {
                writer.blank_line();
                render_struct(
                    &mut writer,
                    fields,
                    spec,
                    &c_result_name(schema),
                    NativeDialect::C,
                );
            }
        }
    }
    for (name, fields) in record_types(functions)? {
        if schemas.insert(name.clone()) {
            writer.blank_line();
            render_internal_struct(
                &mut writer,
                &fields,
                &c_result_name(&name),
                NativeDialect::C,
            );
        }
    }
    for lookup in lookup_definitions(functions) {
        writer.blank_line();
        render_record_lookup_helper(&mut writer, slug, lookup, NativeDialect::C);
    }
    for tree in tree_definitions(functions) {
        writer.blank_line();
        render_tree_helper(&mut writer, slug, tree, NativeDialect::C);
    }
    for function in functions {
        writer.blank_line();
        NativeFunction::c(function)?.render(&mut writer);
    }
    writer.write("\n\n#endif\n");
    Ok(writer.into_string())
}

fn cpp_module(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    let mut writer = Writer::new();
    writer.write(format_args!("{HEADER}\n\n"));
    if requires_pow4(functions) || requires_math(functions) || requires_tree(functions) {
        writer.write("module;\n");
        if requires_pow4(functions) {
            writer.write("#include <ptfkit/detail/power.h>\n");
        }
        if requires_math(functions) || requires_tree(functions) {
            writer.write("#include <cmath>\n");
        }
        writer.blank_line();
    }
    writer.write(format_args!("export module ptfkit.{slug};\n\n"));
    for document in shared_documents(functions) {
        writer.write(format_args!("export import ptfkit.{document};\n"));
    }
    if !shared_documents(functions).is_empty() {
        writer.blank_line();
    }
    let first = functions
        .first()
        .expect("generated source contains at least one function");
    source_comment(&first.entry.spec.source, &first.entry.spec.scope).render(&mut writer);
    writer.blank_line();
    let native_functions = functions
        .iter()
        .map(|function| NativeFunction::cpp(function))
        .collect::<Result<Vec<_>>>()?;
    let record_types = record_types(functions)?;
    let lookup_definitions = lookup_definitions(functions);
    let tree_definitions = tree_definitions(functions);
    let has_tree_definitions = !tree_definitions.is_empty();
    writer.line(format_args!("export namespace ptfkit::{slug} {{"));
    writer.indented(|writer| {
        for definition in enum_definitions(functions) {
            writer.blank_line();
            render_enum(writer, slug, definition, NativeDialect::Cpp);
        }
        let mut schemas = BTreeSet::new();
        for function in functions {
            let spec = &function.entry.spec.functions[function.function_index];
            if let Output::Struct(fields) = &function.core.output {
                let result = spec
                    .result_class()
                    .expect("record output has a result class");
                if schemas.insert(result.to_owned()) {
                    writer.blank_line();
                    render_struct(writer, fields, spec, result, NativeDialect::Cpp);
                }
            }
        }
        for (name, fields) in &record_types {
            if schemas.insert(name.clone()) {
                writer.blank_line();
                render_internal_struct(writer, fields, name, NativeDialect::Cpp);
            }
        }
        if !has_tree_definitions {
            for lookup in &lookup_definitions {
                writer.blank_line();
                render_record_lookup_helper(writer, slug, lookup, NativeDialect::Cpp);
            }
            for function in &native_functions {
                writer.blank_line();
                function.render(writer);
            }
        }
    });
    writer.write(format_args!("\n\n}}  // namespace ptfkit::{slug}\n\n"));
    if !has_tree_definitions {
        return Ok(writer.into_string());
    }
    writer.line(format_args!("namespace ptfkit::{slug} {{"));
    writer.indented(|writer| {
        for lookup in &lookup_definitions {
            writer.blank_line();
            render_record_lookup_helper(writer, slug, lookup, NativeDialect::Cpp);
        }
        for tree in &tree_definitions {
            writer.blank_line();
            render_tree_helper(writer, slug, tree, NativeDialect::Cpp);
        }
    });
    writer.write(format_args!("\n\n}}  // namespace ptfkit::{slug}\n\n"));
    writer.line(format_args!("export namespace ptfkit::{slug} {{"));
    writer.indented(|writer| {
        for function in &native_functions {
            writer.blank_line();
            function.render(writer);
        }
    });
    writer.write(format_args!("\n\n}}  // namespace ptfkit::{slug}\n"));
    Ok(writer.into_string())
}

#[derive(Clone, Copy)]
enum NativeDialect {
    C,
    Cpp,
}

struct NativeFunction<'a> {
    function: &'a CompiledFunction,
    result: String,
    dialect: NativeDialect,
    terminal: bool,
}

impl<'a> NativeFunction<'a> {
    fn c(function: &'a CompiledFunction) -> Result<Self> {
        Self::new(function, NativeDialect::C)
    }

    fn cpp(function: &'a CompiledFunction) -> Result<Self> {
        Self::new(function, NativeDialect::Cpp)
    }

    fn new(function: &'a CompiledFunction, dialect: NativeDialect) -> Result<Self> {
        let spec = &function.entry.spec.functions[function.function_index];
        let result = match function.core.output {
            Output::Scalar => "double".to_owned(),
            Output::Struct(_) if matches!(dialect, NativeDialect::Cpp) => spec
                .result_class()
                .ok_or(crate::targets::GenerationError::MissingResultClass)?
                .to_owned(),
            Output::Struct(_) => c_result_name(
                spec.result_class()
                    .ok_or(crate::targets::GenerationError::MissingResultClass)?,
            ),
        };
        let output_name = &spec.outputs.fields()[0].name;
        let terminal = matches!(function.core.output, Output::Scalar)
            && function.ir.variables.last().is_some_and(|variable| {
                variable.name == *output_name && variable.value.is_number()
            });
        Ok(Self {
            function,
            result,
            dialect,
            terminal,
        })
    }
}

impl Render for NativeFunction<'_> {
    fn render(&self, writer: &mut Writer) {
        let spec = &self.function.entry.spec.functions[self.function.function_index];
        function_comment(spec).render(writer);
        if matches!(self.dialect, NativeDialect::Cpp) {
            writer.line("[[nodiscard]]");
            writer.write("inline ");
        } else {
            writer.write("static inline ");
        }
        writer.write(&self.result);
        writer.write(" ");
        writer.write(&self.function.core.name);
        writer.write("(");
        for (index, input) in self.function.core.inputs.iter().enumerate() {
            if index > 0 {
                writer.write(", ");
            }
            let parameter = &spec.inputs[index];
            match (parameter.enum_type(), self.dialect) {
                (Some(definition), dialect) => {
                    writer.write(enum_type_name(
                        &definition.enum_type,
                        &self.function.entry.slug,
                        dialect,
                    ));
                    writer.write(" ");
                }
                (None, _) => writer.write("double "),
            }
            writer.write(input);
        }
        writer.line(") {");
        writer.indented(|writer| {
            for variable in self
                .function
                .ir
                .variables
                .iter()
                .take(self.function.ir.variables.len() - usize::from(self.terminal))
            {
                match &variable.value {
                    VariableValue::Expression(expression) => {
                        writer.write(format_args!("const double {} = ", variable.name));
                        writer.write(c::expression(
                            expression,
                            &self.function.core.inputs,
                            &self.function.ir.variables,
                            self.expression_dialect(),
                        ));
                        writer.line(";");
                    }
                    VariableValue::RecordLookup(lookup) => {
                        self.render_record_lookup(writer, &variable.name, lookup);
                    }
                    VariableValue::Tree(tree) => {
                        self.render_tree_call(writer, &variable.name, tree);
                    }
                }
            }
            self.render_return(writer);
        });
        writer.line("}");
    }
}

impl NativeFunction<'_> {
    fn expression_dialect(&self) -> Dialect {
        match self.dialect {
            NativeDialect::C => Dialect::C,
            NativeDialect::Cpp => Dialect::Cpp,
        }
    }

    fn render_return(&self, writer: &mut Writer) {
        if matches!(self.function.core.output, Output::Struct(_))
            && let ResultBinding::RecordVariable(index) = self.function.ir.result
        {
            writer.line(format_args!(
                "return {};",
                self.function.ir.variables[index].name
            ));
            return;
        }
        let output_name = &self.function.entry.spec.functions[self.function.function_index]
            .outputs
            .fields()[0]
            .name;
        match &self.function.core.output {
            Output::Scalar if self.terminal => {
                match &self
                    .function
                    .ir
                    .variables
                    .last()
                    .expect("terminal variable")
                    .value
                {
                    VariableValue::Expression(expression) => {
                        writer.write("return ");
                        writer.write(c::expression(
                            expression,
                            &self.function.core.inputs,
                            &self.function.ir.variables,
                            self.expression_dialect(),
                        ));
                        writer.line(";");
                    }
                    VariableValue::Tree(tree) => {
                        writer.line(format_args!("return {};", self.tree_call_expression(tree)));
                    }
                    VariableValue::RecordLookup(_) => {
                        unreachable!("terminal scalar variable is numeric")
                    }
                }
            }
            Output::Scalar => writer.line(format_args!("return {output_name};")),
            Output::Struct(fields) if matches!(self.dialect, NativeDialect::C) => {
                writer.write(format_args!("{} result = {{", self.result));
                render_values(writer, fields);
                writer.line("};");
                writer.line("return result;");
            }
            Output::Struct(fields) => {
                writer.write(format_args!("return {}{{", self.result));
                render_values(writer, fields);
                writer.line("};");
            }
        }
    }

    fn render_record_lookup(&self, writer: &mut Writer, name: &str, lookup: &RecordLookup) {
        let result = match self.dialect {
            NativeDialect::C => c_result_name(&lookup.output.name),
            NativeDialect::Cpp => lookup.output.name.clone(),
        };
        let key = match lookup.key {
            Reference::Input(index) => &self.function.core.inputs[index],
            Reference::Variable(index) => &self.function.ir.variables[index].name,
        };
        writer.line(format_args!(
            "const {result} {name} = {}({key});",
            record_lookup_function_name(lookup)
        ));
    }

    fn render_tree_call(&self, writer: &mut Writer, name: &str, tree: &TreeCall) {
        let value_type = native_value_type(&tree.definition.output, self.dialect);
        writer.line(format_args!(
            "const {value_type} {name} = {};",
            self.tree_call_expression(tree)
        ));
    }

    fn tree_call_expression(&self, tree: &TreeCall) -> String {
        let arguments = tree
            .arguments
            .iter()
            .map(|argument| self.reference_name(*argument))
            .collect::<Vec<_>>()
            .join(", ");
        format!(
            "{}({arguments})",
            tree_function_name(&self.function.entry.slug, &tree.definition)
        )
    }

    fn reference_name(&self, reference: Reference) -> &str {
        match reference {
            Reference::Input(index) => &self.function.core.inputs[index],
            Reference::Variable(index) => &self.function.ir.variables[index].name,
        }
    }
}

fn lookup_definitions<'a>(functions: &[&'a CompiledFunction]) -> Vec<&'a RecordLookup> {
    let mut names = BTreeSet::new();
    functions
        .iter()
        .flat_map(|function| &function.ir.variables)
        .filter_map(|variable| match &variable.value {
            VariableValue::RecordLookup(lookup) => Some(lookup),
            VariableValue::Expression(_) | VariableValue::Tree(_) => None,
        })
        .filter(|lookup| names.insert((lookup.enum_type.clone(), lookup.output.name.clone())))
        .collect()
}

fn tree_definitions<'a>(functions: &[&'a CompiledFunction]) -> Vec<&'a TreeDefinition> {
    let mut names = BTreeSet::new();
    functions
        .iter()
        .flat_map(|function| &function.ir.variables)
        .filter_map(|variable| match &variable.value {
            VariableValue::Tree(tree) => Some(&tree.definition),
            VariableValue::Expression(_) | VariableValue::RecordLookup(_) => None,
        })
        .filter(|definition| names.insert(definition.name.as_str()))
        .collect()
}

fn tree_function_name(slug: &str, definition: &TreeDefinition) -> String {
    format!("{slug}_{}", definition.name.to_case(Case::Snake))
}

fn native_value_type(value_type: &ValueType, dialect: NativeDialect) -> String {
    match value_type {
        ValueType::Number => "double".to_owned(),
        ValueType::Record(record) => match dialect {
            NativeDialect::C => c_result_name(&record.name),
            NativeDialect::Cpp => record.name.clone(),
        },
        ValueType::Enum(_) => unreachable!("tree outputs cannot be enums"),
    }
}

fn render_tree_helper(
    writer: &mut Writer,
    slug: &str,
    definition: &TreeDefinition,
    dialect: NativeDialect,
) {
    let result = native_value_type(&definition.output, dialect);
    match dialect {
        NativeDialect::C => writer.write("static inline "),
        NativeDialect::Cpp => writer.write("[[nodiscard]] inline "),
    }
    writer.write(format_args!(
        "{result} {}(",
        tree_function_name(slug, definition)
    ));
    for (index, input) in definition.inputs.iter().enumerate() {
        if index > 0 {
            writer.write(", ");
        }
        match &input.value_type {
            ValueType::Number => writer.write("double "),
            ValueType::Enum(enum_type) => {
                writer.write(enum_type_name(enum_type, slug, dialect));
                writer.write(" ");
            }
            ValueType::Record(_) => unreachable!("tree inputs cannot be records"),
        }
        writer.write(&input.name);
    }
    writer.line(") {");
    let renderer = NativeTreeRenderer {
        slug,
        dialect,
        definition,
    };
    writer.indented(|writer| renderer.render_node(writer, &definition.root));
    writer.line("}");
}

struct NativeTreeRenderer<'a> {
    slug: &'a str,
    dialect: NativeDialect,
    definition: &'a TreeDefinition,
}

impl NativeTreeRenderer<'_> {
    fn render_node(&self, writer: &mut Writer, tree: &DecisionTree) {
        match tree {
            DecisionTree::Leaf(DecisionTreeLeaf::Number(value)) => {
                writer.line(format_args!("return {};", c::float_literal(&value.lexeme)));
            }
            DecisionTree::Leaf(DecisionTreeLeaf::Record(values)) => {
                let result = native_value_type(&self.definition.output, self.dialect);
                match self.dialect {
                    NativeDialect::C => {
                        writer.write(format_args!("const {result} result = {{"));
                        render_lookup_values(writer, values);
                        writer.line("};");
                        writer.line("return result;");
                    }
                    NativeDialect::Cpp => {
                        writer.write(format_args!("return {result}{{"));
                        render_lookup_values(writer, values);
                        writer.line("};");
                    }
                }
            }
            DecisionTree::Split { predicate, yes, no } => {
                writer.line(format_args!("if ({}) {{", self.condition(predicate)));
                writer.indented(|writer| self.render_node(writer, yes));
                writer.line("} else {");
                writer.indented(|writer| self.render_node(writer, no));
                writer.line("}");
            }
            DecisionTree::Match {
                input,
                enum_type,
                cases,
            } => {
                writer.line(format_args!("switch ({}) {{", self.reference_name(*input)));
                writer.indented(|writer| {
                    for case in cases {
                        for member in &case.members {
                            let member = match self.dialect {
                                NativeDialect::C => c_enum_member(
                                    &c_enum_module(enum_type, self.slug),
                                    &enum_type.name,
                                    member,
                                ),
                                NativeDialect::Cpp => format!(
                                    "{}::{}",
                                    cpp_enum_type_name(enum_type),
                                    member.to_case(Case::Pascal)
                                ),
                            };
                            writer.line(format_args!("case {member}:"));
                        }
                        writer.indented(|writer| {
                            writer.line("{");
                            writer.indented(|writer| self.render_node(writer, &case.then));
                            writer.line("}");
                        });
                    }
                });
                writer.line("}");
                self.render_invalid_fallback(writer);
            }
        }
    }

    fn condition(&self, predicate: &DecisionTreePredicate) -> String {
        match predicate {
            DecisionTreePredicate::LessThan { input, value } => format!(
                "{} < {}",
                self.reference_name(*input),
                c::float_literal(&value.lexeme)
            ),
            DecisionTreePredicate::EnumIn {
                input,
                enum_type,
                members,
            } => members
                .iter()
                .map(|member| {
                    let member = match self.dialect {
                        NativeDialect::C => c_enum_member(
                            &c_enum_module(enum_type, self.slug),
                            &enum_type.name,
                            member,
                        ),
                        NativeDialect::Cpp => {
                            format!(
                                "{}::{}",
                                cpp_enum_type_name(enum_type),
                                member.to_case(Case::Pascal)
                            )
                        }
                    };
                    format!("{} == {member}", self.reference_name(*input))
                })
                .collect::<Vec<_>>()
                .join(" || "),
        }
    }

    fn reference_name(&self, reference: Reference) -> &str {
        match reference {
            Reference::Input(index) => &self.definition.inputs[index].name,
            Reference::Variable(_) => unreachable!("tree definitions have only formal inputs"),
        }
    }

    fn render_invalid_fallback(&self, writer: &mut Writer) {
        match &self.definition.output {
            ValueType::Number => writer.line("return NAN;"),
            ValueType::Record(record) => {
                let result = native_value_type(&self.definition.output, self.dialect);
                match self.dialect {
                    NativeDialect::C => {
                        writer.write(format_args!("const {result} fallback = {{"));
                        for index in 0..record.fields.len() {
                            if index > 0 {
                                writer.write(", ");
                            }
                            writer.write("NAN");
                        }
                        writer.line("};");
                        writer.line("return fallback;");
                    }
                    NativeDialect::Cpp => {
                        writer.write(format_args!("return {result}{{"));
                        for index in 0..record.fields.len() {
                            if index > 0 {
                                writer.write(", ");
                            }
                            writer.write("NAN");
                        }
                        writer.line("};");
                    }
                }
            }
            ValueType::Enum(_) => unreachable!("tree outputs cannot be enums"),
        }
    }
}

fn record_lookup_function_name(lookup: &RecordLookup) -> String {
    format!(
        "{}_from_{}",
        c_result_name(&lookup.output.name),
        lookup.enum_type.shared_module.as_ref().map_or_else(
            || lookup.enum_type.name.to_case(Case::Snake),
            |module| format!(
                "ptfkit_{module}_{}",
                lookup.enum_type.name.to_case(Case::Snake)
            )
        )
    )
}

fn render_record_lookup_helper(
    writer: &mut Writer,
    slug: &str,
    lookup: &RecordLookup,
    dialect: NativeDialect,
) {
    let result = match dialect {
        NativeDialect::C => c_result_name(&lookup.output.name),
        NativeDialect::Cpp => lookup.output.name.clone(),
    };
    let enum_name = enum_type_name(&lookup.enum_type, slug, dialect);
    match dialect {
        NativeDialect::C => writer.write("static inline "),
        NativeDialect::Cpp => writer.write("[[nodiscard]] inline "),
    }
    writer.line(format_args!(
        "{result} {}({enum_name} value) {{",
        record_lookup_function_name(lookup)
    ));
    writer.indented(|writer| {
        match dialect {
            NativeDialect::C => writer.line(format_args!("static const {result} table[] = {{")),
            NativeDialect::Cpp => {
                writer.line(format_args!("static constexpr {result} table[] = {{"))
            }
        }
        writer.indented(|writer| {
            for case in &lookup.cases {
                writer.write("{");
                render_lookup_values(writer, &case.values);
                writer.line("},");
            }
        });
        writer.line("};");
        match dialect {
            NativeDialect::C => {
                writer.line("const unsigned index = (unsigned)value;");
                writer.line("if (index < sizeof(table) / sizeof(table[0])) {");
                writer.indented(|writer| {
                    writer.line("return table[index];");
                });
                writer.line("}");
                writer.write(format_args!("const {result} fallback = {{"));
                for index in 0..lookup.output.fields.len() {
                    if index > 0 {
                        writer.write(", ");
                    }
                    writer.write("NAN");
                }
                writer.line("};");
                writer.line("return fallback;");
            }
            NativeDialect::Cpp => {
                writer.line("return table[static_cast<unsigned>(value)];");
            }
        }
    });
    writer.line("}");
}

fn render_lookup_values(writer: &mut Writer, values: &[crate::semantic::Number]) {
    for (index, value) in values.iter().enumerate() {
        if index > 0 {
            writer.write(", ");
        }
        writer.write(c::float_literal(&value.lexeme));
    }
}

fn render_values(writer: &mut Writer, values: &[String]) {
    for (index, value) in values.iter().enumerate() {
        if index > 0 {
            writer.write(", ");
        }
        writer.write(value);
    }
}

fn render_struct(
    writer: &mut Writer,
    fields: &[String],
    spec: &Function,
    name: &str,
    dialect: NativeDialect,
) {
    match dialect {
        NativeDialect::C => writer.line("typedef struct {"),
        NativeDialect::Cpp => writer.line(format_args!("struct {name} {{")),
    }
    writer.indented(|writer| {
        for field in fields {
            let parameter = spec
                .outputs
                .fields()
                .iter()
                .find(|parameter| parameter.name == *field)
                .expect("core output field matches specification");
            field_comment(parameter).render(writer);
            writer.line(format_args!("double {field};"));
        }
    });
    match dialect {
        NativeDialect::C => writer.line(format_args!("}} {name};")),
        NativeDialect::Cpp => writer.line("};"),
    }
}

fn render_internal_struct(
    writer: &mut Writer,
    fields: &[String],
    name: &str,
    dialect: NativeDialect,
) {
    match dialect {
        NativeDialect::C => writer.line("typedef struct {"),
        NativeDialect::Cpp => writer.line(format_args!("struct {name} {{")),
    }
    writer.indented(|writer| {
        for field in fields {
            writer.line(format_args!("double {field};"));
        }
    });
    match dialect {
        NativeDialect::C => writer.line(format_args!("}} {name};")),
        NativeDialect::Cpp => writer.line("};"),
    }
}

fn enum_definitions<'a>(functions: &[&'a CompiledFunction]) -> Vec<&'a EnumDefinition> {
    let mut names = BTreeSet::new();
    functions
        .iter()
        .flat_map(|function| {
            function.entry.spec.functions[function.function_index]
                .inputs
                .iter()
                .filter_map(|input| input.enum_type())
        })
        .filter(|definition| {
            !definition.is_shared() && names.insert(definition.identity().to_owned())
        })
        .collect()
}

fn shared_documents<'a>(functions: &[&'a CompiledFunction]) -> BTreeSet<&'a str> {
    super::shared_enum_groups(functions.iter().copied())
        .into_keys()
        .collect()
}

fn shared_c_header(
    document: &str,
    definitions: &[&EnumDefinition],
    description: Option<&str>,
) -> String {
    let mut writer = Writer::new();
    writer.write(HEADER);
    if let Some(description) = description {
        for line in description.lines() {
            writer.line(format_args!("/// {line}"));
        }
    }
    writer.write(format_args!(
        "\n\n#ifndef PTFKIT_{document}\n#define PTFKIT_{document}\n\n"
    ));
    for definition in definitions {
        writer.blank_line();
        render_enum(
            &mut writer,
            &format!("ptfkit_{document}"),
            definition,
            NativeDialect::C,
        );
    }
    writer.write("\n\n#endif\n");
    writer.into_string()
}

fn shared_cpp_module(
    document: &str,
    definitions: &[&EnumDefinition],
    description: Option<&str>,
) -> String {
    let mut writer = Writer::new();
    writer.write(HEADER);
    if let Some(description) = description {
        for line in description.lines() {
            writer.line(format_args!("/// {line}"));
        }
    }
    writer.write(format_args!(
        "\n\nexport module ptfkit.{document};\n\nexport namespace ptfkit::{document} {{"
    ));
    for definition in definitions {
        writer.blank_line();
        render_enum(&mut writer, document, definition, NativeDialect::Cpp);
    }
    writer.write(format_args!("\n\n}}  // namespace ptfkit::{document}\n"));
    writer.into_string()
}

pub(crate) fn c_enum_module(enum_type: &EnumType, source: &str) -> String {
    enum_type
        .shared_module
        .as_ref()
        .map_or_else(|| source.to_owned(), |module| format!("ptfkit_{module}"))
}

fn enum_type_name(enum_type: &EnumType, source: &str, dialect: NativeDialect) -> String {
    match dialect {
        NativeDialect::C => c_enum_name(&c_enum_module(enum_type, source), &enum_type.name),
        NativeDialect::Cpp => cpp_enum_type_name(enum_type),
    }
}

pub(crate) fn cpp_enum_type_name(enum_type: &EnumType) -> String {
    enum_type.shared_module.as_ref().map_or_else(
        || enum_type.name.clone(),
        |module| format!("ptfkit::{module}::{}", enum_type.name),
    )
}

pub(crate) fn c_enum_name(module: &str, name: &str) -> String {
    format!("{module}_{}", name.to_case(Case::Snake))
}

pub(crate) fn c_enum_member(module: &str, enum_name: &str, member_name: &str) -> String {
    format!(
        "{module}_{}_{}",
        enum_name.to_case(Case::Snake),
        member_name
    )
}

fn render_enum(
    writer: &mut Writer,
    module: &str,
    definition: &EnumDefinition,
    dialect: NativeDialect,
) {
    match dialect {
        NativeDialect::C => writer.line("typedef enum {"),
        NativeDialect::Cpp => {
            writer.line(format_args!("enum class {} {{", definition.enum_type.name))
        }
    }
    writer.indented(|writer| {
        for member in &definition.values {
            if let Some(description) = &member.description {
                Comment(vec![format!("@brief {description}")]).render(writer);
            }
            match dialect {
                NativeDialect::C => writer.line(format_args!(
                    "{},",
                    c_enum_member(module, &definition.enum_type.name, &member.name)
                )),
                NativeDialect::Cpp => {
                    writer.line(format_args!("{},", member.name.to_case(Case::Pascal)))
                }
            }
        }
    });
    match dialect {
        NativeDialect::C => writer.line(format_args!(
            "}} {};",
            c_enum_name(module, &definition.enum_type.name)
        )),
        NativeDialect::Cpp => writer.line("};"),
    }
}

fn source_comment(source: &Source, scope: &Scope) -> Comment {
    source_comment_from_document(docs::for_source(source, scope))
}

fn source_comment_from_document(document: SourceDocument<'_>) -> Comment {
    let mut lines = vec![
        format!("@brief {}", document.summary),
        String::new(),
        "@details Source publication:".to_owned(),
        document.reference.citation.into(),
    ];
    if let Some(doi) = document.reference.doi {
        lines.push(format!("@see {} DOI: {}", doi.url, doi.identifier));
    }
    if let Some(territory) = document.territory {
        lines.extend([
            String::new(),
            "@remark Geographic scope:".to_owned(),
            territory.into(),
        ]);
    }
    if let Some(dataset) = document.dataset {
        lines.extend([
            String::new(),
            "@remark Calibration dataset:".to_owned(),
            dataset.into(),
        ]);
    }
    Comment(lines)
}

fn function_comment(function: &Function) -> Comment {
    function_comment_from_document(docs::for_function(function))
}

fn function_comment_from_document(document: FunctionDocument<'_>) -> Comment {
    let mut lines = vec![format!("@brief {}", document.summary)];
    lines.extend(document.parameters.iter().map(|parameter| {
        format!(
            "@param {} {}",
            parameter.name(),
            docs::parameter_details(parameter)
        )
    }));

    let outputs = match document.returns {
        docs::Returns::Scalar(field) => std::slice::from_ref(field),
        docs::Returns::Record { fields, .. } => fields,
    };
    if outputs.len() == 1 {
        lines.push(format!("@return {}", docs::parameter_details(&outputs[0])));
    } else {
        lines.push("@return A result with the following fields:".to_owned());
        lines.extend(outputs.iter().map(|parameter| {
            format!(
                "- `{}` — {}",
                parameter.name,
                docs::parameter_details(parameter)
            )
        }));
    }
    if let Some(territory) = document.territory {
        lines.extend([
            String::new(),
            "@remark Geographic scope:".to_owned(),
            territory.into(),
        ]);
    }
    lines.extend([
        String::new(),
        "@details Prediction target:".to_owned(),
        document.remarks.prediction_target.into(),
    ]);
    lines.extend(document.notes.iter().map(|note| format!("@note {note}")));
    lines.extend(
        document
            .warnings
            .iter()
            .map(|warning| format!("@warning {warning}")),
    );
    Comment(lines)
}

fn field_comment(parameter: &OutputField) -> Comment {
    Comment(vec![format!(
        "@brief {}",
        docs::parameter_details(parameter)
    )])
}

struct Comment(Vec<String>);

impl Render for Comment {
    fn render(&self, writer: &mut Writer) {
        writer.line("/**");
        for line in self.0.iter().flat_map(|line| wrap_comment_line(line)) {
            if line.is_empty() {
                writer.line(" *");
            } else {
                writer.line(format_args!(" * {}", line.replace("*/", "* /")));
            }
        }
        writer.line(" */");
    }
}

fn wrap_comment_line(line: &str) -> Vec<String> {
    const WIDTH: usize = 92;
    if line.is_empty() {
        return vec![String::new()];
    }
    let mut lines = Vec::new();
    let mut current = String::new();
    for word in line.split_whitespace() {
        if !current.is_empty() && current.len() + 1 + word.len() > WIDTH {
            lines.push(current);
            current = String::new();
        }
        if !current.is_empty() {
            current.push(' ');
        }
        current.push_str(word);
    }
    lines.push(current);
    lines
}

