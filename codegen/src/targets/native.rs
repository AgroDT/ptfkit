fn c_test(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    c_compatibility_test(slug, functions)
}
fn cpp_test(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    module_test(slug, functions)
}

fn c_compatibility_test(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    let mut writer = Writer::new();
    writer.write(format_args!(
        "{HEADER}\n\n#include <ptfkit/{slug}.h>\n#include \"support/close_enough.h\"\n\n"
    ));
    writer.line("int main() {");
    writer.indented(|writer| {
        for function in functions {
            let spec = &function.entry.spec.functions[function.function_index];
            for case in &function.verification_cases {
                writer.line("{");
                writer.indented(|writer| {
                    if matches!(function.core.output, Output::Scalar) {
                        writer.write("const double");
                    } else {
                        let name = spec
                            .result_class()
                            .expect("record output has a result class");
                        writer.write(format_args!("const {}", c_result_name(name)));
                    }
                    writer.write(" result = ");
                    writer.write(&function.core.name);
                    writer.write("(");
                    render_literals(writer, &case.inputs, NativeDialect::C, Some(slug));
                    writer.line(");");
                    for ((field, expected), tolerance) in spec
                        .outputs
                        .fields()
                        .iter()
                        .zip(&case.expected)
                        .zip(&function.output_tolerances)
                    {
                        writer.write("assert_close(");
                        if matches!(function.core.output, Output::Scalar) {
                            writer.write("result");
                        } else {
                            writer.write(format_args!("result.{}", field.name));
                        }
                        writer.write(", ");
                        writer.write(c::test_float_literal(*expected));
                        writer.write(", ");
                        write_tolerance_arguments(writer, tolerance);
                        writer.write(format_args!(", {:?}", case.id));
                        writer.line(");");
                    }
                });
                writer.line("}");
            }
        }
        writer.line("return 0;");
    });
    writer.line("}");
    Ok(writer.into_string())
}

fn module_test(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    let type_traits = functions
        .iter()
        .any(|function| matches!(function.core.output, Output::Struct(_)));
    let mut writer = Writer::new();
    writer.write(format_args!(
        "{HEADER}\n\nimport ptfkit.{slug};\n\n#include \"support/close_enough.h\""
    ));
    if type_traits {
        writer.write("\n#include <type_traits>\n\n");
    } else {
        writer.blank_line();
    }
    writer.line("int main() {");
    writer.indented(|writer| {
    for function in functions {
        let spec = &function.entry.spec.functions[function.function_index];
        for case in &function.verification_cases {
            writer.line("{");
            writer.indented(|writer| {
            writer.write(format_args!("const auto result = ptfkit::{slug}::{}(", function.core.name));
            render_literals(writer, &case.inputs, NativeDialect::Cpp, Some(slug));
            writer.line(");");
            if matches!(function.core.output, Output::Struct(_)) {
                let result = spec
                    .result_class()
                    .expect("record output has a result class");
                writer.line(format_args!("static_assert(std::is_same_v<std::remove_cv_t<decltype(result)>, ptfkit::{slug}::{result}>);"));
            }
            for ((field, expected), tolerance) in spec
                .outputs
                .fields()
                .iter()
                .zip(&case.expected)
                .zip(&function.output_tolerances)
            {
                writer.write("assert_close(");
                if matches!(function.core.output, Output::Scalar) {
                    writer.write("result");
                } else {
                    writer.write(format_args!("result.{}", field.name));
                }
                writer.write(", ");
                writer.write(c::test_float_literal(*expected));
                writer.write(", ");
                write_tolerance_arguments(writer, tolerance);
                writer.write(format_args!(", {:?}", case.id));
                writer.line(");");
            }
            });
            writer.line("}");
        }
    }
        writer.line("return 0;");
    });
    writer.line("}");
    Ok(writer.into_string())
}

fn write_tolerance_arguments(writer: &mut Writer, tolerance: &crate::model::CompiledTolerance) {
    let source = match &tolerance.source {
        crate::model::ToleranceSource::Registry => "registry",
        crate::model::ToleranceSource::SourceOverride(_) => "source override",
    };
    writer.write(c::test_float_literal(tolerance.absolute));
    writer.write(", ");
    writer.write(c::test_float_literal(tolerance.relative));
    writer.write(format_args!(
        ", \"{}\", \"{}\", \"{}\"",
        tolerance.quantity, tolerance.unit, source
    ));
}

fn render_literals(
    writer: &mut Writer,
    values: &[CompiledInput],
    dialect: NativeDialect,
    cpp_slug: Option<&str>,
) {
    for (index, value) in values.iter().enumerate() {
        if index > 0 {
            writer.write(", ");
        }
        match value {
            CompiledInput::Number(value) => writer.write(c::test_float_literal(*value)),
            CompiledInput::Enum {
                enum_type,
                member_name,
            } => {
                let slug = cpp_slug.expect("native test literals have a source module");
                match dialect {
                    NativeDialect::C => writer.write(c_enum_member(
                        &c_enum_module(enum_type, slug),
                        &enum_type.name,
                        member_name,
                    )),
                    NativeDialect::Cpp => {
                        let name = if enum_type.shared_module.is_some() {
                            enum_type_name(enum_type, slug, dialect)
                        } else {
                            format!("ptfkit::{slug}::{}", enum_type.name)
                        };
                        writer.write(format!("{name}::{}", member_name.to_case(Case::Pascal)));
                    }
                }
            }
        }
    }
}

