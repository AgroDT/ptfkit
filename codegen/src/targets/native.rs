pub(super) const HEADER: &str = "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n";

pub(super) struct OutputFiles {
    pub(super) c_headers: Vec<GeneratedFile>,
    pub(super) cpp_modules: Vec<GeneratedFile>,
    pub(super) c_tests: Vec<GeneratedFile>,
    pub(super) cpp_tests: Vec<GeneratedFile>,
    pub(super) test_support: Vec<GeneratedFile>,
}

pub(super) fn render(functions: &[CompiledFunction]) -> Result<OutputFiles> {
    let mut c_headers = Vec::new();
    let mut cpp_modules = Vec::new();
    let mut c_tests = vec![file("comparator.c", comparator_test(false))];
    let mut cpp_tests = vec![file("comparator.cpp", comparator_test(true))];
    let test_support = vec![file("close_enough.h", close_enough_header())];
    let mut umbrella = Writer::new();
    umbrella.write(format_args!(
        "{HEADER}\n\n#ifndef PTFKIT_PTFKIT_H\n#define PTFKIT_PTFKIT_H\n\n"
    ));

    let mut root_module = Writer::new();
    root_module.write(format_args!("{HEADER}\n\nexport module ptfkit;\n\n"));

    let mut module_paths = vec!["cpp/ptfkit.cppm".to_owned()];
    for (slug, functions) in group_by_source(functions) {
        umbrella.line(format_args!("#include <ptfkit/{slug}.h>"));
        c_headers.push(file(
            format!("ptfkit/{slug}.h"),
            c_header(slug, &functions)?,
        ));
        module_paths.push(format!("cpp/{slug}.cppm"));
        root_module.line(format_args!("export import ptfkit.{slug};"));
        cpp_modules.push(file(format!("{slug}.cppm"), cpp_module(slug, &functions)?));
        c_tests.push(file(format!("{slug}.c"), c_test(slug, &functions)?));
        cpp_tests.push(file(format!("{slug}.cpp"), cpp_test(slug, &functions)?));
    }
    umbrella.write("\n\n#endif\n");
    c_headers.push(file("ptfkit/ptfkit.h", umbrella.into_string()));

    cpp_modules.push(file("ptfkit.cppm", root_module.into_string()));

    Ok(OutputFiles {
        c_headers,
        cpp_modules,
        c_tests,
        cpp_tests,
        test_support,
    })
}

fn file(path: impl Into<PathBuf>, contents: String) -> GeneratedFile {
    GeneratedFile::new(path.into(), contents)
}

pub(crate) fn c_result_name(schema: &str) -> String {
    schema
        .remove_boundaries(&[Boundary::LowerDigit])
        .to_case(Case::Snake)
}

fn c_header(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    let guard = format!("PTFKIT_{}_H", slug.to_ascii_uppercase());
    let mut writer = Writer::new();
    writer.write(format_args!(
        "{HEADER}\n\n#ifndef {guard}\n#define {guard}\n\n"
    ));
    if requires_pow4(functions) {
        writer.write("#include <ptfkit/detail/power.h>\n");
    }
    if requires_record_literal(functions) {
        writer.write("#include <ptfkit/detail/record.h>\n");
    }
    if requires_math(functions) {
        writer.write("#include <math.h>\n");
    }
    if requires_pow4(functions) || requires_math(functions) {
        writer.blank_line();
    }
    let first = functions
        .first()
        .expect("generated source contains at least one function");
    source_comment(&first.entry.spec.source, &first.entry.spec.scope).render(&mut writer);
    for definition in enum_definitions(functions) {
        writer.blank_line();
        render_enum(&mut writer, slug, definition, NativeDialect::C);
    }
    let mut schemas = BTreeSet::new();
    for function in functions {
        let spec = &function.entry.spec.functions[function.function_index];
        if let Output::Struct(fields) = &function.core.output {
            let schema = spec
                .result_class()
                .ok_or_else(|| anyhow::anyhow!("record output has no result class"))?;
            if schemas.insert(schema.to_owned()) {
                writer.blank_line();
                render_struct(
                    &mut writer,
                    fields,
                    spec,
                    &c_result_name(schema),
                    NativeDialect::C,
                );
            }
        }
    }
    for (name, fields) in record_types(functions)? {
        if schemas.insert(name.clone()) {
            writer.blank_line();
            render_internal_struct(
                &mut writer,
                &fields,
                &c_result_name(&name),
                NativeDialect::C,
            );
        }
    }
    for lookup in lookup_definitions(functions) {
        writer.blank_line();
        render_record_lookup_helper(&mut writer, slug, lookup, NativeDialect::C);
    }
    for function in functions {
        writer.blank_line();
        NativeFunction::c(function)?.render(&mut writer);
    }
    writer.write("\n\n#endif\n");
    Ok(writer.into_string())
}

fn cpp_module(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    let mut writer = Writer::new();
    writer.write(format_args!("{HEADER}\n\n"));
    if requires_pow4(functions) || requires_math(functions) || requires_cpp_unreachable(functions) {
        writer.write("module;\n");
        if requires_pow4(functions) {
            writer.write("#include <ptfkit/detail/power.h>\n");
        }
        if requires_math(functions) {
            writer.write("#include <cmath>\n");
        }
        if requires_cpp_unreachable(functions) {
            writer.write("#include <utility>\n");
        }
        writer.blank_line();
    }
    writer.write(format_args!("export module ptfkit.{slug};\n\n"));
    let first = functions
        .first()
        .expect("generated source contains at least one function");
    source_comment(&first.entry.spec.source, &first.entry.spec.scope).render(&mut writer);
    writer.blank_line();
    let native_functions = functions
        .iter()
        .map(|function| NativeFunction::cpp(function))
        .collect::<Result<Vec<_>>>()?;
    let record_types = record_types(functions)?;
    writer.line(format_args!("export namespace ptfkit::{slug} {{"));
    writer.indented(|writer| {
        for definition in enum_definitions(functions) {
            writer.blank_line();
            render_enum(writer, slug, definition, NativeDialect::Cpp);
        }
        let mut schemas = BTreeSet::new();
        for function in functions {
            let spec = &function.entry.spec.functions[function.function_index];
            if let Output::Struct(fields) = &function.core.output {
                let result = spec
                    .result_class()
                    .expect("record output has a result class");
                if schemas.insert(result.to_owned()) {
                    writer.blank_line();
                    render_struct(writer, fields, spec, result, NativeDialect::Cpp);
                }
            }
        }
        for (name, fields) in &record_types {
            if schemas.insert(name.clone()) {
                writer.blank_line();
                render_internal_struct(writer, fields, name, NativeDialect::Cpp);
            }
        }
        for lookup in lookup_definitions(functions) {
            writer.blank_line();
            render_record_lookup_helper(writer, slug, lookup, NativeDialect::Cpp);
        }
        for function in &native_functions {
            writer.blank_line();
            function.render(writer);
        }
    });
    writer.write(format_args!("\n\n}}  // namespace ptfkit::{slug}\n"));
    Ok(writer.into_string())
}

#[derive(Clone, Copy)]
enum NativeDialect {
    C,
    Cpp,
}

struct NativeFunction<'a> {
    function: &'a CompiledFunction,
    result: String,
    dialect: NativeDialect,
    terminal: bool,
}

impl<'a> NativeFunction<'a> {
    fn c(function: &'a CompiledFunction) -> Result<Self> {
        Self::new(function, NativeDialect::C)
    }

    fn cpp(function: &'a CompiledFunction) -> Result<Self> {
        Self::new(function, NativeDialect::Cpp)
    }

    fn new(function: &'a CompiledFunction, dialect: NativeDialect) -> Result<Self> {
        let spec = &function.entry.spec.functions[function.function_index];
        let result = match function.core.output {
            Output::Scalar => "double".to_owned(),
            Output::Struct(_) if matches!(dialect, NativeDialect::Cpp) => spec
                .result_class()
                .ok_or_else(|| anyhow::anyhow!("record output has no result class"))?
                .to_owned(),
            Output::Struct(_) => c_result_name(
                spec.result_class()
                    .ok_or_else(|| anyhow::anyhow!("record output has no result class"))?,
            ),
        };
        let output_name = &spec.outputs.fields()[0].name;
        let terminal = matches!(function.core.output, Output::Scalar)
            && function.ir.variables.last().is_some_and(|variable| {
                variable.name == *output_name && matches!(variable.value, VariableValue::Number(_))
            });
        Ok(Self {
            function,
            result,
            dialect,
            terminal,
        })
    }
}

impl Render for NativeFunction<'_> {
    fn render(&self, writer: &mut Writer) {
        let spec = &self.function.entry.spec.functions[self.function.function_index];
        function_comment(spec).render(writer);
        if matches!(self.dialect, NativeDialect::Cpp) {
            writer.line("[[nodiscard]]");
            writer.write("inline ");
        } else {
            writer.write("static inline ");
        }
        writer.write(&self.result);
        writer.write(" ");
        writer.write(&self.function.core.name);
        writer.write("(");
        for (index, input) in self.function.core.inputs.iter().enumerate() {
            if index > 0 {
                writer.write(", ");
            }
            let parameter = &spec.inputs[index];
            match (parameter.enum_type(), self.dialect) {
                (Some(definition), NativeDialect::C) => {
                    writer.write(c_enum_name(&self.function.entry.slug, &definition.name));
                    writer.write(" ");
                }
                (Some(definition), NativeDialect::Cpp) => {
                    writer.write(&definition.name);
                    writer.write(" ");
                }
                (None, _) => writer.write("double "),
            }
            writer.write(input);
        }
        writer.line(") {");
        writer.indented(|writer| {
            for variable in self
                .function
                .ir
                .variables
                .iter()
                .take(self.function.ir.variables.len() - usize::from(self.terminal))
            {
                match &variable.value {
                    VariableValue::Number(expression) => {
                        writer.write(format_args!("const double {} = ", variable.name));
                        writer.write(c::expression(
                            expression,
                            &self.function.core.inputs,
                            &self.function.ir.variables,
                            self.expression_dialect(),
                        ));
                        writer.line(";");
                    }
                    VariableValue::RecordLookup(lookup) => {
                        self.render_record_lookup(writer, &variable.name, lookup);
                    }
                }
            }
            self.render_return(writer);
        });
        writer.line("}");
    }
}

impl NativeFunction<'_> {
    fn expression_dialect(&self) -> Dialect {
        match self.dialect {
            NativeDialect::C => Dialect::C,
            NativeDialect::Cpp => Dialect::Cpp,
        }
    }

    fn render_return(&self, writer: &mut Writer) {
        if matches!(self.function.core.output, Output::Struct(_))
            && let ResultBinding::RecordVariable(index) = self.function.ir.result
        {
            writer.line(format_args!(
                "return {};",
                self.function.ir.variables[index].name
            ));
            return;
        }
        let output_name = &self.function.entry.spec.functions[self.function.function_index]
            .outputs
            .fields()[0]
            .name;
        match &self.function.core.output {
            Output::Scalar if self.terminal => {
                writer.write("return ");
                writer.write(c::expression(
                    self.function
                        .ir
                        .variables
                        .last()
                        .expect("terminal variable")
                        .value
                        .as_number()
                        .expect("terminal scalar variable is numeric"),
                    &self.function.core.inputs,
                    &self.function.ir.variables,
                    self.expression_dialect(),
                ));
                writer.line(";");
            }
            Output::Scalar => writer.line(format_args!("return {output_name};")),
            Output::Struct(fields) if matches!(self.dialect, NativeDialect::C) => {
                writer.line("#ifdef __cplusplus");
                writer.write(format_args!("return {}{{", self.result));
                render_values(writer, fields);
                writer.line("};");
                writer.line("#else");
                writer.line(format_args!("return ({}) {{", self.result));
                writer.indented(|writer| {
                    for field in fields {
                        writer.line(format_args!(".{field} = {field},"));
                    }
                });
                writer.line("};");
                writer.line("#endif");
            }
            Output::Struct(fields) => {
                writer.write(format_args!("return {}{{", self.result));
                render_values(writer, fields);
                writer.line("};");
            }
        }
    }

    fn render_record_lookup(&self, writer: &mut Writer, name: &str, lookup: &RecordLookup) {
        let result = match self.dialect {
            NativeDialect::C => c_result_name(&lookup.output.name),
            NativeDialect::Cpp => lookup.output.name.clone(),
        };
        let key = match lookup.key {
            Reference::Input(index) => &self.function.core.inputs[index],
            Reference::Variable(index) => &self.function.ir.variables[index].name,
        };
        writer.line(format_args!(
            "const {result} {name} = {}({key});",
            record_lookup_function_name(lookup, self.dialect)
        ));
    }
}

fn lookup_definitions<'a>(functions: &[&'a CompiledFunction]) -> Vec<&'a RecordLookup> {
    let mut names = BTreeSet::new();
    functions
        .iter()
        .flat_map(|function| &function.ir.variables)
        .filter_map(|variable| match &variable.value {
            VariableValue::RecordLookup(lookup) => Some(lookup),
            VariableValue::Number(_) => None,
        })
        .filter(|lookup| names.insert((lookup.enum_name.clone(), lookup.output.name.clone())))
        .collect()
}

fn record_lookup_function_name(lookup: &RecordLookup, _dialect: NativeDialect) -> String {
    format!(
        "{}_from_{}",
        c_result_name(&lookup.output.name),
        lookup.enum_name.to_case(Case::Snake)
    )
}

fn render_record_lookup_helper(
    writer: &mut Writer,
    slug: &str,
    lookup: &RecordLookup,
    dialect: NativeDialect,
) {
    let result = match dialect {
        NativeDialect::C => c_result_name(&lookup.output.name),
        NativeDialect::Cpp => lookup.output.name.clone(),
    };
    let enum_name = match dialect {
        NativeDialect::C => c_enum_name(slug, &lookup.enum_name),
        NativeDialect::Cpp => lookup.enum_name.clone(),
    };
    match dialect {
        NativeDialect::C => writer.write("static inline "),
        NativeDialect::Cpp => writer.write("[[nodiscard]] inline "),
    }
    writer.line(format_args!(
        "{result} {}({enum_name} value) {{",
        record_lookup_function_name(lookup, dialect)
    ));
    writer.indented(|writer| {
        writer.line("switch (value) {");
        writer.indented(|writer| {
            for case in &lookup.cases {
                let member = match dialect {
                    NativeDialect::C => c_enum_member(slug, &lookup.enum_name, &case.member),
                    NativeDialect::Cpp => format!(
                        "{}::{}",
                        lookup.enum_name,
                        case.member.to_case(Case::Pascal)
                    ),
                };
                writer.line(format_args!("case {member}:"));
                writer.indented(|writer| {
                    writer.write("return ");
                    render_record_literal(writer, &result, &case.values, dialect);
                    writer.line(";");
                });
            }
            writer.line("default:");
            writer.indented(|writer| match dialect {
                NativeDialect::C => {
                    let nan_values = std::iter::repeat_n("NAN", lookup.output.fields.len())
                        .collect::<Vec<_>>()
                        .join(", ");
                    writer.line(format_args!(
                        "return PTFKIT_RECORD_LITERAL({result}, {nan_values});"
                    ));
                }
                NativeDialect::Cpp => writer.line("std::unreachable();"),
            });
        });
        writer.line("}");
    });
    writer.line("}");
}

fn render_record_literal(
    writer: &mut Writer,
    result: &str,
    values: &[crate::semantic::Number],
    dialect: NativeDialect,
) {
    match dialect {
        NativeDialect::C => writer.write(format_args!("PTFKIT_RECORD_LITERAL({result}, ")),
        NativeDialect::Cpp => writer.write(format_args!("{result}{{")),
    }
    for (index, value) in values.iter().enumerate() {
        if index > 0 {
            writer.write(", ");
        }
        writer.write(c::float_literal(&value.lexeme));
    }
    writer.write(match dialect {
        NativeDialect::C => ")",
        NativeDialect::Cpp => "}",
    });
}

fn render_values(writer: &mut Writer, values: &[String]) {
    for (index, value) in values.iter().enumerate() {
        if index > 0 {
            writer.write(", ");
        }
        writer.write(value);
    }
}

fn render_struct(
    writer: &mut Writer,
    fields: &[String],
    spec: &Function,
    name: &str,
    dialect: NativeDialect,
) {
    match dialect {
        NativeDialect::C => writer.line("typedef struct {"),
        NativeDialect::Cpp => writer.line(format_args!("struct {name} {{")),
    }
    writer.indented(|writer| {
        for field in fields {
            let parameter = spec
                .outputs
                .fields()
                .iter()
                .find(|parameter| parameter.name == *field)
                .expect("core output field matches specification");
            field_comment(parameter).render(writer);
            writer.line(format_args!("double {field};"));
        }
    });
    match dialect {
        NativeDialect::C => writer.line(format_args!("}} {name};")),
        NativeDialect::Cpp => writer.line("};"),
    }
}

fn render_internal_struct(
    writer: &mut Writer,
    fields: &[String],
    name: &str,
    dialect: NativeDialect,
) {
    match dialect {
        NativeDialect::C => writer.line("typedef struct {"),
        NativeDialect::Cpp => writer.line(format_args!("struct {name} {{")),
    }
    writer.indented(|writer| {
        for field in fields {
            writer.line(format_args!("double {field};"));
        }
    });
    match dialect {
        NativeDialect::C => writer.line(format_args!("}} {name};")),
        NativeDialect::Cpp => writer.line("};"),
    }
}

fn enum_definitions<'a>(functions: &[&'a CompiledFunction]) -> Vec<&'a EnumDefinition> {
    let mut names = BTreeSet::new();
    functions
        .iter()
        .flat_map(|function| {
            function.entry.spec.functions[function.function_index]
                .inputs
                .iter()
                .filter_map(|input| input.enum_type())
        })
        .filter(|definition| names.insert(definition.name.as_str()))
        .collect()
}

pub(crate) fn c_enum_name(module: &str, name: &str) -> String {
    format!("{module}_{}", name.to_case(Case::Snake))
}

pub(crate) fn c_enum_member(module: &str, enum_name: &str, member_name: &str) -> String {
    format!(
        "{module}_{}_{}",
        enum_name.to_case(Case::Snake),
        member_name
    )
}

fn render_enum(
    writer: &mut Writer,
    module: &str,
    definition: &EnumDefinition,
    dialect: NativeDialect,
) {
    match dialect {
        NativeDialect::C => writer.line("typedef enum {"),
        NativeDialect::Cpp => writer.line(format_args!("enum class {} {{", definition.name)),
    }
    writer.indented(|writer| {
        for member in &definition.values {
            if let Some(description) = &member.description {
                Comment(vec![format!("@brief {description}")]).render(writer);
            }
            match dialect {
                NativeDialect::C => writer.line(format_args!(
                    "{},",
                    c_enum_member(module, &definition.name, &member.name)
                )),
                NativeDialect::Cpp => {
                    writer.line(format_args!("{},", member.name.to_case(Case::Pascal)))
                }
            }
        }
    });
    match dialect {
        NativeDialect::C => writer.line(format_args!(
            "}} {};",
            c_enum_name(module, &definition.name)
        )),
        NativeDialect::Cpp => writer.line("};"),
    }
}

fn source_comment(source: &Source, scope: &Scope) -> Comment {
    source_comment_from_document(docs::for_source(source, scope))
}

fn source_comment_from_document(document: SourceDocument<'_>) -> Comment {
    let mut lines = vec![
        format!("@brief {}", document.summary),
        String::new(),
        "@details Source publication:".to_owned(),
        document.reference.citation.into(),
    ];
    if let Some(doi) = document.reference.doi {
        lines.push(format!("@see {} DOI: {}", doi.url, doi.identifier));
    }
    if let Some(territory) = document.territory {
        lines.extend([
            String::new(),
            "@remark Geographic scope:".to_owned(),
            territory.into(),
        ]);
    }
    if let Some(dataset) = document.dataset {
        lines.extend([
            String::new(),
            "@remark Calibration dataset:".to_owned(),
            dataset.into(),
        ]);
    }
    Comment(lines)
}

fn function_comment(function: &Function) -> Comment {
    function_comment_from_document(docs::for_function(function))
}

fn function_comment_from_document(document: FunctionDocument<'_>) -> Comment {
    let mut lines = vec![format!("@brief {}", document.summary)];
    lines.extend(document.parameters.iter().map(|parameter| {
        format!(
            "@param {} {}",
            parameter.name(),
            docs::parameter_details(parameter)
        )
    }));

    let outputs = match document.returns {
        docs::Returns::Scalar(field) => std::slice::from_ref(field),
        docs::Returns::Record { fields, .. } => fields,
    };
    if outputs.len() == 1 {
        lines.push(format!("@return {}", docs::parameter_details(&outputs[0])));
    } else {
        lines.push("@return A result with the following fields:".to_owned());
        lines.extend(outputs.iter().map(|parameter| {
            format!(
                "- `{}` — {}",
                parameter.name,
                docs::parameter_details(parameter)
            )
        }));
    }
    if let Some(territory) = document.territory {
        lines.extend([
            String::new(),
            "@remark Geographic scope:".to_owned(),
            territory.into(),
        ]);
    }
    lines.extend([
        String::new(),
        "@details Prediction target:".to_owned(),
        document.remarks.prediction_target.into(),
    ]);
    lines.extend(document.notes.iter().map(|note| format!("@note {note}")));
    lines.extend(
        document
            .warnings
            .iter()
            .map(|warning| format!("@warning {warning}")),
    );
    Comment(lines)
}

fn field_comment(parameter: &OutputField) -> Comment {
    Comment(vec![format!(
        "@brief {}",
        docs::parameter_details(parameter)
    )])
}

struct Comment(Vec<String>);

impl Render for Comment {
    fn render(&self, writer: &mut Writer) {
        writer.line("/**");
        for line in self.0.iter().flat_map(|line| wrap_comment_line(line)) {
            if line.is_empty() {
                writer.line(" *");
            } else {
                writer.line(format_args!(" * {}", line.replace("*/", "* /")));
            }
        }
        writer.line(" */");
    }
}

fn wrap_comment_line(line: &str) -> Vec<String> {
    const WIDTH: usize = 92;
    if line.is_empty() {
        return vec![String::new()];
    }
    let mut lines = Vec::new();
    let mut current = String::new();
    for word in line.split_whitespace() {
        if !current.is_empty() && current.len() + 1 + word.len() > WIDTH {
            lines.push(current);
            current = String::new();
        }
        if !current.is_empty() {
            current.push(' ');
        }
        current.push_str(word);
    }
    lines.push(current);
    lines
}

fn requires_math(functions: &[&CompiledFunction]) -> bool {
    functions.iter().any(|function| {
        function
            .ir
            .variables
            .iter()
            .any(|variable| match &variable.value {
                VariableValue::Number(expression) => c::requires_math(expression),
                VariableValue::RecordLookup(_) => true,
            })
    })
}

fn requires_pow4(functions: &[&CompiledFunction]) -> bool {
    functions.iter().any(|function| {
        function
            .ir
            .variables
            .iter()
            .filter_map(|variable| variable.value.as_number())
            .any(c::requires_pow4)
    })
}

fn requires_record_literal(functions: &[&CompiledFunction]) -> bool {
    functions.iter().any(|function| {
        function
            .ir
            .variables
            .iter()
            .any(|variable| matches!(variable.value, VariableValue::RecordLookup(_)))
    })
}

fn requires_cpp_unreachable(functions: &[&CompiledFunction]) -> bool {
    requires_record_literal(functions)
}

