pub(super) const HEADER: &str = "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n";
pub(super) const CMAKE_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n";

pub(super) struct OutputFiles {
    pub(super) c_headers: Vec<GeneratedFile>,
    pub(super) cpp_modules: Vec<GeneratedFile>,
    pub(super) cpp_cmake: Vec<GeneratedFile>,
    pub(super) c_tests: Vec<GeneratedFile>,
    pub(super) cpp_tests: Vec<GeneratedFile>,
}

pub(super) fn render(functions: &[CompiledFunction], adapters: &Registry) -> Result<OutputFiles> {
    let mut c_headers = Vec::new();
    let mut cpp_modules = Vec::new();
    let mut c_tests = Vec::new();
    let mut cpp_tests = Vec::new();
    let mut umbrella = Writer::new();
    umbrella.write(format_args!(
        "{HEADER}\n\n#ifndef PTFKIT_PTFKIT_H\n#define PTFKIT_PTFKIT_H\n\n"
    ));

    let mut root_module = Writer::new();
    root_module.write(format_args!("{HEADER}\n\nexport module ptfkit;\n\n"));

    let mut module_paths = vec!["cpp/ptfkit.cppm".to_owned()];
    for adapter in adapters.adapters() {
        c_headers.push(file(
            format!("ptfkit/adapters/{}.h", adapter.adapter_id),
            c_adapter(adapter),
        ));
        let module_path = format!("cpp/adapters.{}.cppm", adapter.adapter_id);
        module_paths.push(module_path);
        root_module.line(format_args!(
            "export import ptfkit.adapters.{};",
            adapter.adapter_id
        ));
        cpp_modules.push(file(
            format!("adapters.{}.cppm", adapter.adapter_id),
            cpp_adapter(adapter),
        ));
    }
    for (slug, functions) in group_by_source(functions) {
        umbrella.line(format_args!("#include <ptfkit/{slug}.h>"));
        c_headers.push(file(
            format!("ptfkit/{slug}.h"),
            c_header(slug, &functions)?,
        ));
        module_paths.push(format!("cpp/{slug}.cppm"));
        root_module.line(format_args!("export import ptfkit.{slug};"));
        cpp_modules.push(file(format!("{slug}.cppm"), cpp_module(slug, &functions)?));
        c_tests.push(file(format!("{slug}.c"), c_test(slug, &functions)?));
        cpp_tests.push(file(format!("{slug}.cpp"), cpp_test(slug, &functions)?));
    }
    umbrella.write("\n\n#endif\n");
    c_headers.push(file("ptfkit/ptfkit.h", umbrella.into_string()));

    cpp_modules.push(file("ptfkit.cppm", root_module.into_string()));

    let mut cmake = Writer::new();
    cmake.write(format_args!("{CMAKE_HEADER}\nset(PTFKIT_CPP_MODULES\n"));
    cmake.indented(|writer| {
        for path in &module_paths {
            writer.line(format_args!("\"${{CMAKE_CURRENT_LIST_DIR}}/../{path}\""));
        }
    });
    cmake.line(")");
    Ok(OutputFiles {
        c_headers,
        cpp_modules,
        cpp_cmake: vec![file("ptfkitModules.cmake", cmake.into_string())],
        c_tests,
        cpp_tests,
    })
}

fn file(path: impl Into<PathBuf>, contents: String) -> GeneratedFile {
    GeneratedFile::new(path.into(), contents)
}

pub(crate) fn c_result_name(schema: &str) -> String {
    schema
        .remove_boundaries(&[Boundary::LowerDigit])
        .to_case(Case::Snake)
}

fn c_header(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    let guard = format!("PTFKIT_{}_H", slug.to_ascii_uppercase());
    let mut writer = Writer::new();
    writer.write(format_args!(
        "{HEADER}\n\n#ifndef {guard}\n#define {guard}\n\n"
    ));
    if requires_math(functions) {
        writer.write("#include <math.h>\n\n");
    }
    for adapter in used_adapters(functions) {
        writer.line(format_args!("#include <ptfkit/adapters/{adapter}.h>"));
    }
    if !used_adapters(functions).is_empty() {
        writer.blank_line();
    }
    let first = functions
        .first()
        .expect("generated source contains at least one function");
    source_comment(&first.entry.spec.source, &first.entry.spec.scope).render(&mut writer);
    let mut schemas = BTreeSet::new();
    for function in functions {
        let spec = &function.entry.spec.functions[function.function_index];
        if let Output::Struct(fields) = &function.core.output {
            let schema = spec
                .result_class()
                .ok_or_else(|| anyhow::anyhow!("record output has no result class"))?;
            if schemas.insert(schema) {
                writer.blank_line();
                render_struct(
                    &mut writer,
                    fields,
                    spec,
                    &c_result_name(schema),
                    NativeDialect::C,
                );
            }
        }
    }
    for function in functions {
        writer.blank_line();
        NativeFunction::c(function)?.render(&mut writer);
    }
    writer.write("\n\n#endif\n");
    Ok(writer.into_string())
}

fn cpp_module(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    let mut writer = Writer::new();
    writer.write(format_args!("{HEADER}\n\n"));
    if requires_math(functions) {
        writer.write("module;\n#include <cmath>\n\n");
    }
    writer.write(format_args!("export module ptfkit.{slug};\n\n"));
    for adapter in used_adapters(functions) {
        writer.line(format_args!("export import ptfkit.adapters.{adapter};"));
    }
    if !used_adapters(functions).is_empty() {
        writer.blank_line();
    }
    let first = functions
        .first()
        .expect("generated source contains at least one function");
    source_comment(&first.entry.spec.source, &first.entry.spec.scope).render(&mut writer);
    writer.blank_line();
    let native_functions = functions
        .iter()
        .map(|function| NativeFunction::cpp(function))
        .collect::<Result<Vec<_>>>()?;
    writer.line(format_args!("export namespace ptfkit::{slug} {{"));
    writer.indented(|writer| {
        let mut schemas = BTreeSet::new();
        for function in functions {
            let spec = &function.entry.spec.functions[function.function_index];
            if let Output::Struct(fields) = &function.core.output {
                let result = spec
                    .result_class()
                    .expect("record output has a result class");
                if schemas.insert(result) {
                    writer.blank_line();
                    render_struct(writer, fields, spec, result, NativeDialect::Cpp);
                }
            }
        }
        for function in &native_functions {
            writer.blank_line();
            function.render(writer);
        }
    });
    writer.write(format_args!("\n\n}}  // namespace ptfkit::{slug}\n"));
    Ok(writer.into_string())
}

#[derive(Clone, Copy)]
enum NativeDialect {
    C,
    Cpp,
}

struct NativeFunction<'a> {
    function: &'a CompiledFunction,
    result: String,
    dialect: NativeDialect,
    terminal: bool,
}

impl<'a> NativeFunction<'a> {
    fn c(function: &'a CompiledFunction) -> Result<Self> {
        Self::new(function, NativeDialect::C)
    }

    fn cpp(function: &'a CompiledFunction) -> Result<Self> {
        Self::new(function, NativeDialect::Cpp)
    }

    fn new(function: &'a CompiledFunction, dialect: NativeDialect) -> Result<Self> {
        let spec = &function.entry.spec.functions[function.function_index];
        let result = match function.core.output {
            Output::Scalar => "double".to_owned(),
            Output::Struct(_) if matches!(dialect, NativeDialect::Cpp) => spec
                .result_class()
                .ok_or_else(|| anyhow::anyhow!("record output has no result class"))?
                .to_owned(),
            Output::Struct(_) => c_result_name(
                spec.result_class()
                    .ok_or_else(|| anyhow::anyhow!("record output has no result class"))?,
            ),
        };
        let output_name = &spec.outputs.fields()[0].name;
        let terminal = matches!(function.core.output, Output::Scalar)
            && function
                .ir
                .variables
                .last()
                .is_some_and(|variable| variable.name == *output_name);
        Ok(Self {
            function,
            result,
            dialect,
            terminal,
        })
    }
}

impl Render for NativeFunction<'_> {
    fn render(&self, writer: &mut Writer) {
        let spec = &self.function.entry.spec.functions[self.function.function_index];
        function_comment(spec).render(writer);
        if matches!(self.dialect, NativeDialect::Cpp) {
            writer.line("[[nodiscard]]");
            writer.write("inline ");
        } else {
            writer.write("static inline ");
        }
        writer.write(&self.result);
        writer.write(" ");
        writer.write(&self.function.core.name);
        writer.write("(");
        for (index, input) in self.function.core.inputs.iter().enumerate() {
            if index > 0 {
                writer.write(", ");
            }
            writer.write(native_input_type(input.r#type.as_str(), self.dialect));
            writer.write(" ");
            writer.write(&input.name);
        }
        writer.line(") {");
        writer.indented(|writer| {
            render_native_lowering(writer, self.function, self.dialect);
            for variable in self
                .function
                .ir
                .variables
                .iter()
                .take(self.function.ir.variables.len() - usize::from(self.terminal))
            {
                writer.write(format_args!("const double {} = ", variable.name));
                writer.write(c::expression(
                    &variable.expression,
                    &self.function.core.inputs,
                    &self.function.ir.derived_inputs,
                    &self.function.ir.variables,
                    self.expression_dialect(),
                ));
                writer.line(";");
            }
            self.render_return(writer);
        });
        writer.line("}");
    }
}

fn native_input_type(input_type: &str, dialect: NativeDialect) -> &'static str {
    match (input_type, dialect) {
        ("number", _) => "double",
        ("usda_texture_class", NativeDialect::C) => "ptfkit_usda_texture",
        ("usda_texture_class", NativeDialect::Cpp) => "ptfkit::adapters::UsdaTexture",
        _ => unreachable!("validated registered input type"),
    }
}

fn render_native_lowering(
    writer: &mut Writer,
    function: &CompiledFunction,
    dialect: NativeDialect,
) {
    let mut lowered = BTreeSet::new();
    for binding in &function.ir.derived_inputs {
        let source = &function.core.inputs[binding.source_input].name;
        let key = (binding.adapter.as_str(), source.as_str());
        if lowered.insert(key) {
            match dialect {
                NativeDialect::C => writer.line(format_args!("const ptfkit_usda_texture_fractions {source}_fractions = ptfkit_usda_texture_to_fractions({source});")),
                NativeDialect::Cpp => writer.line(format_args!("const auto {source}_fractions = ptfkit::adapters::fractions({source});")),
            }
        }
        writer.line(format_args!(
            "const double {} = {source}_fractions.{};",
            binding.symbol, binding.component
        ));
    }
}

fn used_adapters<'a>(functions: &'a [&'a CompiledFunction]) -> BTreeSet<&'a str> {
    functions
        .iter()
        .flat_map(|function| {
            function
                .ir
                .derived_inputs
                .iter()
                .map(|binding| binding.adapter.as_str())
        })
        .collect()
}

fn constant_name(category: &str) -> String {
    category.to_ascii_uppercase().replace(' ', "_")
}
fn variant_name(category: &str) -> String {
    category
        .split(' ')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn c_adapter(adapter: &Adapter) -> String {
    let guard = format!(
        "PTFKIT_ADAPTER_{}_H",
        adapter.adapter_id.to_ascii_uppercase()
    );
    let mut writer = Writer::new();
    writer.write(format_args!("{HEADER}\n#ifndef {guard}\n#define {guard}\n\n#include <math.h>\n#include <stdint.h>\n\ntypedef uint8_t ptfkit_usda_texture;\n\n"));
    for (code, category) in adapter.input_type.categories.iter().enumerate() {
        writer.line(format_args!(
            "#define PTFKIT_USDA_TEXTURE_{} ((ptfkit_usda_texture){code})",
            constant_name(category)
        ));
    }
    writer.write("\ntypedef struct {\n    double sand;\n    double silt;\n    double clay;\n} ptfkit_usda_texture_fractions;\n\nstatic inline ptfkit_usda_texture_fractions ptfkit_make_usda_texture_fractions(double sand, double silt, double clay) {\n    ptfkit_usda_texture_fractions result = {sand, silt, clay};\n    return result;\n}\n\nstatic inline ptfkit_usda_texture_fractions ptfkit_usda_texture_to_fractions(ptfkit_usda_texture value) {\n    switch (value) {\n");
    writer.indented(|writer| {
        for (code, row) in adapter.representatives.iter().enumerate() {
            writer.line(format_args!(
                "case {code}: return ptfkit_make_usda_texture_fractions({}, {}, {});",
                row.values["sand"], row.values["silt"], row.values["clay"]
            ));
        }
    });
    writer.write("    default: return ptfkit_make_usda_texture_fractions(NAN, NAN, NAN);\n    }\n}\n\n#endif\n");
    writer.into_string()
}

fn cpp_adapter(adapter: &Adapter) -> String {
    let mut writer = Writer::new();
    writer.write(format_args!("{HEADER}\nmodule;\n#include <cstdint>\n#include <limits>\n\nexport module ptfkit.adapters.{};\n\nexport namespace ptfkit::adapters {{\n\nenum class UsdaTexture : std::uint8_t {{\n", adapter.adapter_id));
    writer.indented(|writer| {
        for (code, category) in adapter.input_type.categories.iter().enumerate() {
            writer.line(format_args!("{} = {code},", variant_name(category)));
        }
    });
    writer.write("};\n\nstruct UsdaTextureFractions { double sand; double silt; double clay; };\n\n[[nodiscard]] constexpr UsdaTextureFractions fractions(UsdaTexture value) {\n    switch (value) {\n");
    writer.indented(|writer| {
        for row in &adapter.representatives {
            writer.line(format_args!(
                "case UsdaTexture::{}: return {{{}, {}, {}}};",
                variant_name(&row.category),
                row.values["sand"],
                row.values["silt"],
                row.values["clay"]
            ));
        }
    });
    writer.write("    }\n    const auto nan = std::numeric_limits<double>::quiet_NaN();\n    return {nan, nan, nan};\n}\n\n}  // namespace ptfkit::adapters\n");
    writer.into_string()
}

impl NativeFunction<'_> {
    fn expression_dialect(&self) -> Dialect {
        match self.dialect {
            NativeDialect::C => Dialect::C,
            NativeDialect::Cpp => Dialect::Cpp,
        }
    }

    fn render_return(&self, writer: &mut Writer) {
        let output_name = &self.function.entry.spec.functions[self.function.function_index]
            .outputs
            .fields()[0]
            .name;
        match &self.function.core.output {
            Output::Scalar if self.terminal => {
                writer.write("return ");
                writer.write(c::expression(
                    &self
                        .function
                        .ir
                        .variables
                        .last()
                        .expect("terminal variable")
                        .expression,
                    &self.function.core.inputs,
                    &self.function.ir.derived_inputs,
                    &self.function.ir.variables,
                    self.expression_dialect(),
                ));
                writer.line(";");
            }
            Output::Scalar => writer.line(format_args!("return {output_name};")),
            Output::Struct(fields) if matches!(self.dialect, NativeDialect::C) => {
                writer.line("#ifdef __cplusplus");
                writer.write(format_args!("return {}{{", self.result));
                render_values(writer, fields);
                writer.line("};");
                writer.line("#else");
                writer.line(format_args!("return ({}) {{", self.result));
                writer.indented(|writer| {
                    for field in fields {
                        writer.line(format_args!(".{field} = {field},"));
                    }
                });
                writer.line("};");
                writer.line("#endif");
            }
            Output::Struct(fields) => {
                writer.write(format_args!("return {}{{", self.result));
                render_values(writer, fields);
                writer.line("};");
            }
        }
    }
}

fn render_values(writer: &mut Writer, values: &[String]) {
    for (index, value) in values.iter().enumerate() {
        if index > 0 {
            writer.write(", ");
        }
        writer.write(value);
    }
}

fn render_struct(
    writer: &mut Writer,
    fields: &[String],
    spec: &Function,
    name: &str,
    dialect: NativeDialect,
) {
    match dialect {
        NativeDialect::C => writer.line("typedef struct {"),
        NativeDialect::Cpp => writer.line(format_args!("struct {name} {{")),
    }
    writer.indented(|writer| {
        for field in fields {
            let parameter = spec
                .outputs
                .fields()
                .iter()
                .find(|parameter| parameter.name == *field)
                .expect("core output field matches specification");
            field_comment(parameter).render(writer);
            writer.line(format_args!("double {field};"));
        }
    });
    match dialect {
        NativeDialect::C => writer.line(format_args!("}} {name};")),
        NativeDialect::Cpp => writer.line("};"),
    }
}

fn source_comment(source: &Source, scope: &Scope) -> Comment {
    source_comment_from_document(docs::for_source(source, scope))
}

fn source_comment_from_document(document: SourceDocument<'_>) -> Comment {
    let mut lines = vec![
        format!("@brief {}", document.summary),
        String::new(),
        "@details Source publication:".to_owned(),
        document.reference.citation.into(),
    ];
    if let Some(doi) = document.reference.doi {
        lines.push(format!("@see {} DOI: {}", doi.url, doi.identifier));
    }
    if let Some(territory) = document.territory {
        lines.extend([
            String::new(),
            "@remark Geographic scope:".to_owned(),
            territory.into(),
        ]);
    }
    if let Some(dataset) = document.dataset {
        lines.extend([
            String::new(),
            "@remark Calibration dataset:".to_owned(),
            dataset.into(),
        ]);
    }
    Comment(lines)
}

fn function_comment(function: &Function) -> Comment {
    function_comment_from_document(docs::for_function(function))
}

fn function_comment_from_document(document: FunctionDocument<'_>) -> Comment {
    let mut lines = vec![format!("@brief {}", document.summary)];
    lines.extend(document.parameters.iter().map(|parameter| {
        format!(
            "@param {} {}",
            parameter.name,
            docs::input_details(parameter)
        )
    }));

    let outputs = match document.returns {
        docs::Returns::Scalar(field) => std::slice::from_ref(field),
        docs::Returns::Record { fields, .. } => fields,
    };
    if outputs.len() == 1 {
        lines.push(format!("@return {}", docs::parameter_details(&outputs[0])));
    } else {
        lines.push("@return A result with the following fields:".to_owned());
        lines.extend(outputs.iter().map(|parameter| {
            format!(
                "- `{}` — {}",
                parameter.name,
                docs::parameter_details(parameter)
            )
        }));
    }
    if let Some(territory) = document.territory {
        lines.extend([
            String::new(),
            "@remark Geographic scope:".to_owned(),
            territory.into(),
        ]);
    }
    lines.extend([
        String::new(),
        "@details Prediction target:".to_owned(),
        document.remarks.prediction_target.into(),
    ]);
    lines.extend(document.notes.iter().map(|note| format!("@note {note}")));
    lines.extend(
        document
            .warnings
            .iter()
            .map(|warning| format!("@warning {warning}")),
    );
    Comment(lines)
}

fn field_comment(parameter: &Parameter) -> Comment {
    Comment(vec![format!(
        "@brief {}",
        docs::parameter_details(parameter)
    )])
}

struct Comment(Vec<String>);

impl Render for Comment {
    fn render(&self, writer: &mut Writer) {
        writer.line("/**");
        for line in self.0.iter().flat_map(|line| wrap_comment_line(line)) {
            if line.is_empty() {
                writer.line(" *");
            } else {
                writer.line(format_args!(" * {}", line.replace("*/", "* /")));
            }
        }
        writer.line(" */");
    }
}

fn wrap_comment_line(line: &str) -> Vec<String> {
    const WIDTH: usize = 92;
    if line.is_empty() {
        return vec![String::new()];
    }
    let mut lines = Vec::new();
    let mut current = String::new();
    for word in line.split_whitespace() {
        if !current.is_empty() && current.len() + 1 + word.len() > WIDTH {
            lines.push(current);
            current = String::new();
        }
        if !current.is_empty() {
            current.push(' ');
        }
        current.push_str(word);
    }
    lines.push(current);
    lines
}

fn requires_math(functions: &[&CompiledFunction]) -> bool {
    functions.iter().any(|function| {
        function
            .ir
            .variables
            .iter()
            .any(|variable| c::requires_math(&variable.expression))
    })
}

fn c_test(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    c_compatibility_test(slug, functions)
}
fn cpp_test(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    module_test(slug, functions)
}

fn c_compatibility_test(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    let mut writer = Writer::new();
    writer.write(format_args!(
        "{HEADER}\n\n#include <ptfkit/{slug}.h>\n#include \"close_enough.h\"\n\n"
    ));
    writer.line("int main() {");
    writer.indented(|writer| {
        for function in functions {
            let spec = &function.entry.spec.functions[function.function_index];
            for case in &function.golden_tests {
                writer.line("{");
                writer.indented(|writer| {
                    if matches!(function.core.output, Output::Scalar) {
                        writer.write("const double");
                    } else {
                        let name = spec
                            .result_class()
                            .expect("record output has a result class");
                        writer.write(format_args!("const {}", c_result_name(name)));
                    }
                    writer.write(" result = ");
                    writer.write(&function.core.name);
                    writer.write("(");
                    render_literals(writer, function, &case.inputs, NativeDialect::C);
                    writer.line(");");
                    for (field, expected) in spec.outputs.fields().iter().zip(&case.expected) {
                        writer.write("assert_close_enough(");
                        if matches!(function.core.output, Output::Scalar) {
                            writer.write("result");
                        } else {
                            writer.write(format_args!("result.{}", field.name));
                        }
                        writer.write(", ");
                        writer.write(c::test_float_literal(*expected));
                        writer.write(", ");
                        writer.write(c::test_float_literal(case.atol));
                        writer.write(", ");
                        writer.write(c::test_float_literal(case.rtol));
                        writer.line(");");
                    }
                });
                writer.line("}");
            }
        }
        writer.line("return 0;");
    });
    writer.line("}");
    Ok(writer.into_string())
}

fn module_test(slug: &str, functions: &[&CompiledFunction]) -> Result<String> {
    let type_traits = functions
        .iter()
        .any(|function| matches!(function.core.output, Output::Struct(_)));
    let mut writer = Writer::new();
    writer.write(format_args!("{HEADER}\n\n#ifdef IMPORT_UMBRELLA\nimport ptfkit;\n#else\nimport ptfkit.{slug};\n#endif\n\n#include \"close_enough.h\""));
    if type_traits {
        writer.write("\n#include <type_traits>\n\n");
    } else {
        writer.blank_line();
    }
    writer.line("int main() {");
    writer.indented(|writer| {
    for function in functions {
        let spec = &function.entry.spec.functions[function.function_index];
        for case in &function.golden_tests {
            writer.line("{");
            writer.indented(|writer| {
            writer.write(format_args!("const auto result = ptfkit::{slug}::{}(", function.core.name));
            render_literals(writer, function, &case.inputs, NativeDialect::Cpp);
            writer.line(");");
            if matches!(function.core.output, Output::Struct(_)) {
                let result = spec
                    .result_class()
                    .expect("record output has a result class");
                writer.line(format_args!("static_assert(std::is_same_v<std::remove_cv_t<decltype(result)>, ptfkit::{slug}::{result}>);"));
            }
            for (field, expected) in spec.outputs.fields().iter().zip(&case.expected) {
                writer.write("assert_close_enough(");
                if matches!(function.core.output, Output::Scalar) {
                    writer.write("result");
                } else {
                    writer.write(format_args!("result.{}", field.name));
                }
                writer.write(", ");
                writer.write(c::test_float_literal(*expected));
                writer.write(", ");
                writer.write(c::test_float_literal(case.atol));
                writer.write(", ");
                writer.write(c::test_float_literal(case.rtol));
                writer.line(");");
            }
            });
            writer.line("}");
        }
    }
        writer.line("return 0;");
    });
    writer.line("}");
    Ok(writer.into_string())
}

fn render_literals(
    writer: &mut Writer,
    _function: &CompiledFunction,
    values: &[TestValue],
    dialect: NativeDialect,
) {
    for (index, value) in values.iter().enumerate() {
        if index > 0 {
            writer.write(", ");
        }
        match value {
            TestValue::Number(value) => writer.write(c::test_float_literal(*value)),
            TestValue::Category(category) => match dialect {
                NativeDialect::C => writer.write(format_args!(
                    "PTFKIT_USDA_TEXTURE_{}",
                    constant_name(category)
                )),
                NativeDialect::Cpp => writer.write(format_args!(
                    "ptfkit::adapters::UsdaTexture::{}",
                    variant_name(category)
                )),
            },
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::semantic::{BinaryOp, Expr, MathFunction};

    #[test]
    fn math_includes_follow_semantic_expression_requirements() {
        let value = Expr::Number(crate::semantic::Number {
            value: 1.0,
            lexeme: "1.0".to_owned(),
        });
        let arithmetic = Expr::Binary {
            op: BinaryOp::Add,
            left: Box::new(value.clone()),
            right: Box::new(value.clone()),
        };
        let power = Expr::Binary {
            op: BinaryOp::Power,
            left: Box::new(value.clone()),
            right: Box::new(value.clone()),
        };
        let logarithm = Expr::Call {
            function: MathFunction::Ln,
            args: vec![value],
        };

        assert!(!c::requires_math(&arithmetic));
        assert!(c::requires_math(&power));
        assert!(c::requires_math(&logarithm));
    }

    #[test]
    fn c_result_names_use_snake_case_without_a_generated_suffix() {
        assert_eq!(
            c_result_name("Dharumarajan2019WaterRetentionResult"),
            "dharumarajan2019_water_retention_result"
        );
    }
}
