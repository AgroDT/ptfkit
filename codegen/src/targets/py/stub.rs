use crate::{model::CompiledFunction, targets::py::WRAPPER_HEADER};

pub(super) fn render(functions: &[CompiledFunction]) -> String {
    let mut names = functions
        .iter()
        .map(|function| function.core.name.as_str())
        .collect::<Vec<_>>();
    names.sort_unstable();

    let mut lines = vec![
        WRAPPER_HEADER.trim_end().to_owned(),
        String::new(),
        "from numpy import ufunc".into(),
        String::new(),
    ];
    lines.extend(names.into_iter().map(|name| format!("{name}: ufunc")));
    format!("{}\n", lines.join("\n"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn declares_native_ufuncs_in_source_order() {
        assert_eq!(
            render(&[]),
            "# @generated by ptfkit-codegen; DO NOT EDIT.\n\nfrom numpy import ufunc\n\n"
        );
    }
}
