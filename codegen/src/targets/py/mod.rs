mod c;
mod stub;
mod wrapper;

use crate::model::{CompiledFunction, PythonGeneration};

pub(super) const C_HEADER: &str = "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n";
pub(super) const WRAPPER_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n";

pub(super) struct Output {
    pub(super) c_sources: Vec<(String, String)>,
    pub(super) stub: String,
    pub(super) wrappers: Vec<(String, PythonGeneration, String)>,
}

pub(super) fn render(functions: &[CompiledFunction]) -> anyhow::Result<Output> {
    Ok(Output {
        c_sources: c::render(functions)?,
        stub: stub::render(functions),
        wrappers: wrapper::render(functions)?,
    })
}
