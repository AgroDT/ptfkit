pub(super) const HEADER: &str = "// @generated by ptfkit-codegen; DO NOT EDIT.\n";

pub(crate) fn render(functions: &[CompiledFunction]) -> Result<Vec<GeneratedFile>> {
    let shared = shared_enum_groups(functions);
    let shared_modules = shared
        .keys()
        .map(|document| format_ident!("{document}"))
        .collect::<Vec<_>>();
    let mut generated = vec![GeneratedFile::new(
        PathBuf::from("definitions/mod.rs"),
        render_tokens(TokenStream::new(), quote!(#(pub mod #shared_modules;)*)),
    )];
    for (document, definitions) in &shared {
        let definitions = definitions
            .iter()
            .map(|definition| enum_tokens(definition))
            .collect::<Vec<_>>();
        generated.push(GeneratedFile::new(
            PathBuf::from(format!("definitions/{document}.rs")),
            render_tokens(TokenStream::new(), quote!(#(#definitions)*)),
        ));
    }
    generated.extend(group_by_source(functions)
        .into_iter()
        .map(|(slug, functions)| {
            let first = functions
                .first()
                .expect("generated source contains at least one function");
            let module_docs = module_doc_tokens(docs::for_source(
                &first.entry.spec.source,
                &first.entry.spec.scope,
            ));
            let unique_test_modules = functions.len() > 1;
            let mut enum_names = BTreeSet::new();
            let enum_definitions = functions
                .iter()
                .flat_map(|resolved| {
                    resolved.entry.spec.functions[resolved.function_index]
                        .inputs
                        .iter()
                        .filter_map(|input| input.enum_type())
                })
                .filter(|definition| {
                    !definition.is_shared() && enum_names.insert(definition.identity().to_owned())
                })
                .map(enum_tokens)
                .collect::<Vec<_>>();
            let public_record_names = functions
                .iter()
                .filter_map(|resolved| {
                    resolved.entry.spec.functions[resolved.function_index].result_class()
                })
                .collect::<BTreeSet<_>>();
            let internal_record_definitions = record_types(&functions)?
                .into_iter()
                .filter(|(name, _)| !public_record_names.contains(name.as_str()))
                .map(|(name, fields)| internal_record_tokens(&name, &fields))
                .collect::<Vec<_>>();
            let lookup_conversions = lookup_conversion_tokens(&functions);
            let tree_definitions = tree_definitions(&functions)
                .into_iter()
                .map(tree_definition_tokens)
                .collect::<Vec<_>>();
            let mut defined_result_classes = BTreeSet::new();
            let definitions = functions
                .into_iter()
                .map(|resolved| {
                    let function = &resolved.entry.spec.functions[resolved.function_index];
                    let define_output = function
                        .result_class()
                        .is_some_and(|name| defined_result_classes.insert(name));
                    module_tokens(resolved, &resolved.ir, unique_test_modules, define_output)
                })
                .collect::<Result<Vec<_>>>()?;
            Ok(GeneratedFile::new(
                PathBuf::from(format!("{slug}.rs")),
                render_tokens(
                    module_docs,
                    quote!(#(#enum_definitions)* #(#internal_record_definitions)* #(#lookup_conversions)* #(#tree_definitions)* #(#definitions)*),
                ),
            ))
        })
        .collect::<Result<Vec<_>>>()?);
    Ok(generated)
}

fn enum_type_tokens(enum_type: &EnumType) -> TokenStream {
    let name = format_ident!("{}", enum_type.name);
    match &enum_type.shared_module {
        Some(module) => {
            let module = format_ident!("{module}");
            quote!(crate::definitions::#module::#name)
        }
        None => quote!(#name),
    }
}

fn module_tokens(
    resolved: &CompiledFunction,
    ir: &semantic::Function,
    unique_test_module: bool,
    define_output: bool,
) -> Result<TokenStream> {
    let function = &resolved.core;
    let specification = &resolved.entry.spec.functions[resolved.function_index];
    let function_docs = function_doc_tokens(docs::for_function(specification));
    let name = format_ident!("{}", function.name);
    let inputs = function
        .inputs
        .iter()
        .map(|name| format_ident!("{name}"))
        .collect::<Vec<_>>();
    let input_types = specification
        .inputs
        .iter()
        .map(|input| {
            input.enum_type().map_or_else(
                || quote!(f64),
                |definition| enum_type_tokens(&definition.enum_type),
            )
        })
        .collect::<Vec<_>>();
    let scalar_output = matches!(function.output, Output::Scalar).then(|| {
        resolved.entry.spec.functions[resolved.function_index]
            .outputs
            .fields()[0]
            .name
            .as_str()
    });
    let terminal_output = scalar_output.and_then(|output| {
        ir.variables
            .last()
            .filter(|variable| variable.name == output && variable.value.is_number())
    });
    let terminal_record = match ir.result {
        ResultBinding::RecordVariable(index) if index + 1 == ir.variables.len() => {
            match &ir.variables[index].value {
                VariableValue::RecordLookup(lookup) => Some(lookup),
                VariableValue::Expression(_)
                | VariableValue::Tree(_)
                | VariableValue::DecisionTree(_) => None,
            }
        }
        ResultBinding::Fields | ResultBinding::RecordVariable(_) => None,
    };
    let variables = ir
        .variables
        .iter()
        .take(
            ir.variables.len()
                - usize::from(terminal_output.is_some() || terminal_record.is_some()),
        )
        .map(|variable| {
            let name = format_ident!("{}", variable.name);
            match &variable.value {
                VariableValue::Expression(expression) => {
                    let expression = expression_tokens(expression, &inputs, &ir.variables)?.tokens;
                    Ok(quote!(let #name = #expression;))
                }
                VariableValue::RecordLookup(lookup) => {
                    let expression = record_lookup_tokens(lookup, &inputs, &ir.variables)?;
                    Ok(quote!(let #name = #expression;))
                }
                VariableValue::Tree(tree) => {
                    let expression = tree_call_tokens(tree, &inputs, &ir.variables);
                    Ok(quote!(let #name = #expression;))
                }
                VariableValue::DecisionTree(tree) => {
                    let expression =
                        decision_tree_tokens(tree, &inputs, &ir.variables, &ValueType::Number);
                    Ok(quote!(let #name = #expression;))
                }
            }
        })
        .collect::<Result<Vec<_>>>()?;
    let OutputTokens {
        definition,
        return_type,
        expression,
        separates_result,
    } = output_tokens(
        resolved,
        terminal_output,
        terminal_record,
        &inputs,
        &ir.variables,
        define_output,
    )?;
    let tests = verification_test_tokens(resolved, unique_test_module);
    Ok(quote! {
        #definition

        #function_docs
        #[cfg_attr(feature = "inline", inline)]
        #[must_use]
        pub fn #name(#(#inputs: #input_types),*) -> #return_type {
            #(#variables)*
            #separates_result
            #expression
        }

        #tests
    })
}

fn enum_tokens(definition: &EnumDefinition) -> TokenStream {
    let name = format_ident!("{}", definition.enum_type.name);
    let members = definition.values.iter().map(|member| {
        let member_name = format_ident!("{}", member.name.to_case(Case::Pascal));
        let docs = member
            .description
            .as_ref()
            .map(|description| doc_tokens([description.clone()]));
        quote!(#docs #member_name)
    });
    quote!(#[derive(Clone, Copy, Debug, Eq, PartialEq)] pub enum #name { #(#members),* })
}

fn internal_record_tokens(name: &str, fields: &[String]) -> TokenStream {
    let name = format_ident!("{name}");
    let fields = fields.iter().map(|field| format_ident!("{field}"));
    quote!(#[derive(Clone, Copy, Debug, PartialEq)] struct #name { #(#fields: f64),* })
}

struct OutputTokens {
    definition: TokenStream,
    return_type: TokenStream,
    expression: TokenStream,
    separates_result: TokenStream,
}

fn output_tokens(
    resolved: &CompiledFunction,
    terminal_output: Option<&semantic::Variable>,
    terminal_record: Option<&RecordLookup>,
    inputs: &[Ident],
    variables: &[semantic::Variable],
    define_output: bool,
) -> Result<OutputTokens> {
    match &resolved.core.output {
        Output::Scalar => {
            let name = &resolved.entry.spec.functions[resolved.function_index]
                .outputs
                .fields()[0]
                .name;
            let expression = match terminal_output {
                Some(variable) => match &variable.value {
                    VariableValue::Expression(expression) => {
                        expression_tokens(expression, inputs, variables)?.tokens
                    }
                    VariableValue::DecisionTree(tree) => {
                        decision_tree_tokens(tree, inputs, variables, &ValueType::Number)
                    }
                    VariableValue::Tree(tree) => tree_call_tokens(tree, inputs, variables),
                    VariableValue::RecordLookup(_) => {
                        unreachable!("scalar terminal output is numeric")
                    }
                },
                None => {
                    let name = format_ident!("{name}");
                    quote!(#name)
                }
            };
            Ok(OutputTokens {
                definition: TokenStream::new(),
                return_type: quote!(f64),
                expression,
                separates_result: TokenStream::new(),
            })
        }
        Output::Struct(fields) => {
            let specification = &resolved.entry.spec.functions[resolved.function_index];
            let result = specification
                .result_class()
                .ok_or_else(|| anyhow::anyhow!("record output has no result class"))?;
            let result = format_ident!("{result}");
            let definitions = fields.iter().map(|field| {
                let field = format_ident!("{field}");
                let parameter = specification
                    .outputs
                    .fields()
                    .iter()
                    .find(|parameter| field == parameter.name)
                    .expect("core output field matches specification");
                let docs = doc_tokens([docs::parameter_details(parameter)]);
                quote!(#docs pub #field: f64)
            });
            let expression = match resolved.ir.result {
                ResultBinding::RecordVariable(_) if terminal_record.is_some() => {
                    record_lookup_tokens(
                        terminal_record.expect("checked terminal record"),
                        inputs,
                        variables,
                    )?
                }
                ResultBinding::RecordVariable(index) => {
                    let variable = format_ident!("{}", resolved.ir.variables[index].name);
                    quote!(#variable)
                }
                ResultBinding::Fields => {
                    let values = fields.iter().map(|field| format_ident!("{field}"));
                    quote!(#result { #(#values),* })
                }
            };
            Ok(OutputTokens {
                definition: if define_output {
                    let docs =
                        doc_tokens([format!("Results returned by `{}`.", resolved.core.name)]);
                    quote!(#docs #[derive(Clone, Copy, Debug, PartialEq)] pub struct #result { #(#definitions),* })
                } else {
                    TokenStream::new()
                },
                return_type: quote!(#result),
                expression,
                separates_result: quote!(),
            })
        }
    }
}

fn record_lookup_tokens(
    lookup: &RecordLookup,
    inputs: &[Ident],
    variables: &[semantic::Variable],
) -> Result<TokenStream> {
    let key = reference_ident(lookup.key, inputs, variables);
    Ok(quote!(#key.into()))
}

fn decision_tree_tokens(
    tree: &DecisionTree,
    inputs: &[Ident],
    variables: &[semantic::Variable],
    output: &ValueType,
) -> TokenStream {
    match tree {
        DecisionTree::Leaf(DecisionTreeLeaf::Number(value)) => {
            let value = rust_float_literal(value);
            quote!(#value)
        }
        DecisionTree::Leaf(DecisionTreeLeaf::Record(values)) => {
            let ValueType::Record(record) = output else {
                unreachable!("record tree leaf has a record output")
            };
            let name = format_ident!("{}", record.name);
            let fields = record.fields.iter().map(|field| format_ident!("{field}"));
            let values = values.iter().map(rust_float_literal);
            quote!(#name { #(#fields: #values),* })
        }
        DecisionTree::Split { predicate, yes, no } => {
            let predicate = match predicate {
                DecisionTreePredicate::LessThan { input, value } => {
                    let input = reference_ident(*input, inputs, variables);
                    let value = rust_float_literal(value);
                    quote!(#input < #value)
                }
                DecisionTreePredicate::EnumIn {
                    input,
                    enum_type,
                    members,
                } => {
                    let input = reference_ident(*input, inputs, variables);
                    let enum_name = enum_type_tokens(enum_type);
                    let patterns = members.iter().map(|member| {
                        let member = format_ident!("{}", member.to_case(Case::Pascal));
                        quote!(#enum_name::#member)
                    });
                    quote!(matches!(#input, #(#patterns)|*))
                }
            };
            let yes = decision_tree_tokens(yes, inputs, variables, output);
            let no_is_split = matches!(no.as_ref(), DecisionTree::Split { .. });
            let no = decision_tree_tokens(no, inputs, variables, output);
            if no_is_split {
                quote!(if #predicate { #yes } else #no)
            } else {
                quote!(if #predicate { #yes } else { #no })
            }
        }
        DecisionTree::Match {
            input,
            enum_type,
            cases,
        } => {
            let input = reference_ident(*input, inputs, variables);
            let enum_name = enum_type_tokens(enum_type);
            let arms = cases.iter().map(|case| {
                let patterns = case.members.iter().map(|member| {
                    let member = format_ident!("{}", member.to_case(Case::Pascal));
                    quote!(#enum_name::#member)
                });
                let then = decision_tree_tokens(&case.then, inputs, variables, output);
                quote!(#(#patterns)|* => #then)
            });
            quote!(match #input { #(#arms),* })
        }
    }
}

fn tree_call_tokens(
    tree: &TreeCall,
    inputs: &[Ident],
    variables: &[semantic::Variable],
) -> TokenStream {
    let name = format_ident!("{}", tree.definition.name.to_case(Case::Snake));
    let arguments = tree
        .arguments
        .iter()
        .map(|reference| reference_ident(*reference, inputs, variables));
    quote!(#name(#(#arguments),*))
}

fn tree_definitions<'a>(functions: &[&'a CompiledFunction]) -> Vec<&'a TreeDefinition> {
    let mut names = BTreeSet::new();
    functions
        .iter()
        .flat_map(|function| &function.ir.variables)
        .filter_map(|variable| match &variable.value {
            VariableValue::Tree(tree) => Some(&tree.definition),
            VariableValue::Expression(_)
            | VariableValue::RecordLookup(_)
            | VariableValue::DecisionTree(_) => None,
        })
        .filter(|definition| names.insert(definition.name.as_str()))
        .collect()
}

fn tree_definition_tokens(definition: &TreeDefinition) -> TokenStream {
    let name = format_ident!("{}", definition.name.to_case(Case::Snake));
    let inputs = definition
        .inputs
        .iter()
        .map(|input| format_ident!("{}", input.name))
        .collect::<Vec<_>>();
    let input_types = definition
        .inputs
        .iter()
        .map(|input| match &input.value_type {
            ValueType::Number => quote!(f64),
            ValueType::Enum(enum_type) => enum_type_tokens(enum_type),
            ValueType::Record(_) => unreachable!("tree inputs cannot be records"),
        });
    let output = match &definition.output {
        ValueType::Number => quote!(f64),
        ValueType::Record(record) => {
            let name = format_ident!("{}", record.name);
            quote!(#name)
        }
        ValueType::Enum(_) => unreachable!("tree outputs cannot be enums"),
    };
    let body = decision_tree_tokens(&definition.root, &inputs, &[], &definition.output);
    quote!(#[inline] fn #name(#(#inputs: #input_types),*) -> #output { #body })
}

fn lookup_conversion_tokens(functions: &[&CompiledFunction]) -> Vec<TokenStream> {
    let mut names = BTreeSet::new();
    functions
        .iter()
        .flat_map(|function| &function.ir.variables)
        .filter_map(|variable| match &variable.value {
            VariableValue::RecordLookup(lookup) => Some(lookup),
            VariableValue::Expression(_)
            | VariableValue::Tree(_)
            | VariableValue::DecisionTree(_) => None,
        })
        .filter(|lookup| names.insert((lookup.enum_type.clone(), lookup.output.name.clone())))
        .map(|lookup| {
            let enum_name = enum_type_tokens(&lookup.enum_type);
            let output = format_ident!("{}", lookup.output.name);
            let fields = lookup
                .output
                .fields
                .iter()
                .map(|field| format_ident!("{field}"))
                .collect::<Vec<_>>();
            let arms = lookup.cases.iter().map(|case| {
                let member = format_ident!("{}", case.member.to_case(Case::Pascal));
                let values = case.values.iter().map(rust_float_literal);
                quote!(#enum_name::#member => Self { #(#fields: #values),* })
            });
            quote! {
                impl From<#enum_name> for #output {
                    fn from(value: #enum_name) -> Self {
                        match value {
                            #(#arms),*
                        }
                    }
                }
            }
        })
        .collect()
}

fn reference_ident(
    reference: Reference,
    inputs: &[Ident],
    variables: &[semantic::Variable],
) -> Ident {
    match reference {
        Reference::Input(index) => inputs[index].clone(),
        Reference::Variable(index) => format_ident!("{}", variables[index].name),
    }
}

fn module_doc_tokens(document: SourceDocument<'_>) -> TokenStream {
    let mut lines = vec![
        document.summary.into(),
        String::new(),
        "# Reference".into(),
        String::new(),
        document.reference.citation.into(),
    ];
    if let Some(doi) = document.reference.doi {
        lines.push(format!("DOI: {} ({})", doi.identifier, doi.url));
    }
    if let Some(territory) = document.territory {
        lines.extend([
            String::new(),
            "# Territory".into(),
            String::new(),
            territory.into(),
        ]);
    }
    if let Some(dataset) = document.dataset {
        lines.extend([
            String::new(),
            "# Dataset".into(),
            String::new(),
            dataset.into(),
        ]);
    }
    inner_doc_tokens(lines)
}

fn function_doc_tokens(document: FunctionDocument<'_>) -> TokenStream {
    let mut lines = vec![
        document.summary.into(),
        String::new(),
        "# Arguments".into(),
        String::new(),
    ];
    lines.extend(
        document
            .parameters
            .iter()
            .map(|parameter| format!("* {}", docs::parameter_documentation(parameter))),
    );
    lines.extend([String::new(), "# Returns".into(), String::new()]);
    lines.extend(return_doc_lines(document.returns));
    if let Some(territory) = document.territory {
        lines.extend([
            String::new(),
            "# Territory".into(),
            String::new(),
            territory.into(),
        ]);
    }
    let models = [
        document
            .models
            .h_theta
            .map(|model| format!("h(theta): {model}")),
        document.models.k_h.map(|model| format!("k(h): {model}")),
    ]
    .into_iter()
    .flatten()
    .collect::<Vec<_>>();
    if !models.is_empty() {
        lines.extend([String::new(), "# Models".into(), String::new()]);
        lines.extend(models.into_iter().map(|model| format!("* {model}")));
    }
    lines.extend([
        String::new(),
        "# Notes".into(),
        String::new(),
        format!("Prediction target: {}", document.remarks.prediction_target),
    ]);
    lines.extend(document.notes.iter().cloned());
    if !document.warnings.is_empty() {
        lines.extend([String::new(), "# Warnings".into(), String::new()]);
        lines.extend(document.warnings.iter().cloned());
    }
    doc_tokens(lines)
}

fn return_doc_lines(returns: Returns<'_>) -> Vec<String> {
    match returns {
        Returns::Record { name, fields } => {
            debug_assert!(
                !fields.is_empty(),
                "record outputs contain at least one field"
            );
            vec![format!("A [`{name}`].")]
        }
        Returns::Scalar(output) => std::slice::from_ref(output)
            .iter()
            .map(|parameter| format!("* {}", docs::parameter_documentation(parameter)))
            .collect(),
    }
}

fn doc_tokens(lines: impl IntoIterator<Item = String>) -> TokenStream {
    let documentation = raw_doc_literal(wrap_doc_lines(lines).join("\n"));
    quote!(#[doc = #documentation])
}

fn inner_doc_tokens(lines: impl IntoIterator<Item = String>) -> TokenStream {
    let documentation = raw_doc_literal(wrap_doc_lines(lines).join("\n"));
    quote!(#![doc = #documentation])
}

fn wrap_doc_lines(lines: impl IntoIterator<Item = String>) -> Vec<String> {
    lines
        .into_iter()
        .flat_map(|line| {
            if line.is_empty() || line.starts_with('#') {
                return vec![line];
            }
            let (first_prefix, continuation_prefix, text) = match line.strip_prefix("* ") {
                Some(text) => ("  * ", "    ", text),
                None => ("", "", line.as_str()),
            };
            wrap_doc_line(text, first_prefix, continuation_prefix)
        })
        .collect()
}

fn wrap_doc_line(text: &str, first_prefix: &str, continuation_prefix: &str) -> Vec<String> {
    const WIDTH: usize = 96;
    let mut lines = Vec::new();
    let mut line = first_prefix.to_owned();
    for word in text.split_whitespace() {
        let separator = usize::from(line.len() > first_prefix.len());
        if line.len() + separator + word.len() > WIDTH && line.len() > first_prefix.len() {
            lines.push(line);
            line = continuation_prefix.to_owned();
        }
        if line.len()
            > if lines.is_empty() {
                first_prefix.len()
            } else {
                continuation_prefix.len()
            }
        {
            line.push(' ');
        }
        line.push_str(word);
    }
    if !line.is_empty() {
        lines.push(line);
    }
    lines
}

fn raw_doc_literal(documentation: String) -> Literal {
    for hashes in 0.. {
        let delimiter = "#".repeat(hashes);
        let source = format!("r{delimiter}\"{documentation}\"{delimiter}");
        if let Ok(tokens) = TokenStream::from_str(&source) {
            let mut tokens = tokens.into_iter();
            if let (Some(TokenTree::Literal(literal)), None) = (tokens.next(), tokens.next()) {
                return literal;
            }
        }
    }
    unreachable!("a raw string delimiter is always available")
}

#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
enum Precedence {
    Sum,
    Product,
    Unary,
    Primary,
}

struct RenderedExpression {
    tokens: TokenStream,
    precedence: Precedence,
}

impl RenderedExpression {
    fn binary_operand_tokens(&self, parent: Precedence, is_right: bool) -> TokenStream {
        let needs_parentheses = self.precedence < parent || (is_right && self.precedence == parent);
        if needs_parentheses {
            let tokens = &self.tokens;
            quote!((#tokens))
        } else {
            self.tokens.clone()
        }
    }

    fn unary_operand_tokens(&self) -> TokenStream {
        if self.precedence <= Precedence::Unary {
            let tokens = &self.tokens;
            quote!((#tokens))
        } else {
            self.tokens.clone()
        }
    }

    fn method_receiver_tokens(&self) -> TokenStream {
        if self.precedence < Precedence::Primary {
            let tokens = &self.tokens;
            quote!((#tokens))
        } else {
            self.tokens.clone()
        }
    }
}

fn expression_tokens(
    expression: &Expr,
    inputs: &[Ident],
    variables: &[semantic::Variable],
) -> Result<RenderedExpression> {
    match expression {
        Expr::Number(number) => {
            let value = rust_float_literal(number);
            Ok(RenderedExpression {
                tokens: quote!(#value),
                precedence: Precedence::Primary,
            })
        }
        Expr::Reference(Reference::Input(index)) => {
            let input = &inputs[*index];
            Ok(RenderedExpression {
                tokens: quote!(#input),
                precedence: Precedence::Primary,
            })
        }
        Expr::Reference(Reference::Variable(index)) => {
            let name = format_ident!("{}", variables[*index].name);
            Ok(RenderedExpression {
                tokens: quote!(#name),
                precedence: Precedence::Primary,
            })
        }
        Expr::Field { record, field } => {
            let record = reference_ident(*record, inputs, variables);
            let field = format_ident!("{field}");
            Ok(primary_tokens(quote!(#record.#field)))
        }
        Expr::Unary { op, operand } => {
            let operand = expression_tokens(operand, inputs, variables)?;
            Ok(match op {
                UnaryOp::Plus => operand,
                UnaryOp::Minus => RenderedExpression {
                    tokens: {
                        let operand = operand.unary_operand_tokens();
                        quote!(-#operand)
                    },
                    precedence: Precedence::Unary,
                },
            })
        }
        Expr::Binary { op, left, right } => {
            let exponent_is_i32 = matches!(op, BinaryOp::Power)
                && matches!(right.as_ref(), Expr::Number(number) if number.value.fract() == 0.0 && number.value >= i32::MIN as f64 && number.value <= i32::MAX as f64);
            let exponent_value = match right.as_ref() {
                Expr::Number(number) => Some(number.value as i32),
                _ => None,
            };
            let left = expression_tokens(left, inputs, variables)?;
            let right = expression_tokens(right, inputs, variables)?;
            Ok(match op {
                BinaryOp::Add => binary_tokens(left, right, Precedence::Sum, quote!(+)),
                BinaryOp::Subtract => binary_tokens(left, right, Precedence::Sum, quote!(-)),
                BinaryOp::Multiply => binary_tokens(left, right, Precedence::Product, quote!(*)),
                BinaryOp::Divide => binary_tokens(left, right, Precedence::Product, quote!(/)),
                BinaryOp::Power if exponent_is_i32 => power_tokens(left, right, exponent_value),
                BinaryOp::Power => power_tokens(left, right, None),
            })
        }
        Expr::Call { function, args } => {
            let args = args
                .iter()
                .map(|arg| expression_tokens(arg, inputs, variables))
                .collect::<Result<Vec<_>>>()?;
            let first = args[0].method_receiver_tokens();
            Ok(match function {
                MathFunction::Sqrt => primary_tokens(quote!(#first.sqrt())),
                MathFunction::Exp => primary_tokens(quote!(#first.exp())),
                MathFunction::Ln => primary_tokens(quote!(#first.ln())),
                MathFunction::Log10 => primary_tokens(quote!(#first.log10())),
                MathFunction::Abs => primary_tokens(quote!(#first.abs())),
                MathFunction::Min => {
                    let second = &args[1].tokens;
                    primary_tokens(quote!(#first.min(#second)))
                }
                MathFunction::Max => {
                    let second = &args[1].tokens;
                    primary_tokens(quote!(#first.max(#second)))
                }
            })
        }
    }
}

fn rust_float_literal(number: &Number) -> Literal {
    let mut lexeme = number.lexeme.clone();
    if lexeme.starts_with('.') {
        lexeme.insert(0, '0');
    }
    if lexeme.ends_with('.') {
        lexeme.push('0');
    }
    if !lexeme.contains(['.', 'e', 'E']) {
        lexeme.push_str(".0");
    }
    Literal::from_str(&format!("{lexeme}f64")).expect("validated formula number is a Rust float")
}

fn binary_tokens(
    left: RenderedExpression,
    right: RenderedExpression,
    precedence: Precedence,
    operator: TokenStream,
) -> RenderedExpression {
    let left = left.binary_operand_tokens(precedence, false);
    let right = right.binary_operand_tokens(precedence, true);
    RenderedExpression {
        tokens: quote!(#left #operator #right),
        precedence,
    }
}

fn primary_tokens(tokens: TokenStream) -> RenderedExpression {
    RenderedExpression {
        tokens,
        precedence: Precedence::Primary,
    }
}

fn power_tokens(
    base: RenderedExpression,
    exponent: RenderedExpression,
    integer_exponent: Option<i32>,
) -> RenderedExpression {
    let base = base.method_receiver_tokens();
    let exponent = exponent.tokens;
    if let Some(value) = integer_exponent {
        let exponent = Literal::i32_unsuffixed(value);
        primary_tokens(quote!(#base.powi(#exponent)))
    } else {
        primary_tokens(quote!(#base.powf(#exponent)))
    }
}

fn verification_test_tokens(resolved: &CompiledFunction, unique_test_module: bool) -> TokenStream {
    let function = format_ident!("{}", resolved.core.name);
    let module = match unique_test_module {
        true => format_ident!("{}_tests", resolved.core.name),
        false => format_ident!("tests"),
    };
    let tests = resolved
        .verification_cases
        .iter()
        .map(|case| {
            let name = format_ident!("{}", case.id);
            let values = case
                .inputs
                .iter()
                .map(|value| match value {
                    CompiledInput::Number(value) => {
                        let value = Literal::f64_suffixed(*value);
                        quote!(#value)
                    }
                    CompiledInput::Enum {
                        enum_type,
                        member_name,
                        ..
                    } => {
                        let enum_name = enum_type_tokens(enum_type);
                        let member_name = format_ident!("{}", member_name.to_case(Case::Pascal));
                        quote!(#enum_name::#member_name)
                    }
                })
                .collect::<Vec<_>>();
            let assertion_for = |actual: TokenStream,
                                 expected: &f64,
                                 tolerance: &crate::model::CompiledTolerance| {
                let expected = Literal::f64_suffixed(*expected);
                let absolute = Literal::f64_suffixed(tolerance.absolute);
                let relative = Literal::f64_suffixed(tolerance.relative);
                let quantity = Literal::string(&tolerance.quantity);
                let unit = Literal::string(&tolerance.unit);
                let source = match &tolerance.source {
                    crate::model::ToleranceSource::Registry => "registry".to_owned(),
                    crate::model::ToleranceSource::SourceOverride(location) => {
                        format!("source override: {location}")
                    }
                };
                let source = Literal::string(&source);
                quote!(assert_close(#actual, #expected, #absolute, #relative, #quantity, #unit, #source);)
            };
            let assertions = match &resolved.core.output {
                Output::Scalar => assertion_for(
                    quote!(result),
                    &case.expected[0],
                    &resolved.output_tolerances[0],
                ),
                Output::Struct(fields) => {
                    let assertions = fields
                        .iter()
                        .zip(&case.expected)
                        .zip(&resolved.output_tolerances)
                        .map(|((field, expected), tolerance)| {
                            let field = format_ident!("{field}");
                            assertion_for(quote!(result.#field), expected, tolerance)
                        });
                    quote!(#(#assertions)*)
                }
            };
            quote!(#[test] fn #name() { let result = #function(#(#values),*); #assertions })
        })
        .collect::<Vec<_>>();
    quote! { #[cfg(test)] mod #module { use super::*; use crate::test_support::assert_close; #(#tests)* } }
}

fn render_tokens(module_docs: TokenStream, tokens: TokenStream) -> String {
    format!("{HEADER}\n{module_docs}\n\n{tokens}")
}

