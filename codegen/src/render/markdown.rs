//! Shared Markdown file and block rendering primitives.

use std::path::PathBuf;

use super::Writer;
use crate::output::GeneratedFile;

pub(crate) const HEADER: &str = "<!-- @generated by ptfkit-codegen; DO NOT EDIT. -->\n\n";
pub(crate) const FRONTMATTER_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n\n";

pub(crate) fn markdown_file(
    path: impl Into<PathBuf>,
    render: impl FnOnce(&mut Writer),
) -> GeneratedFile {
    let mut writer = Writer::new();
    render(&mut writer);
    GeneratedFile::new(path.into(), markdown_contents(writer))
}

pub(crate) fn markdown_contents(writer: Writer) -> String {
    format!("{}\n", writer.into_string().trim_end())
}

pub(crate) fn frontmatter(writer: &mut Writer, render: impl FnOnce(&mut Writer)) {
    writer.line("---");
    render(writer);
    writer.write("---\n\n");
}

pub(crate) fn generated_frontmatter(writer: &mut Writer, render: impl FnOnce(&mut Writer)) {
    frontmatter(writer, |writer| {
        writer.write(FRONTMATTER_HEADER);
        render(writer);
    });
}

pub(crate) fn code_block(writer: &mut Writer, language: &str, render: impl FnOnce(&mut Writer)) {
    writer.line(format_args!("```{language}"));
    render(writer);
    writer.write("```\n\n");
}

pub(crate) fn admonition(
    writer: &mut Writer,
    kind: &str,
    body: &str,
    render_line: impl Fn(&str) -> String,
) {
    writer.write(format_args!("!!! {kind}\n\n"));
    writer.indented(|writer| {
        for line in body.lines() {
            writer.line(render_line(line));
        }
    });
    writer.blank_line();
}
