use std::{collections::BTreeSet, fs, path::Path};

use anyhow::{Result, bail};
use jsonschema::Draft;
use serde::Deserialize;
use serde_json::Value;

use crate::output::GeneratedFile;

const CANONICAL_CLASSES: [&str; 12] = [
    "sand",
    "loamy sand",
    "sandy loam",
    "loam",
    "silt loam",
    "silt",
    "sandy clay loam",
    "clay loam",
    "silty clay loam",
    "sandy clay",
    "silty clay",
    "clay",
];

#[derive(Clone, Debug, Deserialize)]
#[allow(dead_code)]
pub(crate) struct Specification {
    pub(crate) classification_system: String,
    pub(crate) source: Source,
    pub(crate) units: String,
    pub(crate) sum_tolerance: f64,
    pub(crate) classes: Vec<TextureClass>,
    pub(crate) notes: Vec<String>,
    pub(crate) warnings: Vec<String>,
}

#[derive(Clone, Debug, Deserialize)]
#[allow(dead_code)]
pub(crate) struct Source {
    pub(crate) organization: String,
    pub(crate) title: String,
    pub(crate) artifact: String,
    pub(crate) retrieved: String,
    pub(crate) url: String,
    pub(crate) sha256: String,
    pub(crate) value_rule: String,
}

#[derive(Clone, Debug, Deserialize)]
pub(crate) struct TextureClass {
    pub(crate) name: String,
    pub(crate) sand: f64,
    pub(crate) silt: f64,
    pub(crate) clay: f64,
    #[serde(default)]
    pub(crate) aliases: Vec<String>,
}

pub(crate) fn load(root: &Path) -> Result<Specification> {
    let path = root.join("specs/utilities/usda_texture.yaml");
    let schema: Value = serde_json::from_slice(&fs::read(
        root.join("specs/schema/usda-texture.schema.json"),
    )?)?;
    let validator = jsonschema::options()
        .with_draft(Draft::Draft202012)
        .build(&schema)?;
    let yaml: serde_yaml::Value = serde_yaml::from_str(&fs::read_to_string(&path)?)?;
    let value = serde_json::to_value(yaml)?;
    let mut errors = validator
        .iter_errors(&value)
        .map(|error| format!("{}: {error}", error.instance_path()))
        .collect::<Vec<_>>();
    let specification: Specification = serde_json::from_value(value)?;
    validate(&specification, &mut errors);
    if !errors.is_empty() {
        bail!(
            "{}: USDA texture validation failed:\n{}",
            path.display(),
            errors.join("\n")
        );
    }
    Ok(specification)
}

fn validate(specification: &Specification, errors: &mut Vec<String>) {
    let actual = specification
        .classes
        .iter()
        .map(|class| class.name.as_str())
        .collect::<BTreeSet<_>>();
    let expected = CANONICAL_CLASSES.into_iter().collect::<BTreeSet<_>>();
    if actual != expected || specification.classes.len() != CANONICAL_CLASSES.len() {
        errors.push("classes must contain each canonical basic USDA class exactly once".into());
    }

    let mut normalized_names = BTreeSet::new();
    for class in &specification.classes {
        for (component, value) in [
            ("sand", class.sand),
            ("silt", class.silt),
            ("clay", class.clay),
        ] {
            if !value.is_finite() || !(0.0..=100.0).contains(&value) {
                errors.push(format!(
                    "class `{}` has invalid {component} value {value}",
                    class.name
                ));
            }
        }
        let sum = class.sand + class.silt + class.clay;
        if (sum - 100.0).abs() > specification.sum_tolerance {
            errors.push(format!(
                "class `{}` sums to {sum}, outside tolerance {}",
                class.name, specification.sum_tolerance
            ));
        }
        for accepted in std::iter::once(&class.name).chain(&class.aliases) {
            let normalized = normalize(accepted);
            if !normalized_names.insert(normalized.clone()) {
                errors.push(format!(
                    "normalized accepted name `{normalized}` is ambiguous"
                ));
            }
        }
    }
}

fn normalize(value: &str) -> String {
    value
        .trim()
        .to_lowercase()
        .replace(['_', '-'], " ")
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

