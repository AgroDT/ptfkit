fn python_number(value: f64) -> String {
    format!("{value:.1}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn repository_source_is_valid_and_complete() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
        let specification = load(root).expect("USDA texture source must validate");
        assert_eq!(specification.classes.len(), 12);
        assert_eq!(
            specification
                .classes
                .iter()
                .find(|class| class.name == "loam")
                .map(|class| (class.sand, class.silt, class.clay)),
            Some((41.0, 42.0, 17.0))
        );
    }
}
