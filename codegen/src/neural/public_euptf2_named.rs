//! Scientific named bindings and documentation for the shared QRF runtime.
use super::{
    ModelError,
    public::{Files, enabled, file},
    public_euptf2::Collection,
};
use crate::model::Entry;
use anyhow::Result;
use std::{collections::BTreeSet, fmt::Write as _};

fn output_contract(parameter: &str) -> (&'static str, &'static str, &'static str) {
    match parameter {
        "AWC" | "AWC_2" => ("available_water_capacity", "volume_fraction", "cm^3/cm^3"),
        "KS" => (
            "saturated_hydraulic_conductivity",
            "centimeter_per_day",
            "cm/day",
        ),
        "K0" => (
            "unsaturated_hydraulic_conductivity",
            "centimeter_per_day",
            "cm/day",
        ),
        "ALP" => ("van_genuchten_alpha", "inverse_centimeter", "1/cm"),
        "N" => ("van_genuchten_n", "dimensionless", "1"),
        "M" => ("van_genuchten_m", "dimensionless", "1"),
        "L" => ("conductivity_shape_parameter", "dimensionless", "1"),
        _ => ("volumetric_water_content", "volume_fraction", "cm^3/cm^3"),
    }
}

pub(super) fn render(collection: &Collection, entries: &[Entry]) -> Result<Files> {
    let Some(entry) = entries
        .iter()
        .find(|e| e.slug == "szabo_weynants_weber2021")
    else {
        return Ok(Files::default());
    };
    let functions: Vec<_> = entry.spec.functions.iter().filter(|f| enabled(f)).collect();
    let contracts: Vec<_> = collection
        .models
        .iter()
        .filter(|m| m.status == "implemented")
        .collect();
    let invalid = || ModelError::Contract {
        function: "EU-PTF v2 scientific bindings".into(),
    };
    if functions.len() != contracts.len() {
        return Err(invalid().into());
    }
    let mut rs = String::from(
        "//! Original EU-PTF v2 functions with external model handles.\nuse crate::models::{Euptf2Model,ModelError};\n",
    );
    let mut c = String::from(
        "#ifndef PTFKIT_SZABO_WEYNANTS_WEBER2021_H\n#define PTFKIT_SZABO_WEYNANTS_WEBER2021_H\n#include <ptfkit/models.h>\n",
    );
    let mut cpp = String::from(
        "module;\n#include <ptfkit/szabo_weynants_weber2021.h>\nexport module ptfkit.szabo_weynants_weber2021;\nexport import ptfkit.models;\n",
    );
    let mut py = String::from(
        "\"\"\"Original EU-PTF v2 functions and named default statistics.\"\"\"\nfrom typing import NamedTuple\n\nfrom ptfkit.models import Euptf2Model, ModelInputError\n",
    );
    let mut docs = format!(
        "<!-- @generated by ptfkit-codegen; DO NOT EDIT. -->\n\n# EU-PTF v2 API\n\n{}\n\nLoad external artifacts with `Euptf2Model` / `ptfkit_euptf2_load`. Generic prediction supports 1-64 probabilities strictly inside (0,1). Named functions bind a loaded handle to its exact scientific model and return the five original default quantiles. No trained data or R runtime is bundled.\n\n",
        entry.spec.source.citation_apa
    );
    let mut types = BTreeSet::new();
    let mut seen = BTreeSet::new();
    for f in functions {
        let binding = f
            .implementation
            .as_ref()
            .and_then(|i| i.external_model.as_ref())
            .ok_or_else(invalid)?;
        let m = contracts
            .iter()
            .find(|m| m.id == binding.level)
            .ok_or_else(invalid)?;
        let name = format!("calc_ptf_szabo2021_{}", m.name.to_lowercase());
        let mut expected: Vec<_> = m
            .mean_outputs
            .iter()
            .map(|p| {
                if m.components.len() == 1 {
                    "mean".into()
                } else {
                    format!("{}_mean", p.to_lowercase())
                }
            })
            .collect();
        expected.extend(m.quantile_outputs.iter().flat_map(|p| {
            ["q05", "q25", "q50", "q75", "q95"].map(|q| {
                if m.components.len() == 1 {
                    q.into()
                } else {
                    format!("{}_{q}", p.to_lowercase())
                }
            })
        }));
        let profiles: Vec<_> = m
            .mean_outputs
            .iter()
            .map(|p| output_contract(p))
            .chain(
                m.quantile_outputs
                    .iter()
                    .flat_map(|p| std::iter::repeat_n(output_contract(p), 5)),
            )
            .collect();
        if binding.kind != "euptf2"
            || binding.artifact != "../models/euptf2/collection.json"
            || f.name != name
            || f.public_api.name != name
            || !seen.insert(m.id)
            || f.inputs
                .iter()
                .map(|p| p.name().to_owned())
                .ne(m.features.iter().map(|p| p.to_lowercase()))
            || f.outputs
                .fields()
                .iter()
                .map(|p| &p.name)
                .ne(expected.iter())
            || f.outputs
                .fields()
                .iter()
                .zip(profiles)
                .any(|(field, (quantity, unit, reported))| {
                    field.quantity != quantity
                        || field.unit != unit
                        || field.reported_unit != reported
                })
            || f.inputs.iter().any(|input| match input {
                crate::model::Input::Parameter(p) => {
                    p.unit
                        != match p.name.as_str() {
                            "ussand" | "ussilt" | "usclay" | "oc" | "caco3" => "%",
                            "depth_m" => "cm",
                            "bd" => "g/cm^3",
                            "ph_h2o" => "1",
                            "cec" => "meq/100g",
                            _ => return true,
                        }
                }
                _ => true,
            })
        {
            return Err(invalid().into());
        }
        let ty = f.public_api.result_class.as_deref().ok_or_else(invalid)?;
        let ct = format!("ptfkit_euptf2_{}_statistics", m.family.to_lowercase());
        let fields = f.outputs.fields();
        if types.insert(ty.to_owned()) {
            writeln!(rs,"/// Default statistics in original units.\n#[derive(Clone,Copy,Debug,PartialEq)]\npub struct {ty} {{").unwrap();
            c.push_str("typedef struct {\n");
            writeln!(py,"\nclass {ty}(NamedTuple):\n    \"\"\"Default statistics in original units and parameter order.\"\"\"").unwrap();
            for field in fields {
                writeln!(
                    rs,
                    "/// {} ({})\npub {}:f64,",
                    field.description, field.reported_unit, field.name
                )
                .unwrap();
                writeln!(c, "double {}; /* {} */", field.name, field.reported_unit).unwrap();
                writeln!(py, "    {}: float", field.name).unwrap();
            }
            rs.push_str("}\n");
            writeln!(c, "}} {ct};").unwrap();
            writeln!(cpp, "export namespace ptfkit {{ using {ty}=::{ct}; }}").unwrap();
        }
        let args: Vec<_> = f.inputs.iter().map(|p| p.name()).collect();
        let ra = args
            .iter()
            .map(|p| format!("{p}:f64"))
            .collect::<Vec<_>>()
            .join(",");
        let ca = args
            .iter()
            .map(|p| format!("double {p}"))
            .collect::<Vec<_>>()
            .join(",");
        let pa = args
            .iter()
            .map(|p| format!("{p}:float"))
            .collect::<Vec<_>>()
            .join(",");
        let x = args.join(",");
        let mut values: Vec<_> = (0..m.mean_outputs.len())
            .map(|i| format!("p.mean[{i}]"))
            .collect();
        values.extend(
            (0..m.components.len())
                .flat_map(|i| (0..5).map(move |j| format!("p.quantiles[{i}][{j}]"))),
        );
        let assignments = expected
            .iter()
            .zip(&values)
            .map(|(field, value)| format!("{field}:{value}"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(rs,"/// {}\npub fn {name}(model:&Euptf2Model,{ra})->Result<{ty},ModelError>{{if model.descriptor().name!={:?}{{return Err(ModelError::Input);}}let p=model.predict(&[{x}])?;Ok({ty}{{{assignments}}})}}",f.public_api.summary,m.name).unwrap();
        writeln!(py,"\ndef {name}(model:Euptf2Model,*,{pa})->{ty}:\n    \"\"\"{}\"\"\"\n    if model.name!={:?}:\n        raise ModelInputError\n    p=model.predict([{x}])\n    return {ty}({})",f.public_api.summary,m.name,values.join(",")).unwrap();
        writeln!(c,"PTFKIT_MODEL_INLINE ptfkit_model_status {name}(const ptfkit_euptf2_model *model,{ca},{ct} *out){{if(!out)return PTFKIT_MODEL_INPUT;").unwrap();
        for field in &expected {
            writeln!(c, "out->{field}=NAN;").unwrap();
        }
        writeln!(c,"if(!model || model->detail_contract->id!={})return PTFKIT_MODEL_INPUT;double x[]={{{x}}},mean[7],q[30];ptfkit_model_status status=ptfkit_euptf2_predict(model,x,{},NULL,5,mean,{},q,{});if(status!=PTFKIT_MODEL_OK)return status;",m.id,args.len(),m.mean_outputs.len(),m.components.len()*5).unwrap();
        for (i, field) in expected.iter().enumerate() {
            let value = if i < m.mean_outputs.len() {
                format!("mean[{i}]")
            } else {
                format!("q[{}]", i - m.mean_outputs.len())
            };
            writeln!(c, "out->{field}={value};").unwrap();
        }
        c.push_str("return PTFKIT_MODEL_OK;}\n");
        writeln!(cpp,"export namespace ptfkit {{ inline {ty} {name}(const Euptf2Model& model,{ca}){{{ty} out;auto status=::{name}(model.native_handle(),{x},&out);if(status!=PTFKIT_MODEL_OK)throw ModelError(status);return out;}} }}").unwrap();
        writeln!(docs,"## `{name}`\n\n{}\n\nOriginal object `{}`. Predictors in saved order:\n\n| Name | Unit | Definition |\n| --- | --- | --- |",f.public_api.summary,m.name).unwrap();
        for input in &f.inputs {
            if let crate::model::Input::Parameter(p) = input {
                writeln!(docs, "| `{}` | {} | {} |", p.name, p.unit, p.description).unwrap();
            }
        }
        writeln!(
            docs,
            "\nResult `{ty}`: {}. Complete-container SHA-256 `{}`.\n",
            expected.join(", "),
            m.artifact.sha256
        )
        .unwrap();
    }
    c.push_str("#endif\n");
    Ok(Files {
        rust: vec![file(
            "szabo_weynants_weber2021.rs",
            "// @generated by ptfkit-codegen; DO NOT EDIT.\n",
            rs,
        )],
        c: vec![file(
            "ptfkit/szabo_weynants_weber2021.h",
            "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n",
            c,
        )],
        cpp: vec![file(
            "szabo_weynants_weber2021.cppm",
            "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n",
            cpp,
        )],
        python: vec![file(
            "ptfkit/szabo_weynants_weber2021.py",
            "# @generated by ptfkit-codegen; DO NOT EDIT.\n",
            py,
        )],
        c_docs: vec![file("headers/szabo_weynants_weber2021.md", "", &docs)],
        cpp_docs: vec![file("modules/szabo_weynants_weber2021.md", "", docs)],
        ..Files::default()
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{ExternalModel, Implementation, Input, Outputs, Parameter};

    #[test]
    fn rejects_scientific_bindings_with_changed_predictors_units_or_outputs() {
        let collection: Collection=serde_json::from_value(serde_json::json!({
            "format_version":2,"format":"PTFKQF02","distribution":"external-only",
            "models":[{"id":1,"name":"AWC_PTF01","family":"AWC","status":"implemented",
                "features":["USSAND","USSILT","USCLAY","DEPTH_M"],"mean_outputs":["AWC"],"quantile_outputs":["AWC"],
                "components":[{"parameter":"AWC","transform":0}],"artifact":{"sha256":"abc","bytes":100}}]
        })).unwrap();
        let mut entry = crate::test_support::entries().remove(0);
        entry.slug = "szabo_weynants_weber2021".into();
        let mut function = entry.spec.functions[0].clone();
        function.name = "calc_ptf_szabo2021_awc_ptf01".into();
        function.status = "implemented".into();
        function.public_api.name = function.name.clone();
        function.public_api.result_class = Some("ControlledStatistics".into());
        function.inputs = ["ussand", "ussilt", "usclay", "depth_m"]
            .into_iter()
            .map(|name| {
                Input::Parameter(Parameter {
                    name: name.into(),
                    unit: if name == "depth_m" { "cm" } else { "%" }.into(),
                    domain: None,
                    description: "Original unit".into(),
                    measurement: None,
                })
            })
            .collect();
        let mut field = function.outputs.fields()[0].clone();
        field.quantity = "available_water_capacity".into();
        field.unit = "volume_fraction".into();
        field.reported_unit = "cm^3/cm^3".into();
        function.outputs = Outputs::Record {
            name: "ControlledStatistics".into(),
            fields: ["mean", "q05", "q25", "q50", "q75", "q95"]
                .into_iter()
                .map(|name| {
                    let mut f = field.clone();
                    f.name = name.into();
                    f
                })
                .collect(),
        };
        function.implementation = Some(Implementation {
            variables: vec![],
            external_model: Some(ExternalModel {
                kind: "euptf2".into(),
                artifact: "../models/euptf2/collection.json".into(),
                level: 1,
            }),
        });
        entry.spec.functions = vec![function];
        assert!(render(&collection, std::slice::from_ref(&entry)).is_ok());
        for mutation in 0..5 {
            let mut changed = entry.clone();
            let f = &mut changed.spec.functions[0];
            match mutation {
                0 => f.inputs.swap(0, 1),
                1 => {
                    if let Input::Parameter(p) = &mut f.inputs[3] {
                        p.unit = "m".into();
                    }
                }
                2 => {
                    if let Outputs::Record { fields, .. } = &mut f.outputs {
                        fields.swap(1, 2);
                    }
                }
                3 => {
                    f.implementation
                        .as_mut()
                        .unwrap()
                        .external_model
                        .as_mut()
                        .unwrap()
                        .level = 2
                }
                _ => {
                    if let Outputs::Record { fields, .. } = &mut f.outputs {
                        fields[0].unit = "volume_percent".into();
                    }
                }
            }
            let error = render(&collection, &[changed]).err().unwrap();
            assert!(matches!(
                error.downcast_ref::<ModelError>(),
                Some(ModelError::Contract { .. })
            ));
        }
    }
}
