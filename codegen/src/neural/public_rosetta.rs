//! Validate and render the Rosetta3 scientific adapter for external models.
use super::{
    ModelError,
    public::{AdapterFiles, Files, PythonAdapter, enabled, file},
};
use crate::model::Entry;
use anyhow::{Context, Result};
use std::{fmt::Write as _, path::Path};

const C_HEADER: &str = "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n";
const RS_HEADER: &str = "// @generated by ptfkit-codegen; DO NOT EDIT.\n";
const PY_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n";
const PARAMETERS: [&str; 7] = ["theta_r", "theta_s", "alpha", "n", "k_sat", "k_0", "l"];

pub(crate) fn validate(entries: &[Entry]) -> Result<()> {
    let mut levels = Vec::new();
    for entry in entries {
        for function in &entry.spec.functions {
            if !enabled(function) {
                continue;
            }
            let Some(binding) = function
                .implementation
                .as_ref()
                .and_then(|i| i.external_model.as_ref())
            else {
                continue;
            };
            let fields: Vec<_> = ["mean", "std"]
                .into_iter()
                .flat_map(|stat| PARAMETERS.map(|p| format!("{p}_{stat}")))
                .collect();
            let inputs = [
                "sand",
                "silt",
                "clay",
                "bulk_density",
                "theta_33",
                "theta_1500",
            ];
            if entry.slug != "zhang_schaap2017"
                || binding.kind != "rosetta3"
                || binding.artifact != "../models/rosetta3/artifact.json"
                || !(2..=5).contains(&binding.level)
                || function.name != format!("calc_ptf_zhang2017_mod{}", binding.level)
                || function.public_api.name != function.name
                || function
                    .inputs
                    .iter()
                    .map(|i| i.name())
                    .ne(inputs[..binding.level + 1].iter().copied())
                || function
                    .outputs
                    .fields()
                    .iter()
                    .map(|f| &f.name)
                    .ne(fields.iter())
            {
                return Err(ModelError::Contract {
                    function: function.name.clone(),
                }
                .into());
            }
            levels.push(binding.level);
        }
    }
    if !levels.is_empty() {
        levels.sort_unstable();
        if levels != [2, 3, 4, 5] {
            return Err(ModelError::Contract {
                function: "rosetta3 levels".into(),
            }
            .into());
        }
    }
    Ok(())
}

pub(crate) fn render(root: &Path, entries: &[Entry]) -> Result<Option<AdapterFiles>> {
    validate(entries)?;
    let Some(entry) = entries
        .iter()
        .find(|e| e.spec.functions.iter().any(enabled))
    else {
        return Ok(None);
    };
    let artifact_path = root.join("specs/models/rosetta3/artifact.json");
    let artifact: serde_json::Value = serde_json::from_slice(&std::fs::read(&artifact_path)?)?;
    let sha = artifact["sha256"]
        .as_str()
        .filter(|sha| sha.len() == 64 && sha.bytes().all(|b| b.is_ascii_hexdigit()))
        .ok_or_else(|| ModelError::Artifact {
            path: artifact_path.clone(),
        })?;
    if artifact["format"] != "PTFKNN01" || artifact["distribution"] != "external_only" {
        return Err(ModelError::Artifact {
            path: artifact_path,
        }
        .into());
    }
    let functions: Vec<_> = entry.spec.functions.iter().filter(|f| enabled(f)).collect();
    let fields = functions[0].outputs.fields();
    let names: Vec<_> = fields.iter().map(|f| f.name.as_str()).collect();
    let mut rs_stats = String::from("#[derive(Clone, Debug)]\npub struct Rosetta3Statistics {\n");
    let mut c_stats = String::from("typedef struct {\n");
    let mut cpp_stats = String::from("struct Rosetta3Statistics {\n");
    let mut py_stats = String::from(
        "@dataclass(frozen=True)\nclass Rosetta3Statistics:\n    \"\"\"Named parameter means and sample SDs in the selected reporting scales.\"\"\"\n",
    );
    for f in fields {
        let description = f
            .description
            .replace(
                "Arithmetic ensemble mean.",
                "Ensemble mean in the selected reporting scale.",
            )
            .replace(
                "in physical parameter units.",
                "in the selected scale (physical for geometric estimates).",
            );
        writeln!(rs_stats, "/// {}\npub {}: f64,", description, f.name).unwrap();
        writeln!(c_stats, "/* {} */\ndouble {};", description, f.name).unwrap();
        writeln!(cpp_stats, "double {};", f.name).unwrap();
        writeln!(py_stats, "    {}: float", f.name).unwrap();
    }
    rs_stats.push_str("}\npub type Rosetta3ArithmeticStatistics = Rosetta3Statistics;\nimpl Rosetta3Statistics {\nfn from_values(v:[f64;14]) -> Self {Self {\n");
    for (i, name) in names.iter().enumerate() {
        writeln!(rs_stats, "{name}:v[{i}],").unwrap();
    }
    rs_stats.push_str("}}\n");
    for (method, range) in [("mean", 0..7), ("stddev", 7..14)] {
        let rs_values = names[range.clone()]
            .iter()
            .map(|n| format!("self.{n}"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(
            rs_stats,
            "pub fn {method}(&self) -> [f64;7] {{[{rs_values}]}}"
        )
        .unwrap();
        writeln!(
            cpp_stats,
            "inline std::array<double,7> {method}() const {{return {{{}}};}}",
            names[range.clone()].join(",")
        )
        .unwrap();
        writeln!(py_stats,"\n    @property\n    def {method}(self) -> tuple[float, ...]:\n        \"\"\"Parameter {method} values in the selected reporting scales.\"\"\"\n        return ({rs_values},)").unwrap();
    }
    rs_stats.push_str("}\n");
    c_stats.push_str("} ptfkit_rosetta3_statistics;\n");
    cpp_stats.push_str("};\n");
    let mut rs = include_str!("public_rosetta.rs.in")
        .replace("@SHA256@", sha)
        .replace("@STATISTICS@", &rs_stats);
    rs.push_str("\nuse crate::models::engine;\nmod contract {\n");
    rs.push_str(include_str!("rosetta.rs"));
    rs.push_str("\n}\n");
    let mut py = include_str!("public_rosetta.py.in")
        .replace("@SHA256@", sha)
        .replace("@STATISTICS@", &py_stats);
    let all_names = [
        "MODEL_SHA256",
        "Estimate",
        "Rosetta3",
        "Rosetta3ArithmeticStatistics",
        "Rosetta3Statistics",
    ]
    .into_iter()
    .map(|n| format!("'{n}'"))
    .chain(functions.iter().map(|f| format!("'{}'", f.name)))
    .collect::<Vec<_>>()
    .join(",");
    writeln!(py, "\n__all__ = [{all_names}]").unwrap();
    // The existing inference kernels are reused verbatim apart from symbol/data bindings.
    let source = include_str!("runtime.c").replace("\r\n", "\n");
    let source = source.replace("#include \"engine.h\"\n", "").replace(
        "#include \"metadata.h\"\nextern const double ptfkit_model_data[];",
        "",
    );
    let source = source
        .replace("Scale", "ptfkit_detail_scale")
        .replace("Network", "ptfkit_detail_network")
        .replace("scale_value", "ptfkit_detail_scale_value")
        .replace("network_predict", "ptfkit_detail_network_predict")
        .replace("static double ", "static inline double ")
        .replace("static void ", "static inline void ")
        .replace(
            "const ptfkit_detail_network *net, const double *x",
            "const ptfkit_detail_network *net, const double *data, const double *x",
        )
        .replace("ptfkit_model_data[", "data[");
    let (dense, rest) = source
        .split_once("static inline void stats(")
        .context("dense runtime template boundary")?;
    let c_dense = format!(
        "#ifndef PTFKIT_DETAIL_NEURAL_H\n#define PTFKIT_DETAIL_NEURAL_H\n#include <ptfkit/detail/model_api.h>\n#include <stddef.h>\n{dense}\n#endif\n"
    );
    let rest=format!("static inline void stats({rest}").replace("stats(","ptfkit_detail_stats(")
        .replace("int ptfkit_calc_ptf_zhang2017(unsigned", "static inline int ptfkit_detail_rosetta(const ptfkit_model *model, unsigned")
        .replace("const ptfkit_detail_network *net = &networks[level - 2];", "const ptfkit_detail_network *networks = model->detail_networks;\nconst ptfkit_detail_network *net = &networks[level - 2];")
        .replace("ptfkit_detail_network_predict(net, x, raw)", "ptfkit_detail_network_predict(net, model->detail_data, x, raw)")
        .replace("ptfkit_detail_network_predict(&networks[4], vg, u)", "ptfkit_detail_network_predict(&networks[4], model->detail_data, vg, u)");
    let digest = (0..32)
        .map(|i| format!("0x{}", &sha[i * 2..i * 2 + 2]))
        .collect::<Vec<_>>()
        .join(",");
    let mut c = format!(
        "#ifndef PTFKIT_ZHANG_SCHAAP2017_H\n#define PTFKIT_ZHANG_SCHAAP2017_H\n#include <ptfkit/models.h>\n#define PTFKIT_ROSETTA3_SHA256 \"{sha}\"\n{c_stats}\nstatic inline int ptfkit_rosetta3_accepts(const ptfkit_model *model) {{static const unsigned char expected[32]={{{digest}}};return model && model->detail_count==5 && !memcmp(model->detail_digest,expected,32);}}\nstatic inline ptfkit_model_status ptfkit_rosetta3_load(const char *path,ptfkit_model **out) {{return ptfkit_model_load(path,PTFKIT_ROSETTA3_SHA256,out);}}\n{rest}\nstatic inline ptfkit_model_status ptfkit_rosetta3_predict(const ptfkit_model *model,unsigned level,unsigned mode,const double *x,size_t count,double *out) {{if(!out)return PTFKIT_MODEL_INPUT;for(size_t i=0;i<14;++i)out[i]=NAN;if(!ptfkit_rosetta3_accepts(model))return PTFKIT_MODEL_INTEGRITY;return ptfkit_detail_rosetta(model,level,mode,x,count,out)?PTFKIT_MODEL_OK:PTFKIT_MODEL_INPUT;}}\n"
    );
    let cpp_values = (0..14)
        .map(|i| format!("values[{i}]"))
        .collect::<Vec<_>>()
        .join(",");
    let mut cpp = include_str!("public_rosetta.cppm.in")
        .replace("@STATISTICS@", &cpp_stats)
        .replace("@VALUES@", &cpp_values);
    for function in functions.iter() {
        let level = function
            .implementation
            .as_ref()
            .unwrap()
            .external_model
            .as_ref()
            .unwrap()
            .level;
        let args: Vec<_> = function.inputs.iter().map(|i| i.name()).collect();
        let rs_args = args
            .iter()
            .map(|n| format!("{n}:f64"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(rs,"/// {}\npub fn {}(model:&Rosetta3,{rs_args}) -> Result<Rosetta3ArithmeticStatistics,ModelError> {{model.predict({level},Estimate::Arithmetic,&[{}])}}",function.public_api.summary,function.name,args.join(",")).unwrap();
        let py_args = args
            .iter()
            .map(|n| format!("{n}: float"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(py,"\ndef {}(model: Rosetta3, *, {py_args}) -> Rosetta3ArithmeticStatistics:\n    \"\"\"{}\"\"\"\n    return model.predict({level}, [{}])",function.name,function.public_api.summary,args.join(", ")).unwrap();
        let c_args = args
            .iter()
            .map(|n| format!("double {n}"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(c,"/* {} */\nstatic inline ptfkit_model_status {}(const ptfkit_model *model,{c_args},ptfkit_rosetta3_statistics *out) {{if(!out)return PTFKIT_MODEL_INPUT;double x[]={{{}}},v[14];ptfkit_model_status status=ptfkit_rosetta3_predict(model,{level},0,x,{},v);",function.public_api.name,function.name,args.join(","),args.len()).unwrap();
        for (i, name) in names.iter().enumerate() {
            writeln!(c, "out->{name}=v[{i}];").unwrap();
        }
        c.push_str("return status;}\n");
        writeln!(cpp,"export namespace ptfkit {{inline Rosetta3Statistics {}(const Rosetta3& model,{c_args}) {{const double x[]={{{}}};return model.predict({level},Estimate::Arithmetic,x);}}}}",function.name,args.join(",")).unwrap();
    }
    c.push_str("#endif\n");
    let docs = |language: &str| {
        let mut text = format!(
            "<!-- @generated by ptfkit-codegen; DO NOT EDIT. -->\n\n# Rosetta3 {language} API\n\n{}\n\nModels are external PTFKNN01 containers. No trained parameters are distributed.\nLoad with the pinned SHA-256 `{sha}`. Missing files, digest mismatches, invalid containers and invalid predictors are errors.\n\n",
            entry.spec.source.citation_apa
        );
        text.push_str("`models.h` / `ptfkit.models` provides owned, immutable generic model loading and original-scale network prediction. Rosetta3 requires the pinned complete-container digest. C models must be freed exactly once with `ptfkit_model_free`; C++ models use move-only RAII. Never share a C handle with a thread that frees it. Predictions on a live model use no shared mutable state.\n\nRosetta3 levels are explicit. Modes 0/1/2 are arithmetic/log10/geometric. The 14 outputs are seven means then seven sample standard deviations (ddof=1), ordered theta_r, theta_s, alpha, n, Ksat, K0, L. Geometric estimates retain physical-scale SDs. Fixed-level functions use arithmetic mode; the model prediction interface exposes all three modes.\n\n");
        for f in functions.iter() {
            writeln!(text,"## `{}`\n\n{}\n\nRequires a loaded model plus {}. Returns named hydraulic means and sample SDs.\n",f.public_api.name,f.public_api.summary,f.inputs.iter().map(|i|i.name()).collect::<Vec<_>>().join(", ")).unwrap();
        }
        text.push_str("## Result fields\n\n");
        for f in fields {
            writeln!(
                text,
                "- `{}` ({}): {}",
                f.name, f.reported_unit, f.description
            )
            .unwrap();
        }
        text
    };
    Ok(Some(AdapterFiles {
        dense: c_dense,
        python: PythonAdapter {
            headers: "#include <ptfkit/zhang_schaap2017.h>".into(),
            functions: include_str!("public_rosetta_python.c").into(),
            methods: "    {\"rosetta3\", ptfkit_python_rosetta, METH_VARARGS, NULL},".into(),
            stub: "def rosetta3(handle: object, level: int, mode: int, inputs: Sequence[float]) -> tuple[float, ...]: ...\n".into(),
        },
        files: Files {
            rust: vec![
                file("zhang_schaap2017.rs", RS_HEADER, rs),
            ],
            c: vec![
                file(
                    "ptfkit/zhang_schaap2017.h",
                    C_HEADER,
                    c.replace("static inline ", "PTFKIT_MODEL_INLINE "),
                ),
            ],
            cpp: vec![
                file("zhang_schaap2017.cppm", C_HEADER, cpp),
            ],
            extension: vec![],
            python: vec![
                file("ptfkit/zhang_schaap2017.py", PY_HEADER, py),
            ],
            c_docs: vec![file("headers/zhang_schaap2017.md", "", docs("C11"))],
            cpp_docs: vec![file("modules/zhang_schaap2017.md", "", docs("C++23"))],
        },
    }))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{ExternalModel, Implementation, Input, Outputs, Parameter};
    use crate::neural::public::{render, validate};

    fn bound_entry() -> Entry {
        let mut entry = crate::test_support::entries().remove(0);
        entry.slug = "zhang_schaap2017".into();
        let template = entry.spec.functions[0].clone();
        let field = template.outputs.fields()[0].clone();
        entry.spec.functions = (2..=5)
            .map(|level| {
                let mut function = template.clone();
                function.name = format!("calc_ptf_zhang2017_mod{level}");
                function.public_api.name = function.name.clone();
                function.inputs = [
                    "sand",
                    "silt",
                    "clay",
                    "bulk_density",
                    "theta_33",
                    "theta_1500",
                ][..level + 1]
                    .iter()
                    .map(|name| {
                        Input::Parameter(Parameter {
                            name: (*name).into(),
                            unit: "1".into(),
                            domain: None,
                            description: "Controlled predictor".into(),
                        })
                    })
                    .collect();
                function.outputs = Outputs::Record {
                    name: "ControlledStatistics".into(),
                    fields: ["mean", "std"]
                        .into_iter()
                        .flat_map(|stat| {
                            PARAMETERS.map(|name| {
                                let mut f = field.clone();
                                f.name = format!("{name}_{stat}");
                                f
                            })
                        })
                        .collect(),
                };
                function.implementation = Some(Implementation {
                    variables: vec![],
                    external_model: Some(ExternalModel {
                        kind: "rosetta3".into(),
                        artifact: "../models/rosetta3/artifact.json".into(),
                        level,
                    }),
                });
                function
            })
            .collect();
        entry
    }

    #[test]
    fn external_contract_rejects_wrong_predictor_order_and_model_level() {
        let entry = bound_entry();
        validate(std::slice::from_ref(&entry)).unwrap();
        let mut swapped = entry.clone();
        swapped.spec.functions[0].inputs.swap(0, 1);
        let error = validate(&[swapped]).unwrap_err();
        assert!(
            matches!(error.downcast_ref::<ModelError>(),Some(ModelError::Contract{function}) if function=="calc_ptf_zhang2017_mod2")
        );
        let mut wrong = entry;
        wrong.spec.functions[0]
            .implementation
            .as_mut()
            .unwrap()
            .external_model
            .as_mut()
            .unwrap()
            .level = 5;
        let error = validate(&[wrong]).unwrap_err();
        assert!(
            matches!(error.downcast_ref::<ModelError>(),Some(ModelError::Contract{function}) if function=="calc_ptf_zhang2017_mod2")
        );
    }

    #[test]
    fn external_cases_use_the_existing_scientific_case_validation() {
        let mut entry = bound_entry();
        let mut case = entry.spec.functions[0].verification_cases[0].clone();
        case.id = "bad_external_case".into();
        case.inputs.clear();
        case.inputs.insert(
            "unknown_predictor".into(),
            crate::model::VerificationInput::Number(1.0),
        );
        entry.spec.functions[0].verification_cases = vec![case];
        let Err(error) = crate::compile::functions(vec![entry]) else {
            panic!("invalid external reference was accepted")
        };
        assert!(
            matches!(error,crate::compile::CompileError::UnknownInput{case_id,name} if case_id=="bad_external_case" && name=="unknown_predictor")
        );
    }

    #[test]
    fn unknown_adapter_kind_is_rejected_before_reading_artifacts() {
        let mut entry = bound_entry();
        entry.spec.functions[0]
            .implementation
            .as_mut()
            .unwrap()
            .external_model
            .as_mut()
            .unwrap()
            .kind = "unsupported-test-model".into();
        let error = match render(Path::new("missing-external-test-root"), &[entry]) {
            Err(error) => error,
            Ok(_) => panic!("unknown scientific adapter was accepted"),
        };
        assert!(
            matches!(error.downcast_ref::<ModelError>(), Some(ModelError::Contract { function }) if function == "calc_ptf_zhang2017_mod2")
        );
    }

    #[test]
    fn blocked_external_sources_do_not_render_or_read_model_descriptors() {
        let mut entry = bound_entry();
        for function in &mut entry.spec.functions {
            function.status = "blocked".into();
        }
        validate(std::slice::from_ref(&entry)).unwrap();
        assert!(
            render(Path::new("missing-external-test-root"), &[entry])
                .unwrap()
                .is_none()
        );
    }
}
