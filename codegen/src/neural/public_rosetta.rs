//! Validate and render the Rosetta3 scientific adapter for external models.
use super::{
    ModelError,
    public::{AdapterFiles, Files, PythonAdapter, enabled, file},
};
use crate::model::Entry;
use anyhow::Result;
use sha2::{Digest, Sha256};
use std::{fmt::Write as _, path::Path};

const C_HEADER: &str = "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n";
const RS_HEADER: &str = "// @generated by ptfkit-codegen; DO NOT EDIT.\n";
const PY_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n";
const PARAMETERS: [&str; 7] = ["theta_r", "theta_s", "alpha", "n", "k_sat", "k_0", "l"];

pub(crate) fn validate(entries: &[Entry]) -> Result<()> {
    let mut levels = Vec::new();
    for entry in entries {
        for function in &entry.spec.functions {
            if !enabled(function) {
                continue;
            }
            let Some(binding) = function
                .implementation
                .as_ref()
                .and_then(|i| i.external_model.as_ref())
            else {
                continue;
            };
            let fields: Vec<_> = ["mean", "std"]
                .into_iter()
                .flat_map(|stat| PARAMETERS.map(|p| format!("{p}_{stat}")))
                .collect();
            let inputs = [
                "sand",
                "silt",
                "clay",
                "bulk_density",
                "theta_33",
                "theta_1500",
            ];
            if entry.slug != "zhang_schaap2017"
                || binding.kind != "rosetta3"
                || binding.artifact != "../models/rosetta3/artifact.json"
                || function
                    .implementation
                    .as_ref()
                    .unwrap()
                    .networks
                    .values()
                    .any(|n| n.parameters.artifact != binding.artifact)
                || !(2..=5).contains(&binding.level)
                || function.name != format!("calc_ptf_zhang2017_mod{}", binding.level)
                || function.public_api.name != function.name
                || function
                    .inputs
                    .iter()
                    .map(|i| i.name())
                    .ne(inputs[..binding.level + 1].iter().copied())
                || function
                    .outputs
                    .fields()
                    .iter()
                    .map(|f| &f.name)
                    .ne(fields.iter())
            {
                return Err(ModelError::Contract {
                    function: function.name.clone(),
                }
                .into());
            }
            levels.push(binding.level);
        }
    }
    if !levels.is_empty() {
        levels.sort_unstable();
        if levels != [2, 3, 4, 5] {
            return Err(ModelError::Contract {
                function: "rosetta3 levels".into(),
            }
            .into());
        }
    }
    Ok(())
}

pub(crate) fn render(root: &Path, entries: &[Entry]) -> Result<Option<AdapterFiles>> {
    validate(entries)?;
    let Some(entry) = entries
        .iter()
        .find(|e| e.spec.functions.iter().any(enabled))
    else {
        return Ok(None);
    };
    let artifact_path = root.join("specs/models/rosetta3/artifact.json");
    let artifact: serde_json::Value = serde_json::from_slice(&std::fs::read(&artifact_path)?)?;
    let sha = artifact["sha256"]
        .as_str()
        .filter(|sha| sha.len() == 64 && sha.bytes().all(|b| b.is_ascii_hexdigit()))
        .ok_or_else(|| ModelError::Artifact {
            path: artifact_path.clone(),
        })?;
    if artifact["format"] != "PTFKNN01"
        || artifact["distribution"] != "bundled"
        || artifact["artifact"] != "rosetta3.ptfm"
        || artifact["license"] != "CC0-1.0"
    {
        return Err(ModelError::Artifact {
            path: artifact_path,
        }
        .into());
    }
    let data = std::fs::read(root.join("specs/models/rosetta3/rosetta3.ptfm"))?;
    if Sha256::digest(&data)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect::<String>()
        != sha
        || artifact["bytes"].as_u64() != Some(data.len() as u64)
        || !data.starts_with(b"PTFKNN01")
    {
        return Err(ModelError::Artifact {
            path: artifact_path,
        }
        .into());
    }
    super::parameters::decode(entry, &data)?;
    let computation = super::computation::render(entry)?;
    let functions: Vec<_> = entry.spec.functions.iter().filter(|f| enabled(f)).collect();
    let fields = functions[0].outputs.fields();
    let names: Vec<_> = fields.iter().map(|f| f.name.as_str()).collect();
    let mut rs_stats = String::from("#[derive(Clone, Debug)]\npub struct Rosetta3Statistics {\n");
    let mut c_stats = String::from("typedef struct {\n");
    let mut cpp_stats = String::from("struct Rosetta3Statistics {\n");
    let mut py_stats = String::from(
        "class Rosetta3Statistics(NamedTuple, Generic[T_co]):\n    \"\"\"Named parameter means and sample SDs in the selected reporting scales.\"\"\"\n",
    );
    for f in fields {
        let description = f
            .description
            .replace(
                "Arithmetic ensemble mean.",
                "Ensemble mean in the selected reporting scale.",
            )
            .replace(
                "in physical parameter units.",
                "in the selected scale (physical for geometric estimates).",
            );
        writeln!(rs_stats, "/// {}\npub {}: f64,", description, f.name).unwrap();
        writeln!(c_stats, "/* {} */\ndouble {};", description, f.name).unwrap();
        writeln!(cpp_stats, "double {};", f.name).unwrap();
        writeln!(py_stats, "    {}: T_co", f.name).unwrap();
    }
    rs_stats.push_str("}\npub type Rosetta3ArithmeticStatistics = Rosetta3Statistics;\nimpl Rosetta3Statistics {\nfn from_values(v:[f64;14]) -> Self {Self {\n");
    for (i, name) in names.iter().enumerate() {
        writeln!(rs_stats, "{name}:v[{i}],").unwrap();
    }
    rs_stats.push_str("}}\n");
    for (method, range) in [("mean", 0..7), ("stddev", 7..14)] {
        let rs_values = names[range.clone()]
            .iter()
            .map(|n| format!("self.{n}"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(
            rs_stats,
            "pub fn {method}(&self) -> [f64;7] {{[{rs_values}]}}"
        )
        .unwrap();
        writeln!(
            cpp_stats,
            "inline std::array<double,7> {method}() const {{return {{{}}};}}",
            names[range.clone()].join(",")
        )
        .unwrap();
        writeln!(py_stats,"\n    @property\n    def {method}(self) -> tuple[T_co, ...]:\n        \"\"\"Parameter {method} values in the selected reporting scales.\"\"\"\n        return ({rs_values},)").unwrap();
    }
    rs_stats.push_str("}\n");
    c_stats.push_str("} ptfkit_rosetta3_statistics;\n");
    cpp_stats.push_str("};\n");
    let mut rs = include_str!("public_rosetta.rs.in")
        .replace("@SHA256@", sha)
        .replace("@STATISTICS@", &rs_stats);
    rs.push_str("\nuse crate::models::engine;\nmod contract {\n");
    rs.push_str(&computation.rust);
    rs.push_str("\n}\n");
    let mut py = include_str!("public_rosetta.py.in")
        .replace("@SHA256@", sha)
        .replace("@STATISTICS@", &py_stats);
    let all_names = [
        "MODEL_SHA256",
        "Estimate",
        "Rosetta3",
        "Rosetta3ArithmeticStatistics",
        "Rosetta3Statistics",
    ]
    .into_iter()
    .map(|n| format!("'{n}'"))
    .collect::<Vec<_>>()
    .join(",");
    writeln!(py, "\n__all__ = [{all_names}]").unwrap();
    let c_dense = format!(
        "#include <ptfkit/detail/model_api.h>\n{}",
        include_str!("dense.h")
    );
    let rest = &computation.c;
    let digest = (0..32)
        .map(|i| format!("0x{}", &sha[i * 2..i * 2 + 2]))
        .collect::<Vec<_>>()
        .join(",");
    let mut c = format!(
        "#ifndef PTFKIT_ZHANG_SCHAAP2017_H\n#define PTFKIT_ZHANG_SCHAAP2017_H\n#include <ptfkit/models.h>\n#define PTFKIT_ROSETTA3_SHA256 \"{sha}\"\n{c_stats}\nstatic inline int ptfkit_rosetta3_accepts(const ptfkit_model *model) {{static const unsigned char expected[32]={{{digest}}};return model && model->detail_count==5 && !memcmp(model->detail_digest,expected,32);}}\nstatic inline ptfkit_model_status ptfkit_rosetta3_load(const char *path,ptfkit_model **out) {{return ptfkit_model_load(path,PTFKIT_ROSETTA3_SHA256,out);}}\n{rest}\nstatic inline ptfkit_model_status ptfkit_rosetta3_predict(const ptfkit_model *model,unsigned level,unsigned mode,const double *x,size_t count,double *out) {{if(!out)return PTFKIT_MODEL_INPUT;for(size_t i=0;i<14;++i)out[i]=NAN;if(!ptfkit_rosetta3_accepts(model))return PTFKIT_MODEL_INTEGRITY;return ptfkit_detail_rosetta(model->detail_networks,model->detail_data,level,mode,x,count,out)?PTFKIT_MODEL_OK:PTFKIT_MODEL_INPUT;}}\n"
    );
    let builtin = "\n#ifdef __cplusplus\nextern \"C\" {\n#endif\nptfkit_model_status ptfkit_detail_rosetta3_builtin(ptfkit_model **out);\n#ifdef __cplusplus\n}\n#endif\nstatic inline ptfkit_model_status ptfkit_rosetta3_builtin(ptfkit_model **out) {return ptfkit_detail_rosetta3_builtin(out);}\n";
    c.push_str(builtin);
    let cpp_values = (0..14)
        .map(|i| format!("values[{i}]"))
        .collect::<Vec<_>>()
        .join(",");
    let mut cpp = include_str!("public_rosetta.cppm.in")
        .replace("@STATISTICS@", &cpp_stats)
        .replace("@VALUES@", &cpp_values);
    let mut py_methods = String::new();
    let mut rs_methods = String::new();
    let mut cpp_methods = String::new();
    for function in functions.iter() {
        let level = function
            .implementation
            .as_ref()
            .unwrap()
            .external_model
            .as_ref()
            .unwrap()
            .level;
        let args: Vec<_> = function.inputs.iter().map(|i| i.name()).collect();
        let rs_args = args
            .iter()
            .map(|n| format!("{n}:f64"))
            .collect::<Vec<_>>()
            .join(",");
        let py_args = args
            .iter()
            .map(|n| format!("{n}: ArrayLike"))
            .collect::<Vec<_>>()
            .join(", ");
        let scalar_args = args
            .iter()
            .map(|n| format!("{n}: float"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(py_methods,"    @overload\n    def {}(self, *, {scalar_args}, estimate: Estimate = Estimate.ARITHMETIC) -> Rosetta3Statistics[float]: ...\n\n    @overload\n    def {}(self, *, {py_args}, estimate: Estimate = Estimate.ARITHMETIC, out: Rosetta3Statistics[NDArray[floating]] | None = None) -> Rosetta3Statistics[NDArray[floating]]: ...\n", function.name, function.name).unwrap();
        writeln!(py_methods,"    def {}(self, *, {py_args}, estimate: Estimate = Estimate.ARITHMETIC, out: Rosetta3Statistics[NDArray[floating]] | None = None) -> Rosetta3Statistics[float] | Rosetta3Statistics[NDArray[floating]]:\n        \"\"\"{}\"\"\"\n        return self._predict({level}, [{}], estimate, out)\n",function.name,function.public_api.summary,args.join(", ")).unwrap();
        writeln!(rs_methods,"/// {}\npub fn {}(&self,{rs_args},estimate:Estimate) -> Result<Rosetta3Statistics,ModelError> {{self.predict({level},estimate,&[{}])}}",function.public_api.summary,function.name,args.join(",")).unwrap();
        let c_args = args
            .iter()
            .map(|n| format!("double {n}"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(c,"/* {} */\nstatic inline ptfkit_model_status {}(const ptfkit_model *model,{c_args},ptfkit_rosetta3_statistics *out) {{if(!out)return PTFKIT_MODEL_INPUT;double x[]={{{}}},v[14];ptfkit_model_status status=ptfkit_rosetta3_predict(model,{level},0,x,{},v);",function.public_api.name,function.name,args.join(","),args.len()).unwrap();
        for (i, name) in names.iter().enumerate() {
            writeln!(c, "out->{name}=v[{i}];").unwrap();
        }
        c.push_str("return status;}\n");
        writeln!(cpp_methods,"inline Rosetta3Statistics {}({c_args},Estimate estimate=Estimate::Arithmetic) const {{const double x[]={{{}}};return predict({level},estimate,x);}}",function.name,args.join(",")).unwrap();
    }
    py = py.replace("@METHODS@", &py_methods);
    rs = rs.replace("@METHODS@", &rs_methods);
    cpp = cpp.replace("@METHODS@", &cpp_methods);
    c.push_str("#endif\n");
    let docs = |language: &str| {
        let mut text = format!(
            "<!-- @generated by ptfkit-codegen; DO NOT EDIT. -->\n\n# Rosetta3 {language} API\n\n{}\n\nThe reviewed CC0 model is bundled. Use `ptfkit_rosetta3_builtin` (C) or `Rosetta3::builtin` (C++) without a file. External PTFKNN01 loading remains available with pinned SHA-256 `{sha}`. Invalid predictors, containers and digest mismatches are errors.\n\n",
            entry.spec.source.citation_apa
        );
        text.push_str("`models.h` / `ptfkit.models` provides owned, immutable generic model loading and original-scale network prediction. Rosetta3 requires the pinned complete-container digest. C models must be freed exactly once with `ptfkit_model_free`; C++ models use move-only RAII. Never share a C handle with a thread that frees it. Predictions on a live model use no shared mutable state.\n\nRosetta3 levels are explicit. Modes 0/1/2 are arithmetic/log10/geometric. The 14 outputs are seven means then seven sample standard deviations (ddof=1), ordered theta_r, theta_s, alpha, n, Ksat, K0, L. Geometric estimates retain physical-scale SDs. Named Rust/C++/Python methods expose all three modes through Estimate; C functions use arithmetic estimates, with ptfkit_rosetta3_predict for explicit modes.\n\n");
        for f in functions.iter() {
            writeln!(text,"## `{}`\n\n{}\n\nRequires a loaded model plus {}. Returns named hydraulic means and sample SDs.\n",f.public_api.name,f.public_api.summary,f.inputs.iter().map(|i|i.name()).collect::<Vec<_>>().join(", ")).unwrap();
        }
        text.push_str("## Result fields\n\n");
        for f in fields {
            writeln!(
                text,
                "- `{}` ({}): {}",
                f.name, f.reported_unit, f.description
            )
            .unwrap();
        }
        text
    };
    Ok(Some(AdapterFiles {
        dense: c_dense,
        python: PythonAdapter {
            headers: "#include <ptfkit/zhang_schaap2017.h>".into(),
            functions: include_str!("public_rosetta_python.c").into(),
            methods: "    {\"rosetta3_batch\", ptfkit_python_rosetta_batch, METH_VARARGS, NULL},\n    {\"rosetta3\", ptfkit_python_rosetta, METH_VARARGS, NULL},\n    {\"rosetta3_builtin\", ptfkit_python_rosetta_builtin, METH_NOARGS, NULL},".into(),
            stub: "def rosetta3_batch(handle: object, level: int, mode: int, inputs: Sequence[object], outputs: Sequence[object]) -> None: ...\ndef rosetta3(handle: object, level: int, mode: int, inputs: Sequence[float]) -> tuple[float, ...]: ...\ndef rosetta3_builtin() -> object: ...\n".into(),
        },
        files: Files {
            rust_data: vec![],
            c_sources: vec![],
            rust: vec![
                file("zhang_schaap2017.rs", RS_HEADER, rs),
            ],
            c: vec![
                file(
                    "ptfkit/zhang_schaap2017.h",
                    C_HEADER,
                    c.replace("static inline ", "PTFKIT_MODEL_INLINE "),
                ),
            ],
            cpp: vec![
                file("zhang_schaap2017.cppm", C_HEADER, cpp),
            ],
            extension: vec![],
            python: vec![
                file("ptfkit/zhang_schaap2017.py", PY_HEADER, py),
            ],
            c_docs: vec![file("headers/zhang_schaap2017.md", "", docs("C11"))],
            cpp_docs: vec![file("modules/zhang_schaap2017.md", "", docs("C++23"))],
        },
    }))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{ExternalModel, Implementation, Input, Outputs, Parameter};
    use crate::neural::public::{render, validate};

    fn bound_entry() -> Entry {
        let mut entry = crate::test_support::entries().remove(0);
        entry.slug = "zhang_schaap2017".into();
        let template = entry.spec.functions[0].clone();
        let field = template.outputs.fields()[0].clone();
        entry.spec.functions = (2..=5)
            .map(|level| {
                let mut function = template.clone();
                function.name = format!("calc_ptf_zhang2017_mod{level}");
                function.public_api.name = function.name.clone();
                function.inputs = [
                    "sand",
                    "silt",
                    "clay",
                    "bulk_density",
                    "theta_33",
                    "theta_1500",
                ][..level + 1]
                    .iter()
                    .map(|name| {
                        Input::Parameter(Parameter {
                            name: (*name).into(),
                            unit: "1".into(),
                            domain: None,
                            description: "Controlled predictor".into(),
                        })
                    })
                    .collect();
                function.outputs = Outputs::Record {
                    name: "ControlledStatistics".into(),
                    fields: ["mean", "std"]
                        .into_iter()
                        .flat_map(|stat| {
                            PARAMETERS.map(|name| {
                                let mut f = field.clone();
                                f.name = format!("{name}_{stat}");
                                f
                            })
                        })
                        .collect(),
                };
                function.implementation = Some(Implementation {
                    networks: Default::default(),
                    variables: vec![],
                    external_model: Some(ExternalModel {
                        kind: "rosetta3".into(),
                        artifact: "../models/rosetta3/artifact.json".into(),
                        level,
                    }),
                });
                function
            })
            .collect();
        entry
    }

    #[test]
    fn external_contract_rejects_wrong_predictor_order_and_model_level() {
        let entry = bound_entry();
        validate(std::slice::from_ref(&entry)).unwrap();
        let mut swapped = entry.clone();
        swapped.spec.functions[0].inputs.swap(0, 1);
        let error = validate(&[swapped]).unwrap_err();
        assert!(
            matches!(error.downcast_ref::<ModelError>(),Some(ModelError::Contract{function}) if function=="calc_ptf_zhang2017_mod2")
        );
        let mut wrong = entry;
        wrong.spec.functions[0]
            .implementation
            .as_mut()
            .unwrap()
            .external_model
            .as_mut()
            .unwrap()
            .level = 5;
        let error = validate(&[wrong]).unwrap_err();
        assert!(
            matches!(error.downcast_ref::<ModelError>(),Some(ModelError::Contract{function}) if function=="calc_ptf_zhang2017_mod2")
        );
    }

    #[test]
    fn external_cases_use_the_existing_scientific_case_validation() {
        let mut entry = bound_entry();
        let mut case = entry.spec.functions[0].verification_cases[0].clone();
        case.id = "bad_external_case".into();
        case.inputs.clear();
        case.inputs.insert(
            "unknown_predictor".into(),
            crate::model::VerificationInput::Number(1.0),
        );
        entry.spec.functions[0].verification_cases = vec![case];
        let Err(error) = crate::compile::functions(vec![entry]) else {
            panic!("invalid external reference was accepted")
        };
        assert!(
            matches!(error,crate::compile::CompileError::UnknownInput{case_id,name} if case_id=="bad_external_case" && name=="unknown_predictor")
        );
    }

    #[test]
    fn unknown_adapter_kind_is_rejected_before_reading_artifacts() {
        let mut entry = bound_entry();
        entry.spec.functions[0]
            .implementation
            .as_mut()
            .unwrap()
            .external_model
            .as_mut()
            .unwrap()
            .kind = "unsupported-test-model".into();
        let error = match render(Path::new("missing-external-test-root"), &[entry]) {
            Err(error) => error,
            Ok(_) => panic!("unknown scientific adapter was accepted"),
        };
        assert!(
            matches!(error.downcast_ref::<ModelError>(), Some(ModelError::Contract { function }) if function == "calc_ptf_zhang2017_mod2")
        );
    }

    #[test]
    fn bundled_artifact_digest_is_checked_before_rendering() {
        let root = crate::test_support::fixture_root("corrupt-bundled-model");
        let directory = root.join("specs/models/rosetta3");
        std::fs::create_dir_all(&directory).unwrap();
        std::fs::write(
            directory.join("artifact.json"),
            serde_json::to_vec(&serde_json::json!({
                "format":"PTFKNN01", "distribution":"bundled", "artifact":"rosetta3.ptfm",
                "license":"CC0-1.0", "bytes":8, "sha256":"0".repeat(64)
            }))
            .unwrap(),
        )
        .unwrap();
        std::fs::write(directory.join("rosetta3.ptfm"), b"PTFKNN01").unwrap();
        let error = match render(&root, &[bound_entry()]) {
            Err(error) => error,
            Ok(_) => panic!("unauthenticated bundled data was rendered"),
        };
        assert!(matches!(
            error.downcast_ref::<ModelError>(),
            Some(ModelError::Artifact { .. })
        ));
    }

    #[test]
    fn blocked_external_sources_do_not_render_or_read_model_descriptors() {
        let mut entry = bound_entry();
        for function in &mut entry.spec.functions {
            function.status = "blocked".into();
        }
        validate(std::slice::from_ref(&entry)).unwrap();
        assert!(
            render(Path::new("missing-external-test-root"), &[entry])
                .unwrap()
                .is_none()
        );
    }
}
