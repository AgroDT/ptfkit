//! Verification cases exercise explicitly initialized public calculation methods.
use super::public::Files;
use crate::{
    model::{CompiledInput, Entry},
    output::GeneratedFile,
};
use std::fmt::Write as _;

pub(super) fn render(
    entry: &Entry,
    class: &str,
    prefix: &str,
    files: &mut Files,
) -> anyhow::Result<String> {
    let slug = &entry.slug;
    let mut rust = String::from(
        "#[cfg(test)] mod tests {use super::*;use crate::test_support::assert_close;\n#[test]fn bundled_instances_share_weights(){let a=bundled::builtin();let b=bundled::builtin();assert!(std::ptr::eq(a.data,b.data));}\n",
    );
    let mut c = format!(
        "#include <ptfkit/{slug}.h>\n#include \"support/close_enough.h\"\nint main(void){{ptfkit_model *model=NULL;if(ptfkit_{prefix}_builtin(&model)!=PTFKIT_MODEL_OK)return 1;ptfkit_model *other=NULL;if(ptfkit_{prefix}_builtin(&other)!=PTFKIT_MODEL_OK)return 2;if(model->detail_data!=other->detail_data||model->detail_networks!=other->detail_networks)return 3;ptfkit_{prefix}_free(other);\n"
    );
    let mut cpp = format!(
        "#include \"support/close_enough.h\"\nimport ptfkit.{slug};\nint main(){{auto model=ptfkit::{class}::builtin();\n"
    );
    for function in crate::compile::functions(vec![entry.clone()])?
        .iter()
        .filter(|f| super::public::enabled(&entry.spec.functions[f.function_index]))
    {
        for (index, case) in function.verification_cases.iter().enumerate() {
            let args = case
                .inputs
                .iter()
                .map(|i| match i {
                    CompiledInput::Number(v) => format!("{v:?}"),
                    _ => unreachable!("dense inputs are numeric"),
                })
                .collect::<Vec<_>>()
                .join(",");
            let name = &function.core.name;
            writeln!(
                rust,
                "#[test]fn {name}_case_{index}(){{let model={class}::builtin().unwrap();let result=model.{name}({args},Estimate::Arithmetic).unwrap();"
            )?;
            writeln!(
                c,
                "{{ptfkit_{prefix}_statistics result;if({name}(model,{args},&result)!=PTFKIT_MODEL_OK)return 4;"
            )?;
            writeln!(cpp, "{{auto result=model.{name}({args});")?;
            for ((field, expected), tolerance) in entry.spec.functions[function.function_index]
                .outputs
                .fields()
                .iter()
                .zip(&case.expected)
                .zip(&function.output_tolerances)
            {
                let absolute = tolerance.absolute;
                let relative = tolerance.relative;
                let quantity = &tolerance.quantity;
                let unit = &tolerance.unit;
                let source = match &tolerance.source {
                    crate::model::ToleranceSource::Registry => "registry".to_owned(),
                    crate::model::ToleranceSource::SourceOverride(s) => {
                        format!("source override: {s}")
                    }
                };
                writeln!(
                    rust,
                    "assert_close(result.{},{expected:?},{absolute:?},{relative:?},{quantity:?},{unit:?},{source:?});",
                    field.name
                )?;
                let assertion = format!(
                    "assert_close(result.{},{expected:?},{absolute:?},{relative:?},{quantity:?},{unit:?},{source:?},{:?});\n",
                    field.name, case.id
                );
                c.push_str(&assertion);
                cpp.push_str(&assertion);
            }
            rust.push_str("}\n");
            c.push_str("}\n");
            cpp.push_str("}\n");
        }
    }
    rust.push_str("}\n");
    writeln!(c, "ptfkit_{prefix}_free(model);return 0;}}")?;
    cpp.push_str("return 0;}\n");
    files.c_tests.push(GeneratedFile::new(
        format!("{slug}.c").into(),
        format!("/* @generated by ptfkit-codegen; DO NOT EDIT. */\n{c}"),
    ));
    files.cpp_tests.push(GeneratedFile::new(
        format!("{slug}.cpp").into(),
        format!("/* @generated by ptfkit-codegen; DO NOT EDIT. */\n{cpp}"),
    ));
    Ok(rust)
}
