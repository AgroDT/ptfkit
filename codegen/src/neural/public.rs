//! Shared external-model targets and dispatch to scientific adapters.
use super::{ModelError, public_rosetta};
use crate::{model::Entry, output::GeneratedFile};
use anyhow::Result;
use std::path::Path;

const C_HEADER: &str = "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n";
const RS_HEADER: &str = "// @generated by ptfkit-codegen; DO NOT EDIT.\n";
const PY_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n";

pub(crate) fn enabled(function: &crate::model::Function) -> bool {
    matches!(
        function.status.as_str(),
        "implemented" | "ready-for-implementation"
    ) && function
        .implementation
        .as_ref()
        .is_some_and(|i| i.external_model.is_some())
}

pub(crate) fn validate(entries: &[Entry]) -> Result<()> {
    for function in entries
        .iter()
        .flat_map(|e| &e.spec.functions)
        .filter(|f| enabled(f))
    {
        let binding = function
            .implementation
            .as_ref()
            .unwrap()
            .external_model
            .as_ref()
            .unwrap();
        match binding.kind.as_str() {
            "rosetta3" => {}
            _ => {
                return Err(ModelError::Contract {
                    function: function.name.clone(),
                }
                .into());
            }
        }
    }
    public_rosetta::validate(entries)
}

#[derive(Default)]
pub(crate) struct Files {
    pub(crate) rust: Vec<GeneratedFile>,
    pub(crate) c: Vec<GeneratedFile>,
    pub(crate) cpp: Vec<GeneratedFile>,
    pub(crate) extension: Vec<GeneratedFile>,
    pub(crate) python: Vec<GeneratedFile>,
    pub(crate) c_docs: Vec<GeneratedFile>,
    pub(crate) cpp_docs: Vec<GeneratedFile>,
}

impl Files {
    fn append(&mut self, other: Self) {
        self.rust.extend(other.rust);
        self.c.extend(other.c);
        self.cpp.extend(other.cpp);
        self.extension.extend(other.extension);
        self.python.extend(other.python);
        self.c_docs.extend(other.c_docs);
        self.cpp_docs.extend(other.cpp_docs);
    }
}

/// Native method registrations supplied by a scientific adapter, not the loader.
#[derive(Default)]
pub(super) struct PythonAdapter {
    pub(super) headers: String,
    pub(super) functions: String,
    pub(super) methods: String,
    pub(super) stub: String,
}

pub(super) struct AdapterFiles {
    pub(super) files: Files,
    /// Shared dense interpreter extracted from the preserved local runtime.
    pub(super) dense: String,
    pub(super) python: PythonAdapter,
}

pub(super) fn file(path: &str, header: &str, body: impl AsRef<str>) -> GeneratedFile {
    GeneratedFile::new(
        path.into(),
        format!("{header}{}", body.as_ref().replace("\r\n", "\n")),
    )
}

pub(crate) fn render(root: &Path, entries: &[Entry]) -> Result<Option<Files>> {
    validate(entries)?;
    let Some(adapter) = public_rosetta::render(root, entries)? else {
        return Ok(None);
    };
    let mut files = render_models(&adapter.dense, &adapter.python);
    files.append(adapter.files);
    Ok(Some(files))
}

/// Render generic owned loaders without inspecting publications or artifacts.
fn render_models(dense: &str, adapter: &PythonAdapter) -> Files {
    let bridge = include_str!("public_python.c.in")
        .replace("@ADAPTER_HEADERS@", &adapter.headers)
        .replace("@ADAPTER_FUNCTIONS@", &adapter.functions)
        .replace("@ADAPTER_METHODS@", &adapter.methods);
    let stub = concat!(
        "from collections.abc import Sequence\n\n",
        "ModelIntegrityError: type[ValueError]\nModelInputError: type[ValueError]\nModelFormatError: type[ValueError]\n",
        "def from_bytes(data: bytes, sha256: str) -> object: ...\n",
        "def sha256(handle: object) -> str: ...\n",
        "def network_count(handle: object) -> int: ...\n",
        "def network_shape(handle: object, index: int) -> tuple[int, int, int]: ...\n",
        "def predict_network(handle: object, index: int, inputs: Sequence[float]) -> list[tuple[float, ...]]: ...\n",
    ).to_owned() + &adapter.stub;
    Files {
        rust: vec![
            file("models.rs", RS_HEADER, include_str!("public_models.rs.in")),
            file("detail/neural.rs", RS_HEADER, include_str!("engine.rs")),
        ],
        c: vec![
            file(
                "ptfkit/detail/model_api.h",
                C_HEADER,
                include_str!("public_model_api.h"),
            ),
            file(
                "ptfkit/detail/neural.h",
                C_HEADER,
                dense.replace("static inline ", "PTFKIT_MODEL_INLINE "),
            ),
            file(
                "ptfkit/detail/sha256.h",
                C_HEADER,
                include_str!("public_sha256.h"),
            ),
            file("ptfkit/models.h", C_HEADER, include_str!("public_models.h")),
        ],
        cpp: vec![file(
            "models.cppm",
            C_HEADER,
            include_str!("public_models.cppm.in"),
        )],
        extension: vec![file("src/ptfkit/models.c", C_HEADER, bridge)],
        python: vec![
            file(
                "ptfkit/models.py",
                PY_HEADER,
                include_str!("public_models.py.in"),
            ),
            file("ptfkit/_models.pyi", PY_HEADER, stub),
        ],
        ..Files::default()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generic_targets_do_not_require_a_scientific_adapter() {
        let files = render_models(
            "/* controlled dense runtime */\n",
            &PythonAdapter::default(),
        );
        for file in files
            .rust
            .iter()
            .chain(&files.c)
            .chain(&files.cpp)
            .chain(&files.extension)
            .chain(&files.python)
        {
            assert!(
                !file.contents.contains("zhang_schaap2017"),
                "{}",
                file.path.display()
            );
            assert!(
                !file.contents.to_lowercase().contains("rosetta"),
                "{}",
                file.path.display()
            );
            assert!(
                !file.contents.contains("@ADAPTER_"),
                "{}",
                file.path.display()
            );
        }
        let bridge = &files.extension[0].contents;
        assert!(bridge.contains("#include <ptfkit/models.h>"));
        assert!(
            bridge.contains("{\"predict_network\", ptfkit_python_predict, METH_VARARGS, NULL}")
        );
    }
}
