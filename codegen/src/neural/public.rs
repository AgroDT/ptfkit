//! Dense backend selected by declared implementation operations.
use crate::{
    model::{Entry, Function, ImplementationVariable},
    output::GeneratedFile,
};
use anyhow::Result;
use convert_case::{Case, Casing};
use std::{fmt::Write as _, path::Path};

const C_HEADER: &str = "/* @generated by ptfkit-codegen; DO NOT EDIT. */\n";
const RS_HEADER: &str = "// @generated by ptfkit-codegen; DO NOT EDIT.\n";
const PY_HEADER: &str = "# @generated by ptfkit-codegen; DO NOT EDIT.\n";

pub(crate) fn enabled(function: &Function) -> bool {
    matches!(
        function.status.as_str(),
        "implemented" | "ready-for-implementation"
    ) && function.implementation.as_ref().is_some_and(|i| {
        i.variables
            .iter()
            .any(|v| matches!(v, ImplementationVariable::Neural { .. }))
    })
}

pub(crate) fn validate(entries: &[Entry]) -> Result<()> {
    for entry in entries {
        let functions = entry
            .spec
            .functions
            .iter()
            .filter(|f| enabled(f))
            .collect::<Vec<_>>();
        if let Some(first) = functions.first() {
            for f in &functions {
                if f.outputs.fields().is_empty()
                    || f.outputs.fields().iter().map(|f| &f.name).ne(first
                        .outputs
                        .fields()
                        .iter()
                        .map(|f| &f.name))
                {
                    return Err(super::ModelError::Contract {
                        function: f.name.clone(),
                    }
                    .into());
                }
            }
        }
    }
    Ok(())
}

#[derive(Default)]
pub(crate) struct Files {
    pub(crate) rust: Vec<GeneratedFile>,
    pub(crate) c: Vec<GeneratedFile>,
    pub(crate) cpp: Vec<GeneratedFile>,
    pub(crate) extension: Vec<GeneratedFile>,
    pub(crate) python: Vec<GeneratedFile>,
    pub(crate) c_docs: Vec<GeneratedFile>,
    pub(crate) cpp_docs: Vec<GeneratedFile>,
    pub(crate) c_tests: Vec<GeneratedFile>,
    pub(crate) cpp_tests: Vec<GeneratedFile>,
}
fn file(path: impl Into<std::path::PathBuf>, header: &str, body: impl AsRef<str>) -> GeneratedFile {
    GeneratedFile::new(
        path.into(),
        format!("{header}{}", body.as_ref().replace("\r\n", "\n")),
    )
}

pub(crate) fn render(_root: &Path, entries: &[Entry]) -> Result<Option<Files>> {
    validate(entries)?;
    if !entries.iter().any(|e| e.spec.functions.iter().any(enabled)) {
        return Ok(None);
    }
    let mut files = Files::default();
    files.rust.push(file(
        "models.rs",
        RS_HEADER,
        include_str!("public_models.rs.in"),
    ));
    files.rust.push(file(
        "detail/neural.rs",
        RS_HEADER,
        include_str!("engine.rs"),
    ));
    files.c.push(file(
        "ptfkit/detail/model_api.h",
        C_HEADER,
        include_str!("public_model_api.h"),
    ));
    files.c.push(file(
        "ptfkit/detail/neural.h",
        C_HEADER,
        include_str!("dense.h"),
    ));
    files.c.push(file(
        "ptfkit/detail/models.h",
        C_HEADER,
        include_str!("public_models.h"),
    ));
    files.cpp.push(file(
        "detail_neural.cppm",
        C_HEADER,
        r#"module;
#include <stdexcept>
export module ptfkit.detail.neural;
export namespace ptfkit {
enum class Estimate : unsigned { Arithmetic=0,Log10=1,Geometric=2 };
class ModelError : public std::runtime_error {
public:
    ModelError() : std::runtime_error("invalid predictors or estimate mode") {}
};
}
"#,
    ));
    for entry in entries
        .iter()
        .filter(|e| e.spec.functions.iter().any(enabled))
    {
        // Generation and preparation share the same parameter resolution and validation.
        super::parameters::load(entry)?;
        render_entry(entry, &mut files)?;
    }
    Ok(Some(files))
}

fn render_entry(entry: &Entry, files: &mut Files) -> Result<()> {
    let slug = &entry.slug;
    let default_class = entry.slug.to_case(Case::Pascal);
    let class = entry
        .spec
        .generation
        .model_class
        .as_deref()
        .unwrap_or(&default_class);
    let prefix = class.to_lowercase();
    let functions = entry
        .spec
        .functions
        .iter()
        .enumerate()
        .filter(|(_, f)| enabled(f))
        .collect::<Vec<_>>();
    let result = functions[0].1.result_class().unwrap();
    let fields = functions[0].1.outputs.fields();
    let size = fields.len();
    let mut rs_stats = format!("#[derive(Clone,Debug)]\npub struct {result} {{\n");
    let mut c_stats = String::from("typedef struct {\n");
    let mut cpp_stats = format!("struct {result} {{\n");
    let mut py_stats = format!(
        "class {result}(NamedTuple, Generic[T_co]):\n    \"\"\"Named calculation results.\"\"\"\n"
    );
    for f in fields {
        writeln!(rs_stats, "/// {}\npub {}: f64,", f.description, f.name)?;
        writeln!(c_stats, "/* {} */\ndouble {};", f.description, f.name)?;
        writeln!(cpp_stats, "double {};", f.name)?;
        writeln!(py_stats, "    {}: T_co", f.name)?;
    }
    rs_stats.push_str("}\n");
    writeln!(
        rs_stats,
        "impl {result} {{fn from_values(v:[f64;{size}])->Self{{Self{{"
    )?;
    for (i, f) in fields.iter().enumerate() {
        writeln!(rs_stats, "{}:v[{i}],", f.name)?;
    }
    rs_stats.push_str("}}\n");
    for (method, suffix) in [("mean", "_mean"), ("stddev", "_std")] {
        let names = fields
            .iter()
            .filter(|f| f.name.ends_with(suffix))
            .map(|f| f.name.as_str())
            .collect::<Vec<_>>();
        if names.is_empty() {
            continue;
        }
        let len = names.len();
        let values = names
            .iter()
            .map(|n| format!("self.{n}"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(
            rs_stats,
            "pub fn {method}(&self)->[f64;{len}]{{[{values}]}}"
        )?;
        writeln!(
            cpp_stats,
            "inline std::array<double,{len}> {method}() const {{return {{{}}};}}",
            names.join(",")
        )?;
        writeln!(
            py_stats,
            "\n    @property\n    def {method}(self) -> tuple[T_co, ...]:\n        \"\"\"Selected result fields in declaration order.\"\"\"\n        return ({values},)"
        )?;
    }
    rs_stats.push_str("}\n");
    writeln!(c_stats, "}} ptfkit_{prefix}_statistics;")?;
    cpp_stats.push_str("};\n");
    let mut rs = format!(
        "//! Bundled dense calculation methods.\nuse crate::models::{{Model,engine}};\npub use crate::models::ModelError;\nmod bundled{{include!(\"prepared/{slug}.rs\");}}\n#[derive(Clone,Copy,Debug)]\n#[repr(usize)]\npub enum Estimate{{Arithmetic=0,Log10=1,Geometric=2}}\n{rs_stats}\n#[derive(Debug)]\npub struct {class}{{model:Model}}\nimpl {class}{{\n/// Initialize shared immutable bundled parameters.\npub fn builtin()->Result<Self,ModelError>{{Ok(Self{{model:bundled::builtin()}})}}\n"
    );
    let mut c = format!(
        "#ifndef PTFKIT_{slug}_H\n#define PTFKIT_{slug}_H\n#include <ptfkit/detail/models.h>\n{c_stats}\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\nptfkit_model_status ptfkit_detail_{slug}_builtin(ptfkit_model **out);\n#ifdef __cplusplus\n}}\n#endif\nPTFKIT_MODEL_INLINE ptfkit_model_status ptfkit_{prefix}_builtin(ptfkit_model **out){{return ptfkit_detail_{slug}_builtin(out);}}\nPTFKIT_MODEL_INLINE void ptfkit_{prefix}_free(ptfkit_model *model){{ptfkit_detail_model_free(model);}}\n"
    );
    let mut cpp = format!(
        "module;\n#include <ptfkit/{slug}.h>\n#include <array>\n#include <span>\n#include <new>\n#include <utility>\nexport module ptfkit.{slug};\nexport import ptfkit.detail.neural;\nexport namespace ptfkit{{\n{cpp_stats}\nclass {class}{{\n::ptfkit_model *model_;\ninline explicit {class}(::ptfkit_model *model):model_(model){{}}\npublic:\ninline ~{class}(){{::ptfkit_{prefix}_free(model_);}}\n{class}(const {class}&)=delete;\n{class}& operator=(const {class}&)=delete;\ninline {class}({class}&& other) noexcept:model_(std::exchange(other.model_,nullptr)){{}}\ninline {class}& operator=({class}&& other) noexcept{{if(this!=&other){{::ptfkit_{prefix}_free(model_);model_=std::exchange(other.model_,nullptr);}}return *this;}}\nstatic inline {class} builtin(){{::ptfkit_model *model=nullptr;if(::ptfkit_{prefix}_builtin(&model)!=PTFKIT_MODEL_OK)throw std::bad_alloc();return {class}(model);}}\n"
    );
    let mut py_methods = String::new();
    let mut rs_contract = String::from("mod contract {use super::engine::{Network,statistics};\n");
    let mut c_switch = String::new();
    let mut input_switch = String::new();
    for (index, function) in &functions {
        let args = function.inputs.iter().map(|i| i.name()).collect::<Vec<_>>();
        let names = args.join(",");
        let count = args.len();
        let outputs = fields.iter().map(|f| f.name.clone()).collect::<Vec<_>>();
        let ir = entry.implementations[*index].as_ref().unwrap();
        c.push_str(
            &super::computation::render_function(ir, &outputs, *index, false)?.replace(
                "ptfkit_detail_dense_mod",
                &format!("ptfkit_detail_{slug}_mod"),
            ),
        );
        rs_contract.push_str(
            &super::computation::render_function(ir, &outputs, *index, true)?.replacen(
                "fn mod",
                "pub(super) fn mod",
                1,
            ),
        );
        let rs_args = args
            .iter()
            .map(|n| format!("{n}:f64"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(
            rs,
            "/// {}\npub fn {}(&self,{rs_args},estimate:Estimate)->Result<{result},ModelError>{{contract::mod{index}(&self.model.networks,self.model.data,estimate as usize,&[{names}]).map({result}::from_values).ok_or(ModelError::Input)}}",
            function.public_api.summary, function.name
        )?;
        let c_args = args
            .iter()
            .map(|n| format!("double {n}"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(
            c,
            "/* {} */\nPTFKIT_MODEL_INLINE ptfkit_model_status {}_estimate(const ptfkit_model *_ptfkit_model,{c_args},ptfkit_estimate _ptfkit_estimate,ptfkit_{prefix}_statistics *_ptfkit_out){{if(!_ptfkit_model||!_ptfkit_out)return PTFKIT_MODEL_INPUT;double _ptfkit_inputs[]={{{names}}},_ptfkit_values[{size}];int _ptfkit_ok=ptfkit_detail_{slug}_mod{index}(_ptfkit_model->detail_networks,_ptfkit_model->detail_data,(unsigned)_ptfkit_estimate,_ptfkit_inputs,{count},_ptfkit_values);",
            function.public_api.summary, function.name
        )?;
        for (i, f) in fields.iter().enumerate() {
            writeln!(c, "_ptfkit_out->{}=_ptfkit_values[{i}];", f.name)?;
        }
        c.push_str("return _ptfkit_ok?PTFKIT_MODEL_OK:PTFKIT_MODEL_INPUT;}\n");
        writeln!(
            c,
            "PTFKIT_MODEL_INLINE ptfkit_model_status {name}(const ptfkit_model *_ptfkit_model,{c_args},ptfkit_{prefix}_statistics *_ptfkit_out){{return {name}_estimate(_ptfkit_model,{names},PTFKIT_ESTIMATE_ARITHMETIC,_ptfkit_out);}}",
            name = function.name
        )?;
        let cpp_values = (0..size)
            .map(|i| format!("_ptfkit_values[{i}]"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(
            cpp,
            "inline {result} {}({c_args},Estimate estimate=Estimate::Arithmetic) const {{const double _ptfkit_inputs[]={{{names}}};double _ptfkit_values[{size}];if(!model_||!::ptfkit_detail_{slug}_mod{index}(model_->detail_networks,model_->detail_data,(unsigned)estimate,_ptfkit_inputs,{count},_ptfkit_values))throw ModelError();return {result}{{{cpp_values}}};}}",
            function.name
        )?;
        let py_args = args
            .iter()
            .map(|n| format!("{n}: ArrayLike"))
            .collect::<Vec<_>>()
            .join(", ");
        let scalar_args = args
            .iter()
            .map(|n| format!("{n}: float"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            py_methods,
            "    @overload\n    def {}(self, *, {scalar_args}, estimate: Estimate = Estimate.ARITHMETIC) -> {result}[float]: ...\n\n    @overload\n    def {}(self, *, {py_args}, estimate: Estimate = Estimate.ARITHMETIC, out: {result}[NDArray[floating]] | None = None) -> {result}[NDArray[floating]]: ...\n\n    def {}(self, *, {py_args}, estimate: Estimate = Estimate.ARITHMETIC, out: {result}[NDArray[floating]] | None = None) -> {result}[float] | {result}[NDArray[floating]]:\n        \"\"\"{}\"\"\"\n        return self._predict({index}, [{names}], estimate, out)\n",
            function.name, function.name, function.name, function.public_api.summary
        )?;
        writeln!(
            c_switch,
            "case {index}:return ptfkit_detail_{slug}_mod{index}(model->detail_networks,model->detail_data,mode,x,count,out)?PTFKIT_MODEL_OK:PTFKIT_MODEL_INPUT;"
        )?;
        writeln!(input_switch, "case {index}:return {count};")?;
    }
    rs.push_str("}\n");
    rs_contract.push_str("}\n");
    rs.push_str(&rs_contract);
    writeln!(
        c,
        "PTFKIT_MODEL_INLINE int ptfkit_detail_{slug}_inputs(unsigned function){{switch(function){{{input_switch}default:return 0;}}}}\nPTFKIT_MODEL_INLINE ptfkit_model_status ptfkit_detail_{slug}_predict(const ptfkit_model *model,unsigned function,unsigned mode,const double *x,size_t count,double *out){{if(!model)return PTFKIT_MODEL_INPUT;switch(function){{{c_switch}default:return PTFKIT_MODEL_INPUT;}}}}\n#endif"
    )?;
    cpp.push_str("};\n");
    for (alias, target) in &entry.spec.generation.result_aliases {
        writeln!(cpp, "using {alias} = {target};")?;
    }
    cpp.push_str("}\n");
    let replace = |s: &str| {
        s.replace("@SLUG@", slug)
            .replace("@CLASS@", class)
            .replace("@PREFIX@", &prefix)
            .replace("@RESULT@", result)
            .replace("@SIZE@", &size.to_string())
            .replace("@SUMMARY@", &entry.spec.source.summary)
    };
    for (alias, target) in &entry.spec.generation.result_aliases {
        writeln!(rs, "pub type {alias} = {target};")?;
        // Aliases retain established public result names; calculations still use the YAML record.
    }
    let mut py = replace(include_str!("dense.py.in"))
        .replace("@STATISTICS@", &py_stats)
        .replace("@METHODS@", &py_methods);
    for (alias, target) in &entry.spec.generation.result_aliases {
        writeln!(py, "\n{alias} = {target}")?;
    }
    let bridge = replace(include_str!("public_python.c.in"))
        .replace("@FUNCTIONS@", &replace(include_str!("dense_python.c.in")));
    rs.push_str(&super::verification::render(entry, class, &prefix, files)?);
    files.rust.push(file(format!("{slug}.rs"), RS_HEADER, rs));
    files.c.push(file(format!("ptfkit/{slug}.h"), C_HEADER, c));
    files.cpp.push(file(format!("{slug}.cppm"), C_HEADER, cpp));
    files
        .python
        .push(file(format!("ptfkit/{slug}.py"), PY_HEADER, py));
    files.python.push(file(format!("ptfkit/_{slug}.pyi"),PY_HEADER,"from collections.abc import Sequence\nModelInputError: type[ValueError]\ndef builtin() -> object: ...\ndef evaluate(handle: object, function: int, mode: int, inputs: Sequence[float]) -> tuple[float, ...]: ...\ndef batch(handle: object, function: int, mode: int, inputs: Sequence[object], outputs: Sequence[object]) -> None: ...\n"));
    files
        .extension
        .push(file(format!("src/ptfkit/_{slug}.c"), C_HEADER, bridge));
    let docs = format!(
        "<!-- @generated by ptfkit-codegen; DO NOT EDIT. -->\n\n# {class}\n\n{}\n\nInitialize the bundled model explicitly, then call its named calculation methods. Parameters are immutable and shared by instances. C named functions report arithmetic estimates; each `_estimate` variant also accepts `PTFKIT_ESTIMATE_LOG10` or `PTFKIT_ESTIMATE_GEOMETRIC`.\n\n{}",
        entry.spec.source.citation_apa,
        functions
            .iter()
            .map(|(_, f)| format!("## `{}`\n\n{}\n", f.name, f.public_api.summary))
            .collect::<Vec<_>>()
            .join("\n")
    );
    files
        .c_docs
        .push(file(format!("headers/{slug}.md"), "", &docs));
    files
        .cpp_docs
        .push(file(format!("modules/{slug}.md"), "", docs));
    Ok(())
}
