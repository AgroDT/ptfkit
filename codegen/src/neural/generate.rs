//! Render opt-in, unredistributed local verification targets from a validated model.
use super::{Model, engine::Scale};
use anyhow::{Context, Result};
use std::{fmt::Write as _, fs, path::Path};

const HEADER: &str = "/* @generated by ptfkit-codegen; LOCAL MODELS: DO NOT REDISTRIBUTE. */\n";

fn scales(scales: &[Scale]) -> String {
    let mut text = String::from("{");
    for scale in scales {
        let kind = match scale.kind.as_str() {
            "asis" => 0,
            "division" => 1,
            "logtr" => 2,
            "affine" => 3,
            "minmax" => 4,
            "linear" => 5,
            _ => unreachable!(),
        };
        let mut params = scale.params.clone();
        params.resize(3, 0.0);
        write!(
            text,
            "{{{kind},{{{:.17e},{:.17e},{:.17e}}}}},",
            params[0], params[1], params[2]
        )
        .unwrap();
    }
    text.push('}');
    text
}

pub(crate) fn run(model: &Path, directory: &Path) -> Result<()> {
    let model = Model::load(model)?;
    model.check_rosetta()?;
    // Never overwrite reviewed generated local artifacts or arbitrary directories.
    fs::create_dir(directory).context("creating new local neural output directory")?;
    let write = |name: &str, content: &str| fs::write(directory.join(name), content);
    write(
        "engine.h",
        &format!(
            "{HEADER}\n#ifndef PTFKIT_ROSETTA3_LOCAL_H\n#define PTFKIT_ROSETTA3_LOCAL_H\n#include <stddef.h>\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\nint ptfkit_calc_ptf_zhang2017(unsigned level, unsigned mode, const double *inputs, size_t count, double *out);\n#ifdef __cplusplus\n}}\n#endif\n#endif\n"
        ),
    )?;
    write(
        "runtime.c",
        &format!("{HEADER}{}", include_str!("runtime.c")),
    )?;
    write("python.c", &format!("{HEADER}{}", include_str!("python.c")))?;
    let mut metadata = format!("{HEADER}\nstatic const Network networks[5] = {{\n");
    for n in &model.networks {
        let widths = n
            .widths
            .iter()
            .map(usize::to_string)
            .collect::<Vec<_>>()
            .join(",");
        let acts = n
            .activations
            .iter()
            .map(|a| match a.as_str() {
                "linear" => "0",
                "sigmoid" => "1",
                "tansig" => "2",
                _ => "3",
            })
            .collect::<Vec<_>>()
            .join(",");
        writeln!(
            metadata,
            "{{{},{},{{{}}},{},{{{}}},{},{}}},",
            n.nboot,
            n.activations.len(),
            widths,
            n.offset,
            acts,
            scales(&n.inputs),
            scales(&n.outputs)
        )
        .unwrap();
    }
    metadata.push_str("};\n");
    write("metadata.h", &metadata)?;
    let mut weights = format!("{HEADER}\nconst double ptfkit_model_data[] = {{\n");
    for chunk in model.data.chunks(8) {
        for value in chunk {
            write!(weights, "{value:.17e},").unwrap();
        }
        weights.push('\n');
    }
    weights.push_str("};\n");
    write("weights.c", &weights)?;
    write(
        "ptfkit.cppm",
        &format!(
            "{HEADER}\nmodule;\n#include \"engine.h\"\nexport module ptfkit.rosetta3;\nexport using ::ptfkit_calc_ptf_zhang2017;\n"
        ),
    )?;
    write(
        "runner.c",
        &format!(
            "{HEADER}\n{}",
            r#"
#include "engine.h"
#include <stdio.h>
#include <stdlib.h>
int main(int argc, char **argv) {
    if (argc < 6 || argc > 9) return 2;
    double x[6], out[14];
    for (int i = 3; i < argc; ++i) x[i-3] = strtod(argv[i], NULL);
    if (!ptfkit_calc_ptf_zhang2017((unsigned)strtoul(argv[1], NULL, 10), (unsigned)strtoul(argv[2], NULL, 10), x, (size_t)argc-3, out)) return 3;
    for (size_t i = 0; i < 14; ++i) printf("%.17g\n", out[i]);
    return 0;
}
"#
        ),
    )?;
    let cpp_runner = fs::read_to_string(directory.join("runner.c"))?
        .replace("#include \"engine.h\"", "import ptfkit.rosetta3;");
    write("runner.cpp", &cpp_runner)?;
    write(
        "CMakeLists.txt",
        r#"cmake_minimum_required(VERSION 3.28)
project(ptfkit_rosetta3_local LANGUAGES C CXX)
find_package(Python REQUIRED COMPONENTS Interpreter Development.Module)
add_library(model STATIC weights.c runtime.c)
set_target_properties(model PROPERTIES POSITION_INDEPENDENT_CODE ON C_STANDARD 11 C_STANDARD_REQUIRED ON)
if(UNIX)
  target_link_libraries(model PUBLIC m)
endif()
add_executable(rosetta_c runner.c)
target_link_libraries(rosetta_c PRIVATE model)
set_target_properties(rosetta_c PROPERTIES C_STANDARD 11 C_STANDARD_REQUIRED ON)
add_library(cpp_module STATIC)
target_sources(cpp_module PUBLIC FILE_SET CXX_MODULES FILES ptfkit.cppm)
target_compile_features(cpp_module PUBLIC cxx_std_23)
target_link_libraries(cpp_module PUBLIC model)
add_executable(rosetta_cpp runner.cpp)
target_link_libraries(rosetta_cpp PRIVATE cpp_module)
Python_add_library(_rosetta3_local MODULE WITH_SOABI python.c)
target_link_libraries(_rosetta3_local PRIVATE model)
"#,
    )?;
    const RUST_HEADER: &str =
        "// @generated by ptfkit-codegen; LOCAL MODELS: DO NOT REDISTRIBUTE.\n";
    write(
        "engine.rs",
        &format!("{RUST_HEADER}{}", include_str!("engine.rs")),
    )?;
    write(
        "rosetta.rs",
        &format!("{RUST_HEADER}{}", include_str!("rosetta.rs")),
    )?;
    let mut rust = String::from(
        "mod engine;\nmod rosetta;\nuse engine::{Network, Scale};\nfn networks() -> Vec<Network> { vec![\n",
    );
    rust.insert_str(0, RUST_HEADER);
    for n in &model.networks {
        let scaler = |values: &[Scale]| {
            values
                .iter()
                .map(|s| {
                    format!(
                        "Scale {{ kind: {:?}.into(), params: vec!{:?} }}",
                        s.kind, s.params
                    )
                })
                .collect::<Vec<_>>()
                .join(",")
        };
        let acts = n
            .activations
            .iter()
            .map(|a| format!("{a:?}.into()"))
            .collect::<Vec<_>>()
            .join(",");
        writeln!(rust, "Network {{ nboot: {}, widths: vec!{:?}, activations: vec![{}], inputs: vec![{}], outputs: vec![{}], offset: {} }},",n.nboot,n.widths,acts,scaler(&n.inputs),scaler(&n.outputs),n.offset).unwrap();
    }
    rust.push_str("] }\n");
    rust.push_str(r#"
fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.len() < 5 { std::process::exit(2); }
    let level = args[0].parse().unwrap();
    let mode = args[1].parse().unwrap();
    let input: Vec<f64> = args[2..].iter().map(|x| x.parse().unwrap()).collect();
    let data: Vec<f64> = include_bytes!("models.bin").chunks_exact(8).map(|b| f64::from_le_bytes(b.try_into().unwrap())).collect();
    let Some(values) = rosetta::predict(&networks(), &data, level, mode, &input) else { std::process::exit(3); };
    for value in values { println!("{value:.17e}"); }
}
"#);
    write("runner.rs", &rust)?;
    let bytes: Vec<u8> = model.data.iter().flat_map(|v| v.to_le_bytes()).collect();
    fs::write(directory.join("models.bin"), bytes)?;
    println!(
        "Generated local Rust, C11, C++23 and CPython targets in {}",
        directory.display()
    );
    Ok(())
}
