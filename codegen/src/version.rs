use std::{fs, path::Path};

use anyhow::{Context, Result, bail};

const RUST_MANIFEST: &str = "targets/ptfkit-rs/Cargo.toml";
const PYTHON_VERSION: &str = "targets/ptfkit-py/src/ptfkit/_version.py";
const NATIVE_VERSION: &str = "targets/ptfkit-native/cmake/ptfkitVersion.cmake";

pub(crate) fn run(root: &Path, version: &str) -> Result<()> {
    validate(version)?;
    update_rust_manifest(root, version)?;
    fs::write(
        root.join(PYTHON_VERSION),
        format!("# @generated by ptfkit-codegen; do not edit.\n__version__ = '{version}'\n"),
    )
    .with_context(|| format!("writing {PYTHON_VERSION}"))?;
    fs::write(
        root.join(NATIVE_VERSION),
        format!(
            "# @generated by ptfkit-codegen; do not edit.\nset(PTFKIT_VERSION \"{version}\")\n"
        ),
    )
    .with_context(|| format!("writing {NATIVE_VERSION}"))?;
    Ok(())
}

fn validate(version: &str) -> Result<()> {
    if version.is_empty()
        || !version
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'-' | b'+'))
    {
        bail!("invalid version: {version}")
    }
    Ok(())
}

fn update_rust_manifest(root: &Path, version: &str) -> Result<()> {
    let path = root.join(RUST_MANIFEST);
    let manifest = fs::read_to_string(&path).with_context(|| format!("reading {RUST_MANIFEST}"))?;
    let mut output = String::with_capacity(manifest.len());
    let mut in_package = false;
    let mut updated = false;

    for line in manifest.lines() {
        if line.starts_with('[') {
            in_package = line == "[package]";
        }

        if in_package && line.starts_with("version = ") {
            output.push_str(&format!("version = \"{version}\"\n"));
            updated = true;
        } else {
            output.push_str(line);
            output.push('\n');
        }
    }

    if !updated {
        bail!("missing package version in {RUST_MANIFEST}")
    }

    fs::write(path, output).with_context(|| format!("writing {RUST_MANIFEST}"))?;
    Ok(())
}
