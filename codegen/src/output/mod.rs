pub(crate) struct Output {
    pub(super) layout: &'static Layout,
    pub(super) files: Vec<GeneratedFile>,
}

impl Output {
    pub(crate) fn new(layout: &'static Layout, files: Vec<GeneratedFile>) -> Self {
        Self { layout, files }
    }
}

pub(crate) struct GeneratedFile {
    pub(crate) path: PathBuf,
    pub(crate) contents: String,
}

impl GeneratedFile {
    pub(crate) fn new(path: PathBuf, contents: String) -> Self {
        Self { path, contents }
    }
}
