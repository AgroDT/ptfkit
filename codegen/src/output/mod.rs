//! Generated-artifact layout, formatting, and atomic filesystem commit.

mod write;

use std::path::PathBuf;

pub(crate) use write::{assert_unchanged, commit, snapshot_generated};

#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) enum Formatter {
    None,
    Rust,
    Python,
    C,
    Cpp,
}

pub(crate) struct Layout {
    pub(super) output_directory: &'static str,
    pub(super) cleanup_directory: &'static str,
    pub(super) generated_header: &'static str,
    pub(super) formatter: Formatter,
}

macro_rules! layout {
    ($name:ident, $output:literal, $cleanup:literal, $header:expr, $formatter:expr) => {
        pub(crate) static $name: Layout = Layout {
            output_directory: $output,
            cleanup_directory: $cleanup,
            generated_header: $header,
            formatter: $formatter,
        };
    };
}

