def test_invalid_output_sets_are_rejected_as_a_whole(names: list[str]):
    document = _evaluation()
    document['candidates'][0]['prediction']['names'] = names
    with pytest.raises(PlanValidationError):
        load_evaluation_plan(document)


def test_duplicate_pressures_after_conversion_are_rejected_at_loading_and_execution():
    manifest = json.loads(canonical_json(get_manifest()))
    function = next(
        item for item in manifest['functions'] if item['id'] == 'calc_ptf_beniaich2023_slr1'
    )
    for output in function['outputs']:
        if output['name'] == 'water_field_capacity':
            output['measurement']['conditions'][0].update(value=9.80665, unit='kilopascal')
        elif output['name'] == 'water_wilting_point':
            output['measurement']['conditions'][0].update(value=100, unit='centimeter_water_head')
    with pytest.raises(PlanValidationError) as caught:
        load_evaluation_plan(_evaluation(), manifest=manifest)
    assert 'points.duplicate_pressure' in {item.code for item in caught.value.diagnostics}
    candidate = load_evaluation_plan(_evaluation()).candidates[0]
    assert isinstance(candidate, FunctionCurveCandidate)
    unsafe = replace(
        candidate,
        curve=replace(
            candidate.curve,
            prediction=FixedPointsPrediction(
                (
                    FixedPointPrediction('water_field_capacity', 9.80665, 'kilopascal', None),
                    FixedPointPrediction('water_wilting_point', 100, 'centimeter_water_head', None),
                )
            ),
        ),
    )
    with pytest.raises(CurveExecutionError, match='distinct'):
        evaluate_candidate(unsafe, [9.80665], {'clay': 20})


def test_every_output_method_is_checked_against_the_run_protocol():
    manifest = json.loads(canonical_json(get_manifest()))
    function = next(
        item for item in manifest['functions'] if item['id'] == 'calc_ptf_beniaich2023_slr1'
    )
    for output in function['outputs']:
        if output['name'] == 'water_wilting_point':
            output['measurement']['method'] = 'another_method'
    with pytest.raises(EvaluationDocumentError, match='observation method'):
        load_retention_run_plan(EXAMPLE, manifest=manifest)


def test_grouped_native_selection_fits_the_two_output_ensemble_and_replays(tmp_path: Path):
    plan = load_retention_run_plan(EXAMPLE)
    result = execute_retention_run(plan)
    assert len(result.points) == 24
    assert all(point.eligible for point in result.points)
    learned = result.learned_selection
    assert learned is not None
    assert learned.status == 'computed'
    assert len(learned.folds) == 3
    for fold in learned.folds:
        assert fold.atomic.candidate_id == 'slr3'
        assert fold.atomic.assessment is not None
        assert fold.atomic.assessment.mean_loss == pytest.approx((0.0022575**2 + 0.00364**2) / 2)
        assert fold.ensemble.candidate_id == 'pair'
        assert isinstance(fold.ensemble.outer_fit, ConvexPairFit)
        assert fold.ensemble.outer_fit.left_weight == pytest.approx(0.25)
        assert fold.ensemble.assessment is not None
        assert fold.ensemble.assessment.mean_loss == pytest.approx(0, abs=1e-28)
        assert {point.suction_kpa for point in fold.ensemble.predictions} == {33, 1500}
        assert all(
            point.water_quantity == 'gravimetric_water_content'
            for point in fold.ensemble.predictions
        )
    first = write_retention_run(result, tmp_path / 'first')
    second = write_retention_run(execute_retention_run(plan), tmp_path / 'second')
    assert {path.name for path in first.iterdir()} == {path.name for path in second.iterdir()}
    assert all(path.read_bytes() == (second / path.name).read_bytes() for path in first.iterdir())


def test_outer_targets_cannot_change_inner_choices_or_training_weights(tmp_path: Path):
    baseline = execute_retention_run(load_retention_run_plan(EXAMPLE)).learned_selection
    assert baseline is not None
    held_out = {group[1] for group in baseline.splits.folds[0].test_groups}
    path = _fixture(tmp_path / 'changed')
    document = json.loads((path.parent / 'dataset.json').read_bytes())
    for observation in document['observations']:
        if observation['sample_id'] in held_out:
            # Outer targets favor SLR1 exactly, against the training-only SLR3 choice.
            observation['value'] = {33: 0.17577, 1500: 0.09621}[observation['suction_kpa']]
    _rewrite_dataset(path, document)
    changed = execute_retention_run(load_retention_run_plan(path)).learned_selection
    assert changed is not None
    before, after = baseline.folds[0], changed.folds[0]
    assert before.ensemble.outer_fit == after.ensemble.outer_fit
    assert before.ensemble.inner_scores == after.ensemble.inner_scores
    assert before.atomic.inner_scores == after.atomic.inner_scores
    assert after.atomic.candidate_id == before.atomic.candidate_id == 'slr3'
    assert after.atomic.assessment is not None
    assert after.atomic.assessment.mean_loss == pytest.approx((0.00903**2 + 0.01456**2) / 2)
    assert after.ensemble.assessment is not None
    assert after.ensemble.assessment.mean_loss is not None
    assert after.ensemble.assessment.mean_loss == pytest.approx((0.0067725**2 + 0.01092**2) / 2)


def test_unsupported_native_observation_is_retained_as_an_explicit_exclusion(tmp_path: Path):
    path = _fixture(tmp_path / 'unsupported')
    document = json.loads((path.parent / 'dataset.json').read_bytes())
    document['observations'].append(
        {**document['observations'][0], 'id': 'unsupported', 'suction_kpa': 100, 'value': 0.15}
    )
    _rewrite_dataset(path, document)
    run = json.loads(path.read_bytes())
    del run['selection']
    del run['learned_selection']
    path.write_bytes(canonical_json(run))
    result = execute_retention_run(load_retention_run_plan(path))
    excluded = [point for point in result.points if point.observation_id == 'unsupported']
    assert len(excluded) == 2
    assert all(point.reasons == ('pressure_condition_mismatch',) for point in excluded)


def test_target_free_forecasts_preserve_the_registered_finite_support():
    plan = load_retention_run_plan(EXAMPLE)
    predictions = predict_retention_grid(
        plan,
        candidate_id='slr1',
        sample_keys=(('synthetic', 'soil_0'),),
        pressure_grid_kpa=(33, 100, 1500),
    )
    assert [point.suction_kpa for point in predictions] == [33, 100, 1500]
    assert predictions[0].predicted == pytest.approx(0.17577)
    assert predictions[2].predicted == pytest.approx(0.09621)
    assert predictions[1].predicted is None
    assert predictions[1].reasons == ('pressure_condition_mismatch',)
    assert predictions[1].execution_error is None
